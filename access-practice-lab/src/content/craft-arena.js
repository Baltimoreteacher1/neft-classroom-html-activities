const unpack = ([id, band, title, titleEs, q, qEs, yes, yesEs, no, noEs, cards, objY, objN]) => ({
  id,
  band,
  title: { en: title, es: titleEs },
  question: { en: q, es: qEs },
  stance: { y: { en: yes, es: yesEs }, n: { en: no, es: noEs } },
  cards: cards.map(([side, source, text], i) => ({ id: `${id}-${i + 1}`, side, source, text })),
  objection: { y: objY, n: objN },
});

/** Every topic. objection.y is what the NO side says to a YES argument; objection.n is what the YES side says to a NO argument. */
export const TOPICS = ROWS.map(unpack);
export const topicsFor = (band) => TOPICS.filter((t) => t.band === band);
export const findTopic = (id) => TOPICS.find((t) => t.id === id) || null;

