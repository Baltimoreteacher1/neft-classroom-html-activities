const slot = (id, role, label) => ({ id, role, label });
const BASE5 = (expansion) => [
  slot("subject", "subject", "Who or what"),
  slot("action", "action", "What it is or does"),
  slot("connector", "connector", "Connector"),
  slot("expansion", "expansion", expansion),
];
