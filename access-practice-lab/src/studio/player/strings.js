/** A translator for "en" or "es" over the built-in table plus any host overrides (Spanish falls back to English). */
export function makeTranslator(lang, override = {}) {
  const missing = new Set();
  const table =
    lang === "es"
      ? { ...STRINGS.en, ...STRINGS.es, ...(override.es || {}) }
      : { ...STRINGS.en, ...(override.en || {}) };
  const t = (key, vars) => {
    const raw = table[key];
    if (raw === undefined) {
      missing.add(key);
      return key;
    }
    return vars
      ? raw.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? `{${k}}` : String(vars[k])))
      : raw;
  };
  return { t, missing };
}
