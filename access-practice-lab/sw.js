const SCOPE = "/access-practice-lab/";
const SHELL = `${SCOPE}app-shell`;
const PREFIX = "ewl-access-";
const CACHE = `${PREFIX}${BUILD_HASH}`;
const FRESH_MS = 3500;
// Modules outside the lab folder that src/main.js imports statically: without them the lab cannot start offline.
const OUTSIDE_MODULES = [
  "/shared/math-language-bridge/v1.js",
  "/shared/math-language-bridge/v2.js",
  "/shared/class-platform/contract.js",
  "/shared/class-platform/client.js",
  "/shared/class-platform/book-merge.js",
  "/shared/class-platform/social.js",
  "/shared/qr/qr-code.mjs",
];
// Shared chrome the lab loads from outside its own folder; worth having offline so the page is not unstyled.
const OUTSIDE = [
  /^\/assets\/mobile-access\.css$/,
  /^\/shared\/save-resume\//,
  /^\/shared\/(?:class-platform|qr)\/[\w-]+\.m?js$/,
  /^\/family-app\/home-link\.js$/,
  /^\/shared\/math-language-bridge\/v\d+\.js$/,
  /^\/assets\/fonts\/(?:atkinson-hyperlegible|fraunces)-[0-9a-f]+\.woff2$/,
];

/** How a request is served: "shell" | "immutable" | "fresh" | "network". Pure, so it can be tested. */
function route(request, url, origin) {
  if (request.method !== "GET" || url.origin !== origin) return "network";
  if (request.headers.get("range")) return "network";
  const path = url.pathname;
  if (path.startsWith("/api/")) return "network";
  if (path === `${SCOPE}config.json` || path === `${SCOPE}sw.js`) return "network";
  const inScope = path.startsWith(SCOPE);
  if (request.mode === "navigate")
    return inScope &&
      !path.startsWith(`${SCOPE}printables/`) &&
      !path.startsWith(`${SCOPE}family-tour/`) &&
      path !== `${SCOPE}family-tour` &&
      !path.startsWith(`${SCOPE}arcade/`) &&
      path !== `${SCOPE}arcade` &&
      !path.startsWith(`${SCOPE}videos/`) &&
      path !== `${SCOPE}videos` &&
      !/\.[a-z0-9]+$/i.test(path)
      ? "shell"
      : "network";
  if (inScope) return url.searchParams.has("v") && /\.(js|css)$/.test(path) ? "immutable" : "fresh";
  return OUTSIDE.some((re) => re.test(path)) ? "fresh" : "network";
}

const isHtml = (response) => /text\/html/i.test(response.headers.get("content-type") || "");

// The copy is taken before this returns: once the page starts reading the response its body cannot be cloned.
function put(cacheName, key, response) {
  if (!response || !response.ok) return Promise.resolve();
  const copy = response.clone();
  return caches
    .open(cacheName)
    .then((cache) => cache.put(key, copy))
    .catch(() => {
      /* storage full or blocked: the network copy still works */
    });
}

function withTimeout(promise, ms, fallback) {
  return Promise.race([
    promise,
    new Promise((resolve) => setTimeout(() => resolve(fallback()), ms)),
  ]);
}

async function shellResponse(request) {
  const network = fetch(request).then((response) => {
    if (response.ok && isHtml(response)) put(CACHE, SHELL, response);
    return response;
  });
  const saved = await caches.match(SHELL);
  if (!saved) return network;
  return withTimeout(
    network.then((r) => (r.status >= 500 ? saved : r)).catch(() => saved),
    FRESH_MS,
    () => saved,
  );
}

async function immutableResponse(request) {
  const saved = await caches.match(request);
  if (saved) return saved;
  const response = await fetch(request);
  put(CACHE, request, response);
  return response;
}

// This build's copy first; an offline week pack (older, possibly) only when the build has none.
async function savedCopy(request) {
  const own = await caches
    .open(CACHE)
    .then((cache) => cache.match(request))
    .catch(() => undefined);
  return own || caches.match(request);
}

async function freshResponse(request) {
  const network = fetch(request).then((response) => {
    put(CACHE, request, response);
    return response;
  });
  const saved = await savedCopy(request);
  if (!saved) return network;
  return withTimeout(
    network.then((r) => (r.status >= 500 ? saved : r)).catch(() => saved),
    FRESH_MS,
    () => saved,
  );
}

async function precache() {
  const cache = await caches.open(CACHE);
  // Required: the shell, critical styles and the entry module's static chain. Route modules are deliberately kept
  // off the install path so a first visit is not competing with the entire lab download.
  await cache.put(SHELL, await fetchOk(new Request(SHELL, { cache: "reload" })));
  await Promise.all(
    PRECACHE_CORE.map(async (url) => cache.put(url, await fetchOk(new Request(url)))),
  );
}

async function warmOffline() {
  const cache = await caches.open(CACHE);
  // Best effort after first paint: route modules, secondary styles, content and pictures. A miss is filled by use.
  const more = [...OUTSIDE_MODULES, ...PRECACHE_MORE];
  for (let i = 0; i < more.length; i += 8)
    await Promise.all(
      more.slice(i, i + 8).map(async (url) => {
        try {
          await cache.put(url, await fetchOk(new Request(url, { cache: "reload" })));
        } catch {
          /* skip */
        }
      }),
    );
}

async function fetchOk(request) {
  const response = await fetch(request);
  if (!response.ok) throw new Error(`${response.status} ${request.url}`);
  return response;
}

async function dropOldCaches() {
  const keys = (await caches.keys()).filter((key) => key.startsWith(PREFIX) && key !== CACHE);
  // Keep the newest previous build for tabs opened before this deploy; caches.keys() is in creation order.
  const stale = keys.slice(0, Math.max(0, keys.length - 1));
  await Promise.all(stale.map((key) => caches.delete(key)));
}

// ── Offline week packs (src/offline-pack.js) ────────────────────────────────────
// A page sends {type: "cache-urls", name, urls} with a MessagePort. Same-origin URLs inside the lab are saved into
// their own cache, "ewl-offline-<name>", which dropOldCaches never clears (it only clears "ewl-access-" builds).
// Pages (navigations) are not fetched: the shell answers them, so the worker only checks it has the shell and the
// lab's modules. Everything else (cross-origin, outside the lab, /api/, this file, config.json) is refused.
const PACK_PREFIX = "ewl-offline-";
const PACK_MAX = 400;
const PACK_NAME = /^[a-z0-9-]{1,60}$/;
const PACK_MANIFEST = `${SCOPE}__offline-pack.json`;

/** Pure: split a requested list into pages, files and refused entries. */
function packPlan(urls, origin) {
  const pages = [];
  const files = [];
  const refused = [];
  const seen = new Set();
  for (const raw of Array.isArray(urls) ? urls.slice(0, PACK_MAX) : []) {
    let url;
    try {
      url = new URL(String(raw), origin);
    } catch {
      refused.push(String(raw));
      continue;
    }
    const path = url.pathname;
    if (
      url.origin !== origin ||
      !/^https?:$/.test(url.protocol) ||
      !path.startsWith(SCOPE) ||
      path.includes("..") ||
      path === `${SCOPE}sw.js` ||
      path === `${SCOPE}config.json` ||
      path === PACK_MANIFEST
    ) {
      refused.push(String(raw));
      continue;
    }
    if (seen.has(url.href)) continue;
    seen.add(url.href);
    (/\.[a-z0-9]+$/i.test(path) ? files : pages).push(url.href);
  }
  return { pages, files, refused };
}

/** The lab's own modules and styles (not content) that this build has not saved yet: needed to open a page offline. */
async function ensureAppCode() {
  const cache = await caches.open(CACHE);
  if (!(await cache.match(SHELL)))
    await cache.put(SHELL, await fetchOk(new Request(SHELL, { cache: "reload" })));
  const code = [
    ...OUTSIDE_MODULES,
    ...[...PRECACHE_CORE, ...PRECACHE_MORE].filter((u) => /\.(js|css)\?v=/.test(u)),
  ];
  for (let i = 0; i < code.length; i += 8)
    await Promise.all(
      code.slice(i, i + 8).map(async (url) => {
        if (await cache.match(url)) return;
        try {
          await cache.put(url, await fetchOk(new Request(url)));
        } catch {
          /* best effort: a module the learner never opens is not needed */
        }
      }),
    );
}

async function cachePack(data, report = () => {}) {
  const name = String(data?.name || "");
  if (!PACK_NAME.test(name)) throw new Error("bad pack name");
  const origin = self.location.origin;
  const { pages, files, refused } = packPlan(data.urls, origin);
  await ensureAppCode();
  const cache = await caches.open(PACK_PREFIX + name);
  let done = 0;
  let bytes = 0;
  let failed = 0;
  report({ done, total: files.length, bytes });
  for (let i = 0; i < files.length; i += 4)
    await Promise.all(
      files.slice(i, i + 4).map(async (url) => {
        try {
          const response = await fetchOk(new Request(url, { cache: "reload" }));
          bytes += (await response.clone().blob()).size;
          await cache.put(url, response);
        } catch {
          failed += 1;
        }
        done += 1;
        report({ done, total: files.length, bytes });
      }),
    );
  const summary = {
    name,
    saved: files.length - failed,
    failed,
    refused: refused.length,
    pages: pages.length,
    bytes,
    at: new Date().toISOString(),
  };
  await cache.put(
    PACK_MANIFEST,
    new Response(JSON.stringify(summary), { headers: { "content-type": "application/json" } }),
  );
  return summary;
}

if (typeof self !== "undefined" && typeof self.addEventListener === "function") {
  self.addEventListener("install", (event) => {
    event.waitUntil(precache().then(() => self.skipWaiting()));
  });
  self.addEventListener("activate", (event) => {
    event.waitUntil(dropOldCaches().then(() => self.clients.claim()));
  });
  self.addEventListener("message", (event) => {
    if (event.data?.type === "prepare-offline") event.waitUntil(warmOffline());
    if (event.data?.type === "cache-urls") {
      const port = event.ports?.[0] || event.source;
      const reply = (msg) => port?.postMessage?.(msg);
      event.waitUntil(
        cachePack(event.data, (p) => reply({ type: "cache-progress", ...p }))
          .then((summary) => reply({ type: "cache-done", ...summary }))
          .catch((error) =>
            reply({ type: "cache-error", message: String(error?.message || error) }),
          ),
      );
    }
  });
  self.addEventListener("fetch", (event) => {
    const kind = route(event.request, new URL(event.request.url), self.location.origin);
    if (kind === "network") return;
    event.respondWith(
      kind === "shell"
        ? shellResponse(event.request)
        : kind === "immutable"
          ? immutableResponse(event.request)
          : freshResponse(event.request),
    );
  });
}

