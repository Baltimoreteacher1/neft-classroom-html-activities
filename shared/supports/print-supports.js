/*
 * print-supports.js — the paper surface of the lesson adaptation layer.
 *
 * A teacher who configures supports before class should not have to rebuild
 * them by hand in the printed packet. This script runs on the GENERATED print
 * pages (printable / worksheet / handout / guided notes) and renders the same
 * effective support configuration the interactive lesson renders.
 *
 * ONE SOURCE OF TRUTH. It computes nothing. `resolveEffectiveSupports` and
 * `supportBlocks` in shared/supports/lesson-supports.js decide what is on and
 * what each support contributes; this file only draws it for paper. That is
 * deliberate and load-bearing: the moment print works out "what is on" for
 * itself, the worksheet in a student's hand can disagree with the lesson the
 * teacher just taught, and nobody finds out until the middle of a class.
 *
 * WHY RUNTIME. These pages are regenerated by their generators on every build,
 * from lesson config alone. A teacher's support selection is a runtime choice
 * on their own device and cannot exist at build time, so the support layer has
 * to attach when the page opens — exactly as it does in the lesson.
 *
 * AUDIENCE. `data-support-audience="teacher"` pages get the provenance summary
 * and the delivery notes for supports paper cannot carry. Student pages get the
 * supports themselves and NOTHING about why anyone might need them — a packet
 * travels around a building.
 *
 * FALLBACK. Every failure path ends in "print the canonical page". A missing
 * manifest, an unreadable store, an absent module: the page is exactly what its
 * generator wrote.
 */
(function () {
  "use strict";
  if (window.EWLPrintSupports) return;

  var LESSON_ID = document.documentElement.getAttribute("data-ewl-supports-lesson") || "";
  var AUDIENCE =
    document.documentElement.getAttribute("data-support-audience") === "teacher"
      ? "teacher"
      : "student";
  var MODULE_URL = "/shared/supports/lesson-supports.js";
  var MANIFEST_URL = "/assets/learning-supports/manifest.json";

  function el(tag, className, text) {
    var n = document.createElement(tag);
    if (className) n.className = className;
    if (text != null) n.textContent = text;
    return n;
  }

  /* -- styles ------------------------------------------------------------
   * Injected rather than shipped in every generator's <style> block, so the
   * print surfaces cannot drift apart. Print-safe: no colour dependence, no
   * background fills that eat toner, page-break-inside avoided on each block. */
  var CSS = [
    ".ewl-ps{border:1.5px solid #444;border-radius:6px;padding:8px 12px;margin:10px 0;page-break-inside:avoid;}",
    ".ewl-ps h3{font-size:11.5pt;margin:0 0 4px;border:0;padding:0;}",
    ".ewl-ps ul,.ewl-ps ol{margin:4px 0 0;padding-left:20px;}",
    ".ewl-ps li{margin:2px 0;}",
    ".ewl-ps-chips{list-style:none;padding:0;display:flex;flex-wrap:wrap;gap:4px 10px;}",
    ".ewl-ps-chips li{border:1px solid #777;border-radius:10px;padding:1px 8px;font-size:10.5pt;}",
    ".ewl-ps-check{list-style:none;padding:0;}",
    ".ewl-ps-check li::before{content:'\\2610';margin-right:6px;}",
    ".ewl-ps-frame{border-bottom:1px solid #999;display:block;margin:6px 0 2px;min-height:1.4em;}",
    ".ewl-ps-def{margin:3px 0;}",
    ".ewl-ps-def b{font-weight:700;}",
    ".ewl-ps-space{border:1px dashed #888;border-radius:6px;height:150px;margin-top:6px;}",
    ".ewl-ps-nl{width:100%;height:56px;}",
    ".ewl-ps-grid{border-collapse:collapse;font-size:9pt;}",
    ".ewl-ps-grid td,.ewl-ps-grid th{border:1px solid #888;padding:1px 4px;text-align:center;min-width:20px;}",
    ".ewl-ps-prov{border:1.5px solid #444;border-radius:6px;padding:8px 12px;margin:10px 0;font-size:10.5pt;page-break-inside:avoid;}",
    ".ewl-ps-prov h3{font-size:11pt;margin:0 0 4px;border:0;padding:0;}",
    ".ewl-ps-mod{border-width:2px;}",
    ".ewl-ps-optional{opacity:0.72;}",
    ".ewl-ps-optional-tag{font-size:9.5pt;font-style:italic;display:block;}",
  ].join("\n");

  function ensureStyles() {
    if (document.getElementById("ewl-print-supports-css")) return;
    var s = document.createElement("style");
    s.id = "ewl-print-supports-css";
    s.textContent = CSS;
    document.head.appendChild(s);
  }

  /* -- drawing one block -------------------------------------------------- */
  function drawBlock(block) {
    var box = el("section", "ewl-ps");
    box.setAttribute("data-support-key", block.key);
    box.appendChild(el("h3", null, block.title));

    if (block.kind === "definitions") {
      block.items.forEach(function (v) {
        var p = el("p", "ewl-ps-def");
        p.appendChild(el("b", null, v.term + " — "));
        p.appendChild(document.createTextNode(v.definition));
        if (v.visual) p.appendChild(el("em", null, " " + v.visual));
        box.appendChild(p);
      });
    } else if (block.kind === "chips") {
      var chips = el("ul", "ewl-ps-chips");
      block.items.forEach(function (w) {
        chips.appendChild(el("li", null, w));
      });
      box.appendChild(chips);
    } else if (block.kind === "lines") {
      block.items.forEach(function (line) {
        box.appendChild(el("p", null, line));
      });
    } else if (block.kind === "steps") {
      var ol = el("ol");
      block.items.forEach(function (s) {
        ol.appendChild(el("li", null, s));
      });
      box.appendChild(ol);
    } else if (block.kind === "checkboxes") {
      var ul = el("ul", "ewl-ps-check");
      block.items.forEach(function (s) {
        ul.appendChild(el("li", null, s));
      });
      box.appendChild(ul);
    } else if (block.kind === "model-space") {
      block.items.forEach(function (s) {
        box.appendChild(el("p", null, s));
      });
      box.appendChild(el("div", "ewl-ps-space"));
    } else if (block.kind === "number-line") {
      box.appendChild(numberLineSvg());
    } else if (block.kind === "mult-chart") {
      box.appendChild(grid(12));
    } else if (block.kind === "place-value") {
      box.appendChild(placeValueTable());
    }

    // A sentence frame on paper needs a line to write on; the frame alone is a
    // prompt with nowhere to answer it.
    if (block.key === "sentence-frames") {
      block.items.forEach(function () {
        box.appendChild(el("span", "ewl-ps-frame"));
      });
    }
    return box;
  }

  function numberLineSvg() {
    var NS = "http://www.w3.org/2000/svg";
    var svg = document.createElementNS(NS, "svg");
    svg.setAttribute("class", "ewl-ps-nl");
    svg.setAttribute("viewBox", "0 0 620 56");
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", "Blank number line from negative ten to ten");
    var axis = document.createElementNS(NS, "line");
    axis.setAttribute("x1", "10");
    axis.setAttribute("y1", "24");
    axis.setAttribute("x2", "610");
    axis.setAttribute("y2", "24");
    axis.setAttribute("stroke", "#333");
    axis.setAttribute("stroke-width", "1.5");
    svg.appendChild(axis);
    for (var i = 0; i <= 20; i++) {
      var x = 10 + i * 30;
      var tick = document.createElementNS(NS, "line");
      tick.setAttribute("x1", x);
      tick.setAttribute("y1", "18");
      tick.setAttribute("x2", x);
      tick.setAttribute("y2", "30");
      tick.setAttribute("stroke", "#333");
      svg.appendChild(tick);
      var t = document.createElementNS(NS, "text");
      t.setAttribute("x", x);
      t.setAttribute("y", "45");
      t.setAttribute("text-anchor", "middle");
      t.setAttribute("font-size", "9");
      t.textContent = String(i - 10);
      svg.appendChild(t);
    }
    return svg;
  }

  function grid(n) {
    var table = el("table", "ewl-ps-grid");
    for (var r = 0; r <= n; r++) {
      var tr = el("tr");
      for (var c = 0; c <= n; c++) {
        var cell = el(r === 0 || c === 0 ? "th" : "td");
        if (r === 0 && c === 0) cell.textContent = "×";
        else if (r === 0) cell.textContent = String(c);
        else if (c === 0) cell.textContent = String(r);
        else cell.textContent = String(r * c);
        tr.appendChild(cell);
      }
      table.appendChild(tr);
    }
    return table;
  }

  function placeValueTable() {
    var heads = ["Thousands", "Hundreds", "Tens", "Ones", ".", "Tenths", "Hundredths"];
    var table = el("table", "ewl-ps-grid");
    var hr = el("tr");
    heads.forEach(function (h) {
      var th = el("th", null, h);
      hr.appendChild(th);
    });
    table.appendChild(hr);
    for (var r = 0; r < 3; r++) {
      var tr = el("tr");
      heads.forEach(function () {
        var td = el("td");
        td.innerHTML = "&nbsp;";
        tr.appendChild(td);
      });
      table.appendChild(tr);
    }
    return table;
  }

  /* -- teacher provenance ------------------------------------------------- */
  function drawProvenance(prov) {
    var frag = document.createDocumentFragment();
    if (prov.supports.length) {
      var box = el("section", "ewl-ps-prov");
      box.setAttribute("data-support-provenance", "supports");
      box.appendChild(el("h3", null, "Student supports applied"));
      var ul = el("ul");
      prov.supports.forEach(function (s) {
        ul.appendChild(el("li", null, s));
      });
      box.appendChild(ul);
      frag.appendChild(box);
    }
    if (prov.modifications.length) {
      var mod = el("section", "ewl-ps-prov ewl-ps-mod");
      mod.setAttribute("data-support-provenance", "modification");
      mod.appendChild(el("h3", null, "Instructional modification"));
      prov.modifications.forEach(function (m) {
        mod.appendChild(el("p", null, m.label + " — " + m.consequence));
      });
      frag.appendChild(mod);
    }
    if (prov.delivery.length) {
      var d = el("section", "ewl-ps-prov");
      d.setAttribute("data-support-provenance", "delivery");
      d.appendChild(el("h3", null, "Teacher delivery notes"));
      var dl = el("ul");
      prov.delivery.forEach(function (x) {
        dl.appendChild(el("li", null, x.label + " — " + x.note));
      });
      d.appendChild(dl);
      frag.appendChild(d);
    }
    return frag;
  }

  /* -- the modification, made real on paper --------------------------------
   * Marking problems optional is the paper equivalent of serving a shorter
   * practice set. The problems stay ON the page — a student who can keep going
   * should be able to, and a teacher needs to see the whole set — but what is
   * REQUIRED is genuinely shorter, and the teacher copy says so. A floor of
   * three matches the on-screen rule; below that it stops being practice. */
  var REQUIRED_MIN = 3;
  function applyShorterPracticeSet(root) {
    var items = root.querySelectorAll("[data-practice-item]");
    if (items.length <= REQUIRED_MIN) return 0;
    var keep = Math.max(REQUIRED_MIN, Math.ceil(items.length / 2));
    var marked = 0;
    for (var i = keep; i < items.length; i++) {
      items[i].classList.add("ewl-ps-optional");
      items[i].setAttribute("data-support-optional", "1");
      var tag = el("span", "ewl-ps-optional-tag", "Optional — try it if you have time.");
      items[i].insertBefore(tag, items[i].firstChild);
      marked++;
    }
    return marked;
  }

  /* -- placement ---------------------------------------------------------- */
  function slotFor(slot) {
    return document.querySelector('[data-support-slot="' + slot + '"]');
  }

  /** A block whose slot the page does not have still has to land somewhere: a
   * support present on screen and absent on paper is the exact divergence this
   * feature exists to remove. Unslotted blocks collect in one section near the
   * top rather than being dropped. */
  function fallbackHost() {
    var host = document.getElementById("ewl-print-supports-extra");
    if (host) return host;
    host = el("div");
    host.id = "ewl-print-supports-extra";
    var anchor = document.querySelector("[data-support-slot], h1");
    if (anchor && anchor.parentNode) anchor.parentNode.insertBefore(host, anchor.nextSibling);
    else document.body.insertBefore(host, document.body.firstChild);
    return host;
  }

  function loadScript(url) {
    return new Promise(function (resolve) {
      var settled = false;
      var done = function () {
        if (settled) return;
        settled = true;
        resolve(window.EWLLessonSupports || null);
      };
      var s = document.createElement("script");
      s.src = url;
      s.onload = done;
      s.onerror = done;
      document.head.appendChild(s);
      setTimeout(done, 3000);
    });
  }

  var state = { applied: [], blocks: 0, optional: 0, effective: null };

  /* Idempotent. A second run must not append a second copy of every block —
   * "sentence frames on" means ensure sentence support exists, and that is as
   * true of running twice as it is of a small-group lesson that already has
   * one. The promise is cached rather than a boolean so a caller arriving mid
   * fetch waits for the same work instead of starting its own. */
  var running = null;
  function run() {
    if (running) return running;
    running = doRun().catch(function (e) {
      // Canonical page. A support layer that throws must not take the packet
      // down — a teacher printing at 7:55am gets the lesson, not an error.
      if (window.console && console.warn) console.warn("Print supports unavailable.", e);
    });
    return running;
  }

  async function doRun() {
    if (!LESSON_ID) return;
    var LS = window.EWLLessonSupports || (await loadScript(MODULE_URL));
    if (!LS) return; // canonical page

    var store;
    try {
      store = LS.readStore();
    } catch (_e) {
      return;
    }
    // Nothing configured for this lesson (or its parent) — print as authored,
    // and do not spend a manifest fetch finding that out.
    var parent = LS.parentLessonId(LESSON_ID);
    if (!store[LESSON_ID] && !(parent && store[parent])) return;

    var manifest = null;
    try {
      var res = await fetch(MANIFEST_URL, { credentials: "same-origin" });
      if (res.ok) manifest = await res.json();
    } catch (_e) {
      manifest = null;
    }
    if (!manifest) return;
    var entry = manifest[LESSON_ID] || (parent ? manifest[parent] : null);
    if (!entry) return;

    var eff = LS.resolveEffectiveSupports({
      lessonId: LESSON_ID,
      store: store,
      entry: entry,
      surface: "print",
    });
    state.effective = eff;
    if (!eff.active.length && !eff.teacherNotes.length) return;

    ensureStyles();

    var blocks = LS.supportBlocks(eff.active, entry);
    blocks.forEach(function (b) {
      var host = slotFor(b.slot) || fallbackHost();
      host.appendChild(drawBlock(b));
      state.blocks++;
    });

    if (eff.modifications.indexOf("shorter-practice-set") > -1) {
      state.optional = applyShorterPracticeSet(document.body);
    }

    // Provenance and delivery notes are TEACHER information. A student packet
    // gets the supports and no commentary about them.
    if (AUDIENCE === "teacher") {
      var prov = LS.provenance(eff);
      if (!prov.isEmpty) {
        var anchor = document.querySelector("h1");
        var frag = drawProvenance(prov);
        if (anchor && anchor.parentNode) anchor.parentNode.insertBefore(frag, anchor.nextSibling);
        else document.body.insertBefore(frag, document.body.firstChild);
      }
    }

    state.applied = eff.active.slice();
    document.documentElement.setAttribute(
      "data-support-print-applied",
      String(state.applied.length),
    );
  }

  window.EWLPrintSupports = {
    version: "1.0.0",
    run: run,
    state: state,
    // test hooks
    _drawBlock: drawBlock,
    _applyShorterPracticeSet: applyShorterPracticeSet,
  };

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () {
      run();
    });
  } else {
    run();
  }
})();
