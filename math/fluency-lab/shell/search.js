// Search in "Choose a Skill": what a learner types is matched against the skill's own words, and against everyday
// words (English and Spanish) that name a strand. Pure, so shell/search.test.mjs can hold it to 30 real queries.
//   - accents and case are folded ("raíz" finds "raiz"), a trailing -s / -es is dropped ("roots" finds "root");
//   - filler words ("away", "of", "the", "how") never decide a result;
//   - a word that matches nothing in the grade is ignored rather than emptying the list, so "long division" or
//     "fractions zebra" still finds the strand; a query with no known word at all finds nothing.
export const fold = (text) =>
  String(text ?? "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/\p{M}/gu, "");

