// Words that never decide a result (English and Spanish).
const FILLER = new Set(
  "a an the of for to in on and or with by my me how what do does is are i can at it from about problems problem practice skills skill help learn y o de del la el los las un una en con por para como que mi mis se".split(" "),
);

export const queryWords = (query) => {
  const words = fold(query).split(/[^\p{L}\p{N}]+/u).filter(Boolean);
  const kept = words.filter((w) => !FILLER.has(w) && (w.length > 1 || /\d/.test(w)));
  return kept.length ? kept : words.filter((w) => w.length > 1);
};

const stems = (w) => [w, w.replace(/e?s$/, ""), w.replace(/ing$/, "")];
const wordMatches = (w, haystack, topicId) => stems(w).some((x) => x.length > 1 && (haystack.includes(x) || SYNONYMS[x] === topicId));

// words: queryWords(query). haystack: the skill's own text (folded here). Returns a predicate over (haystack, topicId).
export function skillMatcher(words, entries) {
  const folded = entries.map((e) => ({ ...e, hay: fold(e.text) }));
  const known = words.filter((w) => folded.some((e) => wordMatches(w, e.hay, e.topicId)));
  return {
    known,
    matches: (hay, topicId) => known.length > 0 && known.every((w) => wordMatches(w, fold(hay), topicId)),
  };
}
