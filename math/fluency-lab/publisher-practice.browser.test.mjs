import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { createServer } from 'vite';
import { REPO_ROOT } from '../../tools/lib/curriculum-source.mjs';

const server = await createServer({ root: REPO_ROOT, logLevel: 'error', server: { host: '127.0.0.1', port: 0 } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const errors = [];
  const openPractice = async () => {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.addInitScript(() => { Math.random = () => 0.5; });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/math/fluency-lab/?grade=7&skill=proportions&start=practice`);
    await page.locator('#publisher-practice-root').waitFor({ state: 'visible' });
    assert.equal(await page.locator('#answer-form').isHidden(), true, 'legacy answer form is replaced during publisher practice');
    assert.equal(await page.locator('#question').isHidden(), true, 'the prompt appears once in the publisher workspace');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'publisher practice fits a phone viewport');
    const values = await page.locator('#publisher-practice-root').evaluate(host => {
      const fractions = [...host.shadowRoot.querySelectorAll('h2 .math-fraction')].map(f => [Number(f.querySelector('.math-fraction-num').textContent), Number(f.querySelector('.math-fraction-den').textContent)]);
      return { fractions, prompt: host.shadowRoot.querySelector('h2').innerHTML };
    });
    assert.equal(values.fractions.length, 2, values.prompt);
    return { context, page, host: page.locator('#publisher-practice-root'), answer: String(values.fractions[0][0] * values.fractions[1][1] / values.fractions[0][1]), unit: String(values.fractions[1][1] / values.fractions[0][1]) };
  };
  const success = await openPractice();
  await success.host.locator('#answer').fill(success.answer);
  await success.host.locator('#check').click();
  await success.page.locator('#next-problem').waitFor({ state: 'visible' });
  assert.equal(await success.page.locator('#answer-form').isVisible(), true, 'session Next remains available after mastery');
  assert.equal(await success.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'completed practice fits a phone viewport');
  const successSession = await success.page.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
  assert.equal(successSession?.session.answered, 1, 'publisher result advances the normal practice session');
  assert.equal(successSession?.session.correct, 1, 'correct publisher result enters normal practice score');
  await success.page.locator('#next-problem').click();
  assert.equal(await success.page.locator('#publisher-practice-root').count() <= 1, true, 'the next item does not retain the previous publisher workspace');
  assert.equal(await success.page.locator('#answer-form').getAttribute('data-publisher-complete'), null, 'the completion layout resets for the next item');
  await success.context.close();
  const miss = await openPractice();
  await miss.host.locator('#answer').fill('999');
  await miss.host.locator('#check').click();
  assert.equal(await miss.host.locator('#answer').inputValue(), '999');
  await miss.page.goto(`http://127.0.0.1:${server.httpServer.address().port}/math/fluency-lab/?grade=7&skill=proportions&stage=practice`);
  await miss.page.locator('#publisher-practice-root').waitFor({ state: 'visible' });
  assert.match(await miss.host.locator('#conceptual-hint').textContent(), /Check the equal segment value|Equivalent ratios|Keep the two quantities|That answer/, 'the conceptual scaffold survives session resume');
  await miss.host.locator('#answer').fill('998');
  await miss.host.locator('#check').click();
  assert.equal(await miss.host.locator('#answer').count(), 0, 'main equation input is locked after two misses');
  const model = miss.host.locator('interactive-double-number-line');
  await model.locator('[data-track="A"]').last().click();
  await model.locator('[data-track="B"]').last().click();
  await miss.host.locator('#sub-answer').fill(miss.unit);
  await miss.host.locator('#sandbox-next').click();
  await miss.page.locator('#next-problem').waitFor({ state: 'visible' });
  const missedSession = await miss.page.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
  assert.equal(missedSession?.session.answered, 1);
  assert.equal(missedSession?.session.correct, 0, 'explanation does not inflate normal practice mastery');
  assert.match(await miss.host.locator('#content').textContent(), /Core conceptual rule/);
  await miss.context.close();
  const gradeSix = await browser.newContext();
  await gradeSix.addInitScript(() => { Math.random = () => 0.5; });
  const ratioPage = await gradeSix.newPage();
  ratioPage.on('pageerror', error => errors.push(error.message));
  await ratioPage.goto(`http://127.0.0.1:${server.httpServer.address().port}/math/fluency-lab/?grade=6&skill=ratios&start=practice`);
  const ratioHost = ratioPage.locator('#publisher-practice-root');
  await ratioHost.waitFor({ state: 'visible' });
  const ratioPrompt = (await ratioHost.locator('h2').textContent()).trim();
  const firstUnknown = ratioPrompt.match(/^(\d+):(\d+)\s*=\s*□:(\d+)/);
  const secondUnknown = ratioPrompt.match(/^(\d+):(\d+)\s*=\s*(\d+):□/);
  assert.ok(firstUnknown || secondUnknown, 'Grade 6 bridge accepts an equivalent-ratio item');
  const [, first, second, scaled] = firstUnknown || secondUnknown;
  const ratioAnswer = firstUnknown ? Number(first) * Number(scaled) / Number(second) : Number(second) * Number(scaled) / Number(first);
  await ratioHost.locator('#answer').fill(String(ratioAnswer));
  await ratioHost.locator('#check').click();
  await ratioPage.locator('#next-problem').waitFor({ state: 'visible' });
  const ratioSession = await ratioPage.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
  assert.equal(ratioSession?.session.correct, 1, 'Grade 6 ratio result enters the existing practice score');
  await gradeSix.close();
  for (const [grade, skill] of [[6, 'unit-rates'], [7, 'unit-rate']]) {
    const rateContext = await browser.newContext();
    await rateContext.addInitScript(() => { Math.random = () => 0.5; });
    const ratePage = await rateContext.newPage();
    ratePage.on('pageerror', error => errors.push(error.message));
    await ratePage.goto(`http://127.0.0.1:${server.httpServer.address().port}/math/fluency-lab/?grade=${grade}&skill=${skill}&start=practice`);
    const rateHost = ratePage.locator('#publisher-practice-root');
    await rateHost.waitFor({ state: 'visible' });
    const ratePrompt = (await rateHost.locator('h2').textContent()).trim();
    const numbers = ratePrompt.match(/^([\d.]+)(?: dollars)? for (\d+) items/);
    assert.ok(numbers, `Grade ${grade} uses an eligible unit-rate prompt`);
    const total = Number(numbers[1]);
    const count = Number(numbers[2]);
    const unitRate = String(Number((total / count).toFixed(6)));
    if (grade === 6) {
      await rateHost.locator('#answer').fill(unitRate);
      await rateHost.locator('#check').click();
      await ratePage.locator('#next-problem').waitFor({ state: 'visible' });
      const rateSession = await ratePage.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
      assert.equal(rateSession?.session.correct, 1, 'Grade 6 unit-rate result enters the normal practice score');
    } else {
      await rateHost.locator('#answer').fill(String(total));
      await rateHost.locator('#check').click();
      assert.match(await rateHost.locator('#conceptual-hint').textContent(), /cost for all|covers/);
      await rateHost.locator('#answer').fill('999');
      await rateHost.locator('#check').click();
      const rateModel = rateHost.locator('interactive-ratio-tape');
      await rateModel.locator('[data-track="A"]').last().click();
      await rateModel.locator('[data-track="B"]').last().click();
      await rateHost.locator('#sub-answer').fill(unitRate);
      await rateHost.locator('#sandbox-next').click();
      await ratePage.locator('#next-problem').waitFor({ state: 'visible' });
      assert.match(await rateHost.locator('#content').textContent(), /cost for all|covers/);
      const rateSession = await ratePage.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
      assert.equal(rateSession?.session.correct, 0, 'the unit-rate explanation does not count as mastery');
    }
    await rateContext.close();
  }
  const percentContext = await browser.newContext();
  await percentContext.addInitScript(() => { Math.random = () => 0.5; });
  const percentPage = await percentContext.newPage();
  percentPage.on('pageerror', error => errors.push(error.message));
  await percentPage.goto(`http://127.0.0.1:${server.httpServer.address().port}/math/fluency-lab/?grade=6&skill=percent&start=practice`);
  const percentHost = percentPage.locator('#publisher-practice-root');
  await percentHost.waitFor({ state: 'visible' });
  const percentPrompt = (await percentHost.locator('h2').textContent()).trim();
  const percentNumbers = percentPrompt.match(/^(?:Find|What is) (\d+)% of ([\d.]+)/);
  assert.ok(percentNumbers, 'Grade 6 uses an eligible percent-part prompt');
  const percent = Number(percentNumbers[1]);
  const whole = Number(percentNumbers[2]);
  await percentHost.locator('#answer').fill(String(whole));
  await percentHost.locator('#check').click();
  assert.match(await percentHost.locator('#conceptual-hint').textContent(), /whole, or 100%/);
  await percentHost.locator('#answer').fill(String(percent * whole / 100));
  await percentHost.locator('#check').click();
  await percentPage.locator('#next-problem').waitFor({ state: 'visible' });
  const percentSession = await percentPage.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
  assert.equal(percentSession?.session.correct, 1);
  assert.equal(percentSession?.session.independentCorrect, 0, 'a corrected percent answer is supported work');
  await percentContext.close();
  const wholeContext = await browser.newContext();
  await wholeContext.addInitScript(() => { Math.random = () => 0.5; });
  const wholePage = await wholeContext.newPage();
  wholePage.on('pageerror', error => errors.push(error.message));
  await wholePage.goto(`http://127.0.0.1:${server.httpServer.address().port}/math/fluency-lab/?grade=6&skill=percent-whole&start=practice`);
  const wholeHost = wholePage.locator('#publisher-practice-root');
  await wholeHost.waitFor({ state: 'visible' });
  const wholePrompt = (await wholeHost.locator('h2').textContent()).trim();
  const wholeNumbers = wholePrompt.match(/^([\d.]+) is (\d+)% of what number\?$/);
  assert.ok(wholeNumbers, 'Grade 6 uses an eligible inverse-percent prompt');
  const knownPart = Number(wholeNumbers[1]);
  const knownPercent = Number(wholeNumbers[2]);
  await wholeHost.locator('#answer').fill(String(knownPart));
  await wholeHost.locator('#check').click();
  assert.match(await wholeHost.locator('#conceptual-hint').textContent(), /only .*% of the whole/);
  await wholeHost.locator('#answer').fill(String(knownPart * 100 / knownPercent));
  await wholeHost.locator('#check').click();
  await wholePage.locator('#next-problem').waitFor({ state: 'visible' });
  const wholeSession = await wholePage.evaluate(() => JSON.parse(localStorage.getItem('ewl-fluency-session-v2') || 'null'));
  assert.equal(wholeSession?.session.correct, 1);
  assert.equal(wholeSession?.session.independentCorrect, 0, 'inverse-percent correction remains supported work');
  await wholeContext.close();
  assert.deepEqual(errors, [], 'normal practice and publisher engine have no page errors');
  console.log('Publisher practice bridge browser acceptance passed');
} finally {
  await browser?.close();
  await server.close();
}
