import assert from "node:assert/strict";
import { chromium } from "@playwright/test";
import { createServer } from "vite";
import { REPO_ROOT } from "../../../tools/lib/curriculum-source.mjs";
import { createState, derive, format, multiply, rational } from "./engine.js";

const server = await createServer({ root: REPO_ROOT, logLevel: "error", server: { host: "127.0.0.1", port: 0 } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto(`${server.config.server.origin || `http://127.0.0.1:${server.httpServer.address().port}`}/math/fluency-lab/?grade=6&skill=ratios`);
  const link = page.getByText("Explore this ratio in Ratio Studio", { exact: true });
  await link.waitFor();
  const href = await link.getAttribute("href");
  const expected = new URLSearchParams(href.split("?")[1]);
  await link.click();
  await page.waitForFunction(() => document.querySelector("#amount-a")?.value !== "");
  assert.equal(await page.locator("#amount-a").inputValue(), expected.get("a"));
  assert.equal(await page.locator("#amount-b").inputValue(), expected.get("b"));
  assert.equal(await page.locator("#label-a").inputValue(), expected.get("labelA"));
  assert.equal(expected.get("profile"), await page.evaluate(() => sessionStorage.getItem("ewl-fluency-tab-profile")));
  const scenario = createState({ a: expected.get("a"), b: expected.get("b"), labelA: expected.get("labelA"), labelB: expected.get("labelB") });
  const equivalentRow = derive(createState({ ...scenario, factor: 4 }));
  const prompt = await page.locator("#challenge-prompt").innerText();
  assert.ok(prompt.includes(`${expected.get("a")}:${expected.get("b")}`));
  await page.locator("#row-factor").fill("4");
  await page.locator("#row-a").fill(format(equivalentRow.a));
  await page.locator("#row-b").fill(format(equivalentRow.b));
  await page.locator("#check-row").click();
  assert.match(await page.locator("#row-feedback").innerText(), /^Yes/);
  await page.locator("#reason").fill("Both quantities were multiplied by four.");
  await page.locator("#unit-one").fill("2.5");
  await page.locator("#unit-two").fill("2");
  await page.locator('[data-predict="yes"]').click();
  await page.reload();
  await page.waitForFunction(() => document.querySelector("#amount-a")?.value !== "");
  const secondToWhole = derive(scenario).comparisons.find((item) => item.id === "second-to-whole");
  await page.locator('[data-comparison="second-to-whole"]').click();
  assert.equal(await page.locator('[data-comparison="second-to-whole"]').getAttribute("aria-pressed"), "true");
  assert.equal(await page.locator("#comparison-output strong").innerText(), `${secondToWhole.first} : total = ${format(secondToWhole.left)} : ${format(secondToWhole.right)}`);
  await page.reload();
  await page.waitForFunction(() => document.querySelector("#amount-a")?.value !== "");
  assert.equal(await page.locator('[data-comparison="second-to-whole"]').getAttribute("aria-pressed"), "true");
  assert.equal(await page.locator("#comparison-output strong").innerText(), `${secondToWhole.first} : total = ${format(secondToWhole.left)} : ${format(secondToWhole.right)}`);
  assert.equal(await page.locator("#row-a").inputValue(), format(equivalentRow.a));
  assert.equal(await page.locator("#row-b").inputValue(), format(equivalentRow.b));
  assert.match(await page.locator("#row-feedback").innerText(), /^Yes/);
  assert.equal(await page.locator("#reason").inputValue(), "Both quantities were multiplied by four.");
  assert.equal(await page.locator("#unit-one").inputValue(), "2.5");
  assert.equal(await page.locator("#unit-two").inputValue(), "2");
  assert.match(await page.locator("#prediction").innerText(), /Use the table to test/);
  assert.match(await page.locator("#challenge-math").innerText(), /not equivalent/);
  await page.locator('[data-predict="no"]').click();
  assert.match(await page.locator("#challenge-math").innerText(), /Correct: the exact ratios are not equivalent/);
  const languageSupport = page.locator("details.language-support").first();
  await languageSupport.locator("summary").click();
  await assert.doesNotReject(() => page.getByText(/Both quantities were multiplied by/).waitFor());
  await page.locator("#reason").fill("Both quantities were multiplied by different factors, so the ratio is not equivalent because the factors differ.");
  await page.locator("#check-reason").click();
  assert.match(await page.locator("#reason-feedback").innerText(), /Observed language evidence/);
  assert.match(await page.locator("#reason-feedback").innerText(), /separately/);
  await page.locator("#transfer-support summary").click();
  await page.locator("#unit-one").fill("2.5");
  await page.locator("#unit-two").fill("2");
  await page.locator("#buy").selectOption("second");
  await page.locator("#check-transfer").click();
  assert.match(await page.locator("#transfer-feedback").innerText(), /^Supported transfer complete/);
  await page.locator("#transfer-support summary").click();
  await page.locator("#check-transfer").click();
  assert.match(await page.locator("#transfer-feedback").innerText(), /^Independent transfer complete/);
  const base = [rational(await page.locator("#amount-a").inputValue()), rational(await page.locator("#amount-b").inputValue())];
  await page.locator('[data-ratio-factor="4"]').tap();
  assert.equal(await page.locator("#factor").inputValue(), "4");
  assert.match(await page.locator("#models article:first-child > p:first-of-type strong").innerText(), new RegExp(`${format(multiply(base[0], rational(4)))} : ${format(multiply(base[1], rational(4)))}`));
  await page.locator('[data-ratio-factor="3"]').focus();
  await page.keyboard.press("Enter");
  assert.equal(await page.locator("#factor").inputValue(), "3");
  assert.match(await page.locator("#models article:first-child > p:first-of-type strong").innerText(), new RegExp(`${format(multiply(base[0], rational(3)))} : ${format(multiply(base[1], rational(3)))}`));
  assert.equal(await page.evaluate(() => document.activeElement?.getAttribute("data-ratio-factor")), "3");
  const tutor = await page.evaluate(() => JSON.parse(localStorage.getItem("ewl-fluency-tutor-v2")));
  const { buildTeacherReport } = await import("../learning-evidence.js");
  const report = buildTeacherReport([{ label: "Orbit", tutor }], 6);
  const ratioEvidence = report.rows.find((row) => row.skill.id === "ratios");
  const rateEvidence = report.rows.find((row) => row.skill.id === "unit-rates");
  assert.equal(ratioEvidence.status.supportedTotal, 1);
  assert.equal(ratioEvidence.status.independent, 0);
  assert.equal(rateEvidence.status.independent, 1);
  assert.equal(rateEvidence.status.ratio, 1);
  assert.equal(report.groups.length, 0, "one independent attempt is not enough to recommend an intervention group");
  assert.equal(JSON.stringify(tutor).includes("Both quantities were multiplied by different factors"), false, "typed reasoning is not copied into teacher evidence");
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1280, height: 900 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log("Grade 6 ratio lesson → contextual Ratio Studio → language support → supported and independent transfer passed at 390px.");
} finally {
  await browser?.close();
  await server.close();
}
