test("a saved custom unit is a custom:true record, never overwrites the corpus, and round-trips through store and export", async () => {
  const words = await draftFromList(parseWordList("timid"), corpusByHeadword(index), lookup);
  const mine = {
    ...good,
    hw: "snug",
    def: "Warm and comfortable in a small space.",
    ex: "The kitten felt snug in the basket.",
  };
  const built = buildUnit(
    { title: "Cozy Words", grade: "3", words: [...words, mine], activities: ["a", "a", "b"] },
    { now: 1_700_000_000_000, taken: [] },
  );
  assert.equal(built.custom, true);
  assert.ok(built.id.startsWith(CUSTOM_PREFIX));
  assert.equal(built.n, 0);
  for (const w of built.words) {
    assert.ok(w.id.startsWith(built.id), "word ids live under the custom id");
    assert.ok(!index.words[w.id], "no corpus id is reused");
  }
  assert.deepEqual(built.activities, ["a", "b"]);
  const snug = built.words.find((w) => w.hw === "snug");
  assert.equal(snug.cloze.f, "snug");
  assert.equal(snug.cloze.s.split("___").length, 2);
  assert.equal(snug.src.method, "teacher-authored");
  assert.equal(built.words.find((w) => w.hw === "timid").src.method, "corpus-copy");
  assert.notEqual(
    buildUnit(
      { title: "Cozy Words", grade: "3", words: [mine] },
      { now: 1_700_000_000_000, taken: [built.id] },
    ).id,
    built.id,
    "a taken id is never reused",
  );

  assert.equal(saveCustom(built).state, "saved");
  assert.equal(getCustom(built.id).title, "Cozy Words");
  assert.throws(() => saveCustom({ ...built, id: "g3-u01", custom: true }), TypeError);
  assert.throws(() => saveCustom({ ...built, custom: false }), TypeError);
  const file = JSON.parse(JSON.stringify(exportUnitFile(built)));
  assert.equal(unitsFromFile(file).length, 1);
  assert.equal(
    unitsFromFile({ v: 1, custom: { "g3-u01": { ...built, id: "g3-u01" } } }).length,
    0,
    "a published id is never imported as custom",
  );
  assert.equal(
    unitsFromFile({
      v: 1,
      custom: { [built.id]: { ...built, words: [{ ...snug, ex: "No target here." }] } },
    }).length,
    0,
  );
  deleteCustom(built.id);
  assert.equal(getCustom(built.id), null);
});

