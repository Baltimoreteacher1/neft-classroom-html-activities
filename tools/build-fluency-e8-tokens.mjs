// Compiles math/fluency-lab/e8/tokens.js into tokens.generated.css.
// `--check` fails (exit 1) when the committed CSS is stale; otherwise the file is rewritten.
import { readFileSync, writeFileSync } from "node:fs";
import { BREAKPOINTS, ELEVATION, SPACING, TOKENS } from "../math/fluency-lab/e8/tokens.js";

export function buildCss() {
  const block = (selector, tokens) =>
    `${selector} {\n${Object.entries(tokens)
      .map(([name, value]) => `  --e8-${name}: ${value};`)
      .join("\n")}\n}\n`;
  const scale = {
    ...Object.fromEntries(Object.entries(SPACING).map(([key, value]) => [`space-${key}`, value])),
    ...Object.fromEntries(
      Object.entries(ELEVATION).map(([key, value]) => [`elevation-${key}`, value]),
    ),
    ...Object.fromEntries(
      Object.entries(BREAKPOINTS).map(([key, value]) => [`bp-${key}`, `${value}px`]),
    ),
  };
  return [
    "/* GENERATED by tools/build-fluency-e8-tokens.mjs from e8/tokens.js. Do not edit by hand. */",
    block(":root", { ...TOKENS.light, ...scale }),
    block('html[data-theme="dark"]', TOKENS.dark),
    `@media (prefers-color-scheme: dark) {\n${block('html[data-theme="auto"]', TOKENS.dark)
      .split("\n")
      .map((line) => (line ? `  ${line}` : line))
      .join("\n")}}\n`,
  ].join("\n");
}

const target = new URL("../math/fluency-lab/e8/tokens.generated.css", import.meta.url);
if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  const css = buildCss();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(target, "utf8");
    } catch {}
    if (current !== css) {
      console.error("tokens.generated.css is stale. Run: node tools/build-fluency-e8-tokens.mjs");
      process.exit(1);
    }
    console.log("tokens.generated.css is current");
  } else {
    writeFileSync(target, css);
    console.log(`wrote ${target.pathname}`);
  }
}
