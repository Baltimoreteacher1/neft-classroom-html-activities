#!/usr/bin/env node
/**
 * report-part-two-practice.mjs — which Part 2 family homeworks practise the
 * session they teach, and which still practise the previous one.
 *
 * REPORT ONLY, deliberately not a gate. The defect it measures cannot be fixed
 * by policy: a Part 2 inherits its practice pool from the PARENT lesson's
 * parallel banks, so when session 2 teaches different mathematics — which is
 * the whole premise of the split — the pool holds nothing to select. Lesson 3-1
 * session 2 taught splitting a total with a tape diagram and asked "write the
 * ratio" fifteen times. The fix is AUTHORED practice per lesson, which is human
 * work, and failing a build until a person writes 52 lessons of curriculum
 * would only teach people to pass `--no-verify`. Same reasoning as
 * `report:apply-day-tiers`.
 *
 * It is also why `audit:homework` cannot catch this: that gate scores topic
 * alignment, and "write the ratio" IS on-topic for a ratio lesson. On-topic and
 * wrong-task are different questions.
 *
 *   node tools/report-part-two-practice.mjs          → reports/part-two-practice.md
 *   node tools/report-part-two-practice.mjs --stdout
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { LESSONS_DIR as LESSONS } from "./lib/curriculum-source.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "reports", "part-two-practice.md");
const STDOUT = process.argv.includes("--stdout");

const readJson = (path, fallback) =>
  existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : fallback;

const authored = readJson(join(ROOT, "data/part-two-session2-practice.json"), {
  lessons: {},
}).lessons;
const source = readJson(join(ROOT, "data/part-two-session2-source.json"), { lessons: [] }).lessons;
const sourceById = new Map(source.map((l) => [l.id, l]));

const STOP = new Set(
  "the a an and or to of in on for with is are can this that using use write find solve show explain work number numbers math your their each every from into by as at be what how many much more than then".split(
    " ",
  ),
);
const words = (text) =>
  String(text || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .split(/\s+/)
    .filter((w) => w.length > 3 && !STOP.has(w));

const rows = [];
for (const dir of readdirSync(LESSONS).sort()) {
  if (!dir.endsWith("-part2")) continue;
  const configPath = join(LESSONS, dir, "config.json");
  const notesPath = join(ROOT, "data", "family-homework-notes", `${dir}.json`);
  if (!existsSync(configPath) || !existsSync(join(LESSONS, dir, "homework.html"))) continue;

  const config = readJson(configPath, {});
  const notes = readJson(notesPath, {});
  const sessionTitle = notes.sessionTitle || "";

  if (authored[dir]) {
    rows.push({ id: dir, state: "authored", sessionTitle, coverage: 1 });
    continue;
  }

  /* How much of the session's OWN method vocabulary the inherited pool uses.
     A proxy, not a verdict — it is why this is a report. */
  const levels = config.groupLevels || {};
  const stems = ["level1", "level2", "level3"]
    .flatMap((k) => (Array.isArray(levels[k]) ? levels[k] : []))
    .map((p) => String(p.stem || p.prompt || ""))
    .join(" ")
    .toLowerCase();
  const method = [...new Set([...words(sessionTitle), ...words(notes.bigIdea?.en)])];
  const hit = method.filter((w) => stems.includes(w));
  rows.push({
    id: dir,
    state: sourceById.has(dir) ? "inherited (source available)" : "inherited (no Reveal source)",
    sessionTitle,
    coverage: method.length ? hit.length / method.length : 1,
  });
}

rows.sort((a, b) => a.coverage - b.coverage || a.id.localeCompare(b.id));
const authoredRows = rows.filter((r) => r.state === "authored");
const withSource = rows.filter((r) => r.state === "inherited (source available)");
const noSource = rows.filter((r) => r.state === "inherited (no Reveal source)");

const lines = [
  "# Part 2 family homework — does the practice match the session?",
  "",
  `_Generated by \`tools/report-part-two-practice.mjs\`. ${rows.length} Part 2 homeworks._`,
  "",
  `- **${authoredRows.length} authored** — practice written for the session, answer key verified by \`tools/part-two-session2-practice.test.mjs\`.`,
  `- **${withSource.length} inherited, Reveal Session 2 source available** — the material to author from is already extracted into \`data/part-two-session2-source.json\`.`,
  `- **${noSource.length} inherited, no Reveal source** — units 1 and 10 and the appended extras; nothing to author from.`,
  "",
  "`coverage` is the share of the session's own method vocabulary that appears in its practice stems. Low means the pool is drilling the other session's skill. It is a proxy: judging whether a problem asks the right *task* is a reading task, which is why nothing here fails a build.",
  "",
  "| lesson | state | coverage | session |",
  "| --- | --- | ---: | --- |",
  ...rows.map(
    (r) => `| ${r.id} | ${r.state} | ${(r.coverage * 100).toFixed(0)}% | ${r.sessionTitle} |`,
  ),
  "",
];
const text = lines.join("\n");

if (STDOUT) {
  console.log(text);
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, text);
}
console.log(
  `part-two-practice: ${authoredRows.length} authored, ${withSource.length} inherited with source, ${noSource.length} inherited without source`,
);
