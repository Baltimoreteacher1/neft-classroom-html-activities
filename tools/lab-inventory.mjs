#!/usr/bin/env node
// Phase 0 inventory of the Language Lab's games, worlds and Road weeks, read from the code (registry, game
// modules, content JSON, worlds, road.json) and written to access-practice-lab/LAB-INVENTORY.md.
// Usage: node tools/lab-inventory.mjs [--stdout]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { WORLDS } from "../access-practice-lab/src/adventures/worlds/index.js";
import { GAMES } from "../access-practice-lab/src/games/registry.js";
import { gameMeta } from "../access-practice-lab/src/lab/meta.js";

const lab = join(process.cwd(), "access-practice-lab");
const read = (p) => (existsSync(p) ? readFileSync(p, "utf8") : "");
const sources = (g) => {
  const base = join(lab, "src/games", g.module);
  const files = [`${base}.js`, `${base}-view.js`, `${base}-art.js`].filter(existsSync);
  return { files, text: files.map(read).join("\n") };
};
// A Spanish gap is a bilingual pair with one half missing: an object that has `es` but no `en`, or a sibling in an
// array of `{ en, es }` pairs that lacks its `es`. A lone `{ en }` (an English answer choice, a passage sentence) is
// practice text and is not a gap.
const missingEs = (node, path = "", out = []) => {
  if (Array.isArray(node)) {
    const paired = node.some(
      (v) => v && typeof v === "object" && typeof v.en === "string" && typeof v.es === "string",
    );
    node.forEach((v, i) => {
      if (
        paired &&
        v &&
        typeof v === "object" &&
        typeof v.en === "string" &&
        typeof v.es !== "string"
      )
        out.push(`${path}[${i}]`);
      missingEs(v, `${path}[${i}]`, out);
    });
  } else if (node && typeof node === "object") {
    if (
      typeof node.es === "string" &&
      typeof node.en !== "string" &&
      Object.keys(node).length === 1
    )
      out.push(path || "$");
    for (const [k, v] of Object.entries(node)) missingEs(v, `${path}.${k}`, out);
  }
  return out;
};

const rows = GAMES.map((g) => {
  const { files, text } = sources(g);
  const meta = gameMeta(g.id);
  const content = (() => {
    try {
      return JSON.parse(read(join(lab, "content/games", `${g.id}.json`)));
    } catch {
      return null;
    }
  })();
  const flags = [];
  if (/choiceList\(|mixChoices\(/.test(text)) flags.push("CHOICE_LOOP");
  const keyboard = /\bkey\s*[(:]/.test(text)
    ? "key()"
    : /\bdnd\(/.test(text)
      ? "dnd+tap"
      : /<button/.test(text)
        ? "buttons"
        : "AUDIT";
  if (keyboard === "AUDIT") flags.push("KEYBOARD_AUDIT");
  const speaks = meta.domains.includes("Speaking");
  const records = /recorder|\brec\./.test(text);
  const fallback = /norec|typed|canRecord|AudioGuard|audio-guard/.test(text);
  if (speaks && records && !fallback) flags.push("MIC_FALLBACK_MISSING");
  const gaps = content ? missingEs(content) : ["content missing"];
  if (gaps.length) flags.push(`ES_GAPS(${gaps.length})`);
  return {
    id: g.id,
    title: g.title[0],
    file: files.map((f) => f.replace(`${process.cwd()}/`, "")).join(" + "),
    band: Object.keys(g.obj).join(", "),
    domains: meta.domains.join("/"),
    area: meta.contentArea,
    mechanic: g.mechanic,
    state: `games:${g.id}:<band> -> tlp_lab_v2`,
    flags: flags.join(" ") || "-",
    recorder: records ? "recorder.js" : speaks ? "typed/choice" : "n/a",
  };
});

const road = JSON.parse(read(join(lab, "content/road.json")));
const md = [];
md.push(
  "# Language Lab inventory (Phase 0)",
  "",
  "Generated by `node tools/lab-inventory.mjs` from the registry, game modules, content JSON, worlds and `road.json`. Do not edit by hand.",
  "",
);
md.push(
  `## Games (${rows.length})`,
  "",
  "| id | title | filePath | gradeBand | widaDomains | contentArea | coreMechanic | currentStateKey | recorder | flags |",
  "|---|---|---|---|---|---|---|---|---|---|",
);
for (const r of rows)
  md.push(
    `| ${r.id} | ${r.title} | ${r.file} | ${r.band} | ${r.domains} | ${r.area} | ${r.mechanic} | ${r.state} | ${r.recorder} | ${r.flags} |`,
  );
md.push(
  "",
  "Flags: `CHOICE_LOOP` = the module drives a multiple-choice loop (check the item is tied to the text or audio, not decoupled); `KEYBOARD_AUDIT` = no explicit key handler, drag-and-drop helper or native buttons found; `MIC_FALLBACK_MISSING` = records speech with no typed fallback; `ES_GAPS(n)` = content objects with an `en` string and no `es`.",
  "",
);
md.push(
  `## Worlds (${WORLDS.length})`,
  "",
  "| id | title | filePath | gradeBand | widaDomains | coreMechanic | currentStateKey |",
  "|---|---|---|---|---|---|---|",
);
for (const w of WORLDS)
  md.push(
    `| ${w.id} | ${w.title.en} | access-practice-lab/src/adventures/worlds/${w.id}.js | ${(w.bands || ["3-5", "6-8"]).join(", ")} | ${(w.domains || []).join("/") || "L/R/S/W"} | ${w.missions.length}-mission chain | adventures state -> tlp_lab_v2 (missions) |`,
  );
md.push("");
md.push(
  "## Road to ACCESS",
  "",
  "| gradeBand | weeks | content file | route | currentStateKey |",
  "|---|---|---|---|---|",
);
for (const [band, v] of Object.entries(road))
  md.push(
    `| ${band} | ${v.weeks?.length ?? 0} | access-practice-lab/content/road.json | /access-practice-lab/road/:week | road week pref -> tlp_lab_v2 readiness |`,
  );
md.push("");
const out = md.join("\n");
if (process.argv.includes("--stdout")) console.log(out);
else {
  writeFileSync(join(lab, "LAB-INVENTORY.md"), out);
  console.log(
    `lab-inventory: ${rows.length} games, ${WORLDS.length} worlds -> access-practice-lab/LAB-INVENTORY.md`,
  );
}
