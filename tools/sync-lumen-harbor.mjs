#!/usr/bin/env node
/**
 * sync-lumen-harbor.mjs — publish the Lumen Harbor graphic novels onto this site.
 *
 *   node tools/sync-lumen-harbor.mjs --app <lumen-harbor checkout>   rebuild outputs from the app's `out/` export
 *   node tools/sync-lumen-harbor.mjs --check                         fail if the generated pieces drifted
 *
 * The novels are a separate Next.js app (package lumen-harbor-graphic-novels), exported as static
 * files (`npm run build` in that app) and mounted at /lumen-harbor/. Its coverage manifest is the
 * single source for which lessons belong to which chapter, so everything derived from it is written
 * here and nowhere else:
 *
 *   lumen-harbor/                        the static export (copied, never hand-edited)
 *   engine/core/lumen-harbor-chapters.js lesson id -> chapter id, read by the lesson side rail
 *   data/routes.json (+ _redirects, redirect-map.js, regenerated)  /novels/unit/N/level/1|2 entry points
 *   curriculum/units/index.html          each unit's Graphic Novel #1/#2 + a library link
 *   curriculum/index.html                a hub link to the library
 *
 * Legacy /graphic-novels/unitN/ folders are NOT redirected: their folder numbers predate the current
 * unit order (Unit 2's block links unit8/, Unit 6's links unit2/), so a folder-number redirect would
 * send students to the wrong story. Those files stay live; only the unit blocks' own links move.
 */
import { execFileSync } from "node:child_process";
import { cpSync, existsSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { REPO_ROOT } from "./lib/curriculum-source.mjs";

export const MOUNT = "/lumen-harbor";
const UNITS = [2, 3, 4, 5, 6, 7, 8, 9];
const PATHWAY = { 1: "supported", 2: "independent" };

const readText = (rel) => readFileSync(join(REPO_ROOT, rel), "utf8");
const chapterUrl = (id, pathway) => `${MOUNT}/read/${id}/${pathway ? `?path=${pathway}` : ""}`;

/** Fail loudly on a manifest that does not cover Units 2-9: every output below depends on it. */
export function parseManifest(manifest) {
  const unitChapters = new Map();
  const lessonToChapter = {};
  for (const unit of manifest.units) {
    unitChapters.set(unit.unit, unit.chapters);
    for (const chapter of unit.chapters)
      for (const code of chapter.lessons) lessonToChapter[code.replace(".", "-")] = chapter.id;
  }
  for (const n of UNITS) {
    if (!unitChapters.get(n)?.length) throw new Error(`manifest has no chapters for Unit ${n}`);
  }
  return { unitChapters, lessonToChapter };
}

export function chaptersModule({ lessonToChapter }) {
  // Trailing comma on the last entry: that is the shape biome formats this file to.
  const body = JSON.stringify(lessonToChapter, null, 2).replace(/"\n}$/, '",\n}');
  return (
    "// Generated by tools/sync-lumen-harbor.mjs from the Lumen Harbor coverage manifest. Do not edit.\n" +
    `export const LUMEN_HARBOR_ROOT = "${MOUNT}";\n` +
    `export const LUMEN_HARBOR_CHAPTER_BY_LESSON = ${body};\n`
  );
}

/** The legacy entry points: Level 1 is Supported Explorer, Level 2 is Independent Investigator. */
export function routeRedirects({ unitChapters }) {
  return UNITS.flatMap((n) =>
    [1, 2].map((level) => ({
      source: `/novels/unit/${n}/level/${level}`,
      destination: chapterUrl(unitChapters.get(n)[0].id, PATHWAY[level]),
      status: 301,
    })),
  );
}

/** data/routes.json owns every redirect (tools/generate-route-files.mjs emits _redirects from it). */
export function withRoutes(text, entries) {
  const registry = JSON.parse(text);
  registry.redirects = [
    ...registry.redirects.filter((r) => !r.source.startsWith("/novels/unit/")),
    ...entries,
  ];
  return `${JSON.stringify(registry, null, 2)}\n`;
}

const UNIT_LINK = (n) =>
  `<!-- novel-library-link:${n} --><a class="res" href="${MOUNT}/#unit-${n}">Graphic Novel Library · Unit ${n}</a><!-- /novel-library-link -->`;
const GN_ANCHOR = (level) =>
  new RegExp(
    `(<a class="res" href=")[^"]+("\\s*>\\s*Graphic Novel #${level} <span class="res-sub">Whole unit · Level ${level} (?:Support|Enrichment)</span>)`,
  );

/** Point Unit N's own "Whole unit" Graphic Novel #1/#2 at its first chapter and add the library link. */
export function withUnitLinks(html, { unitChapters }) {
  let out = html;
  for (const n of UNITS) {
    const marker = new RegExp(
      `(<!-- studio-unit-link:${n} -->.*?<!-- /studio-unit-link -->)(?:<!-- novel-unit-block:${n} -->.*?<!-- /novel-unit-block -->)?(?:<!-- novel-library-link:${n} -->.*?<!-- /novel-library-link -->)?(?:<!-- novel-legacy-links:${n} -->.*?<!-- /novel-legacy-links -->)?(?:<!-- novel-entry-links:${n} -->.*?<!-- /novel-entry-links -->)?`,
    );
    const found = out.match(marker);
    if (!found) throw new Error(`curriculum/units/index.html has no studio-unit-link:${n} marker`);
    const first = unitChapters.get(n)[0].id;
    // A studio marker that wraps its own `unit-res` block (Unit 9) is a row of its own, so the novel
    // links get a row of their own; everywhere else the marker sits inside a row and links join it.
    if (found[1].includes('class="unit-res"')) {
      const block = `<!-- novel-unit-block:${n} --><div class="unit-res"><span class="unit-res-label">Graphic Novels</span><div class="res-row">${UNIT_LINK(n)}${fallbackAnchors(n, first)}</div></div><!-- /novel-unit-block -->`;
      out = out.replace(marker, `$1${block}`);
      continue;
    }
    out = out.replace(marker, `$1${UNIT_LINK(n)}${legacyLinks(n)}`);
    // Bound the search to this unit's own block: later units' links are not ours to touch.
    const from = out.search(new RegExp(`novel-library-link:${n} -->`));
    const next = out.indexOf(`<!-- studio-unit-link:${n + 1} -->`, from);
    const to = next === -1 ? out.length : next;
    let span = out.slice(from, to);
    // Only the first existing pair is the unit's own; later pairs are other legacy novels.
    // A unit with no pair of its own (Unit 9) gets the two entry links in a marked block.
    span = span.replace(FALLBACK_GN, "");
    if (GN_ANCHOR(1).test(span) && GN_ANCHOR(2).test(span)) {
      for (const level of [1, 2])
        span = span.replace(GN_ANCHOR(level), `$1${chapterUrl(first, PATHWAY[level])}$2`);
    } else {
      span = span.replace(/(<!-- \/novel-library-link -->)/, `$1${fallbackAnchors(n, first)}`);
    }
    out = out.slice(0, from) + span + out.slice(to);
  }
  return out;
}

// The old /graphic-novels/unitN/ folders predate the current unit order. Each current unit's own block
// linked these folders, so they stay listed there as the earlier edition (nothing leaves the hub).
const LEGACY_FOLDER = { 2: 8, 3: 3, 4: 4, 5: 5, 6: 2, 7: 9, 8: 7 };
const legacyLinks = (n) => {
  const folder = LEGACY_FOLDER[n];
  if (!folder) return "";
  const link = (k) =>
    `<a class="res" href="/graphic-novels/unit${folder}/graphic-novel-${k}.html">Graphic Novel #${k} (earlier edition)</a>`;
  return `<!-- novel-legacy-links:${n} -->${link(1)}${link(2)}<!-- /novel-legacy-links -->`;
};

const FALLBACK_GN = /<!-- novel-entry-links:\d+ -->.*?<!-- \/novel-entry-links -->/s;
const fallbackAnchors = (n, first) =>
  `<!-- novel-entry-links:${n} --><a class="res" href="${chapterUrl(first, PATHWAY[1])}">Graphic Novel #1 <span class="res-sub">Whole unit · Level 1 Support</span></a><a class="res" href="${chapterUrl(first, PATHWAY[2])}">Graphic Novel #2 <span class="res-sub">Whole unit · Level 2 Enrichment</span></a><!-- /novel-entry-links -->`;

const HUB_ANCHOR =
  '<li><a href="/curriculum/all-resources/">All resources <span lang="es">· Todos los recursos</span></a></li>';
const HUB_LINK = `<!-- novel-library-hub-link --><li><a href="${MOUNT}/">Graphic Novel Library</a></li><!-- /novel-library-hub-link -->`;

export function withHubLink(html) {
  const marked = /<!-- novel-library-hub-link -->.*?<!-- \/novel-library-hub-link -->/;
  if (marked.test(html)) return html.replace(marked, HUB_LINK);
  if (!html.includes(HUB_ANCHOR))
    throw new Error("curriculum/index.html: hub resources anchor not found");
  return html.replace(HUB_ANCHOR, `${HUB_ANCHOR}\n          ${HUB_LINK}`);
}

function generated(manifest) {
  const parsed = parseManifest(manifest);
  return new Map([
    ["engine/core/lumen-harbor-chapters.js", chaptersModule(parsed)],
    ["data/routes.json", withRoutes(readText("data/routes.json"), routeRedirects(parsed))],
    ["curriculum/units/index.html", withUnitLinks(readText("curriculum/units/index.html"), parsed)],
    ["curriculum/index.html", withHubLink(readText("curriculum/index.html"))],
  ]);
}

function main() {
  const args = process.argv.slice(2);
  const check = args.includes("--check");
  const appFlag = args.indexOf("--app");
  const app = appFlag === -1 ? null : resolve(args[appFlag + 1] ?? "");
  const manifestPath = app
    ? join(app, "content/coverage-manifest.json")
    : join(REPO_ROOT, "data/lumen-harbor-manifest.json");
  if (!existsSync(manifestPath)) throw new Error(`coverage manifest not found: ${manifestPath}`);
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (app)
    writeFileSync(
      join(REPO_ROOT, "data/lumen-harbor-manifest.json"),
      `${JSON.stringify(manifest, null, 2)}\n`,
    );

  let stale = 0;
  for (const [file, expected] of generated(manifest)) {
    const actual = existsSync(join(REPO_ROOT, file)) ? readText(file) : null;
    if (actual === expected) continue;
    if (check) {
      console.error(
        `Stale: ${file}. Run node tools/sync-lumen-harbor.mjs --app <lumen-harbor checkout>.`,
      );
      stale++;
    } else {
      writeFileSync(join(REPO_ROOT, file), expected);
      console.log(`Updated ${file}`);
    }
  }
  if (!check)
    execFileSync("node", ["tools/generate-route-files.mjs"], { cwd: REPO_ROOT, stdio: "inherit" });
  if (app && !check) {
    const out = join(app, "out");
    if (!existsSync(join(out, "read")))
      throw new Error(`no static export at ${out}; run npm run build in the app first`);
    rmSync(join(REPO_ROOT, "lumen-harbor"), { recursive: true, force: true });
    cpSync(out, join(REPO_ROOT, "lumen-harbor"), { recursive: true });
    // The site serves its own root 404.html; the app's copy would only be catalogued as a resource.
    rmSync(join(REPO_ROOT, "lumen-harbor/404.html"), { force: true });
    // The site serves its own root 404.html; the app's copy would only be catalogued as a resource.
    rmSync(join(REPO_ROOT, "lumen-harbor/404.html"), { force: true });
    console.log("Copied static export to lumen-harbor/");
  }
  if (stale) process.exitCode = 1;
  else if (check) console.log("Lumen Harbor links, redirects and chapter map match the manifest.");
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) main();
