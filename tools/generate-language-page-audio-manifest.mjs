#!/usr/bin/env node
/* =============================================================================
 * generate-language-page-audio-manifest.mjs — one row for every listening script, with a hash of the words, and the status of its audio.
 *
 * WHY. Every Listening item is read aloud by the browser's text-to-speech today (listenPlayerHTML -> speechSynthesis). That is a stand-in:
 * the audit (E1/WS4) wants recorded human voices with captions, and recording is a human job (H-12). This is the pipeline the
 * recordings drop into, so a recording can never silently outlive the script it was made from:
 *
 *   data/language-page-audio-manifest.json     GENERATED. A row per listening item: id, band, word count, sha256 of the script, and a status:
 *                                              "tts" (no recording), "recorded" (a recording that matches the script word for word),
 *                                              "stale" (a recording whose script has since changed: it must be re-recorded or removed).
 *   data/language-page-audio-recordings.json   HAND-EDITED by whoever records. { recordings: { <itemId>: { file, captions, scriptSha256,
 *                                              speaker, recordedOn, licence } } }. Empty today: no recording has been made.
 *
 * It records nothing and invents nothing: with no recordings, every row is "tts".
 *
 *   node tools/generate-language-page-audio-manifest.mjs           write the manifest
 *   node tools/generate-language-page-audio-manifest.mjs --check   fail when it is stale
 * ========================================================================== */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("../", import.meta.url));
export const MANIFEST = "data/language-page-audio-manifest.json";
export const RECORDINGS = "data/language-page-audio-recordings.json";
const BANDS = ["gK", "g1", "g2-3", "g3-5", "g6-8"];

export const sha = (s) => createHash("sha256").update(s.normalize("NFC").trim()).digest("hex");
const words = (s) => (s.match(/[\p{L}\p{N}'’-]+/gu) || []).length;

/** { id, band, script|null } for every activity in a Listening file. */
export function loadListening(root = join(ROOT, "access-practice-lab/content")) {
  const out = [];
  for (const band of BANDS) {
    const p = join(root, band, "Listening.json");
    if (!existsSync(p)) continue;
    const walk = (n) => {
      if (Array.isArray(n)) n.forEach(walk);
      else if (n && typeof n === "object") {
        if (n.id && (n.directions || n.prompt || n.question))
          out.push({ id: n.id, band, script: typeof n.script === "string" ? n.script : null });
        else Object.values(n).forEach(walk);
      }
    };
    walk(JSON.parse(readFileSync(p, "utf8")));
  }
  return out;
}

/** The status of one item given the recording registry. */
export function statusOf(item, recordings) {
  const rec = recordings[item.id];
  if (!rec) return "tts";
  return item.script && rec.scriptSha256 === sha(item.script) ? "recorded" : "stale";
}

export function buildManifest(items, recordings) {
  const rows = items
    .filter((i) => i.script)
    .map((i) => ({
      id: i.id,
      band: i.band,
      words: words(i.script),
      scriptSha256: sha(i.script),
      status: statusOf(i, recordings),
    }));
  const count = (s) => rows.filter((r) => r.status === s).length;
  return {
    _why: "GENERATED by tools/generate-language-page-audio-manifest.mjs; do not edit. Recordings are registered in data/language-page-audio-recordings.json.",
    totals: {
      items: rows.length,
      tts: count("tts"),
      recorded: count("recorded"),
      stale: count("stale"),
    },
    noScript: items.filter((i) => !i.script).map((i) => i.id),
    rows,
  };
}

/** Problems with the recording registry itself (files, captions, ids, hashes). */
export function recordingProblems(items, recordings, exists = (p) => existsSync(join(ROOT, p))) {
  const out = [];
  const byId = new Map(items.map((i) => [i.id, i]));
  for (const [id, rec] of Object.entries(recordings)) {
    const item = byId.get(id);
    if (!item) {
      out.push(`${id}: a recording is registered for a Listening item that does not exist`);
      continue;
    }
    for (const f of ["file", "captions", "scriptSha256", "speaker", "recordedOn", "licence"])
      if (typeof rec[f] !== "string" || !rec[f].trim())
        out.push(`${id}: recording is missing ${f}`);
    if (typeof rec.file === "string" && !/\.(mp3|m4a|ogg|wav)$/i.test(rec.file))
      out.push(`${id}: file must be an audio file`);
    if (typeof rec.captions === "string" && !/\.vtt$/i.test(rec.captions))
      out.push(`${id}: captions must be a WebVTT (.vtt) file`);
    for (const f of ["file", "captions"])
      if (typeof rec[f] === "string" && rec[f] && !exists(rec[f]))
        out.push(`${id}: ${f} ${rec[f]} does not exist`);
    if (!item.script) out.push(`${id}: the item has no script to record`);
    else if (rec.scriptSha256 !== sha(item.script))
      out.push(
        `${id}: the script changed after it was recorded; re-record it (or remove the recording) and update scriptSha256`,
      );
  }
  return out;
}

export function load() {
  const items = loadListening();
  const recordings = JSON.parse(readFileSync(join(ROOT, RECORDINGS), "utf8")).recordings || {};
  return { items, recordings, manifest: buildManifest(items, recordings) };
}

const serialise = (m) => `${JSON.stringify(m, null, 2)}\n`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { manifest } = load();
  const path = join(ROOT, MANIFEST);
  if (process.argv.includes("--check")) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== serialise(manifest)) {
      console.error(
        `${MANIFEST} is stale: run node tools/generate-language-page-audio-manifest.mjs`,
      );
      process.exit(1);
    }
    console.log(
      `generate-language-page-audio-manifest: ${MANIFEST} is current (${manifest.totals.items} scripts, ${manifest.totals.recorded} recorded)`,
    );
  } else {
    writeFileSync(path, serialise(manifest));
    console.log(
      `generate-language-page-audio-manifest: wrote ${MANIFEST} (${manifest.totals.items} scripts)`,
    );
  }
}
