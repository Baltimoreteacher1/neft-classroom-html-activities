#!/usr/bin/env node
/**
 * Internal-link auditor — verifies every internal href/src in the site's source
 * HTML resolves to a real file/dir or a `_redirects` rule. Catches broken
 * navigation before it ships. Run with `npm run audit:links` (exits non-zero on
 * any unresolved link). Skips external URLs and JS-templated links (`${...}`).
 *
 * Note: this is a dev tool and is NOT published (tools/ is excluded from dist).
 */
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, extname, join, resolve } from "node:path";
import { frontRoute } from "../functions/_lib/lp-front.js";
import { routePfa } from "../functions/_lib/pfa/render.js";
import { STUDIOS_BASE } from "../functions/_lib/studios-proxy.js";

const ROOT = process.cwd();
const SKIP_DIRS = new Set([
  "node_modules",
  "dist",
  ".git",
  ".github",
  ".claude",
  ".wrangler",
  ".qa-logs",
  ".playwright-mcp",
  "reports",
]);

// Fixed-name assets that only exist after `vite build` (emitted to dist/assets/),
// so they are absent from the source tree the auditor walks. Keep in lockstep
// with the fixed `entryFileNames` outputs in vite.config.js (hashed bundles are
// never referenced by a static path, so only the fixed-name ones need listing).
const BUILT_ASSETS = new Set(["/assets/homework-lesson-models.js"]);

// The Language Page (lp/, generated by tools/lp/build-site.mjs) is served on thelanguagepage.com from
// this same Pages project: its clean URLs (/content/, /practice/...) are answered by
// functions/_lib/lp-front.js on that host, while its assets and shared files (/lp/assets/, /assets/fonts/,
// /access-teacher/) resolve from the repo root like everywhere else. So a link inside an lp/ page also
// resolves when the front router has that exact route (`page`; a path it does not know is `missing`
// and is still reported). tools/lp/fixtures are pages that are broken ON PURPOSE, to prove the lp
// gates fail when they should; they are not part of any site and are not scanned.
const LP_DIR = join(ROOT, "lp");
const FIXTURES_DIR = join(ROOT, "tools", "lp", "fixtures");

// ---- gather source HTML files ----
const htmlFiles = [];
(function walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith(".")) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (SKIP_DIRS.has(e.name) || p === FIXTURES_DIR) continue;
      walk(p);
    } else if (e.isFile() && e.name.endsWith(".html")) {
      htmlFiles.push(p);
    }
  }
})(ROOT);

// ---- load _redirects source patterns ----
const redirects = [];
const redirPath = join(ROOT, "_redirects");
if (existsSync(redirPath)) {
  for (const line of readFileSync(redirPath, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const src = t.split(/\s+/)[0];
    if (src) redirects.push(src);
  }
}
function redirectCovers(pathname) {
  const bare = pathname.replace(/\/$/, "");
  for (const src of redirects) {
    if (src.endsWith("/*")) {
      if (pathname.startsWith(src.slice(0, -1))) return true;
    } else if (src.includes(":")) {
      const a = src.split("/"),
        b = pathname.split("/");
      if (a.length === b.length && a.every((seg, i) => seg.startsWith(":") || seg === b[i]))
        return true;
    } else if (src === pathname || src === bare) {
      return true;
    }
  }
  return false;
}

function existsTarget(fsPath) {
  if (existsSync(fsPath)) {
    try {
      return statSync(fsPath).isDirectory() ? existsSync(join(fsPath, "index.html")) : true;
    } catch {
      return false;
    }
  }
  if (!extname(fsPath) && existsSync(fsPath + ".html")) return true;
  return false;
}

// The lookbehind keeps `data-only-src="wordlab"` from reading as `src="wordlab"`:
// a hyphenated data attribute is not a link, and flagging it failed the whole gate.
const LINK_RE = /(?<![-\w])(?:href|src)\s*=\s*["']([^"'#]+)["']/gi;
const problems = [];
let linkCount = 0;

for (const file of htmlFiles) {
  const html = readFileSync(file, "utf8");
  const fileDir = dirname(file);
  const seen = new Set();
  let m;
  while ((m = LINK_RE.exec(html))) {
    let url = m[1].trim();
    if (!url) continue;
    if (/^(https?:|mailto:|tel:|data:|javascript:|#|\/\/)/i.test(url)) continue;
    if (url.includes("${") || url.includes("{{")) continue; // template literal
    // JS string-concatenation fragment, e.g. '<a href="/x/" + id + "/">' —
    // the captured value is a partial URL; the next non-space char is `+`.
    if (
      html
        .slice(m.index + m[0].length)
        .trimStart()
        .startsWith("+")
    )
      continue;
    url = url.split("#")[0].split("?")[0];
    // A link is an encoded URL, a file is a name: /x/%5BchapterId%5D/ is the folder [chapterId].
    try {
      url = decodeURI(url);
    } catch {
      /* a malformed escape stays as written and is reported unresolved */
    }
    if (!url || seen.has(url)) continue;
    seen.add(url);
    if (BUILT_ASSETS.has(url)) continue; // resolved by vite build, absent from source
    linkCount++;

    let pathname, fsPath;
    if (url.startsWith("/")) {
      pathname = url;
      fsPath = join(ROOT, url);
      // Vite serves `public/` AT the site root, so /assets/fonts/x.css is a
      // real URL even though no assets/fonts/ exists in the source tree.
      // Resolving only against the repo root reported every such file as a
      // broken link — the file ships, the checker just looked in one place.
      if (!existsTarget(fsPath) && existsTarget(join(ROOT, "public", url))) continue;
    } else {
      fsPath = resolve(fileDir, url);
      pathname = "/" + fsPath.slice(ROOT.length + 1);
    }

    if (existsTarget(fsPath)) continue;
    if (url.startsWith("/") && redirectCovers(pathname)) continue;
    // /studios is a reverse proxy to the Learning Studios Worker (functions/_lib/studios-proxy.js): no files on disk.
    if (pathname === STUDIOS_BASE || pathname.startsWith(`${STUDIOS_BASE}/`)) continue;
    // Practice / Family / Assignments pages are rendered by a Pages Function (functions/_lib/pfa):
    // a link resolves only if the renderer really answers it.
    if (routePfa(pathname)) continue;
    // Language Page front routes, for links written inside lp/ pages.
    if (
      file.startsWith(`${LP_DIR}/`) &&
      url.startsWith("/") &&
      frontRoute(pathname).kind === "page"
    )
      continue;
    problems.push({ file: file.slice(ROOT.length + 1), url });
  }
}

console.log(
  `audit:links — scanned ${htmlFiles.length} HTML files, ${linkCount} unique internal links.`,
);
if (!problems.length) {
  console.log("✓ All internal links resolve.");
  process.exit(0);
}
console.log(`✗ ${problems.length} unresolved internal link(s):`);
const byFile = {};
for (const p of problems) (byFile[p.file] ||= []).push(p.url);
for (const [f, urls] of Object.entries(byFile).sort((a, b) => b[1].length - a[1].length)) {
  console.log(`\n${f}  (${urls.length})`);
  for (const u of [...new Set(urls)]) console.log(`   ✗ ${u}`);
}
process.exit(1);
