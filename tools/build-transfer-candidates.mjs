#!/usr/bin/env node
// Writes data/language-page/transfer-candidates.json: DRAFT cross-subject-transfer candidates for units without any,
// queued for review (nothing is published as reviewed and no review row is written). Rules: tools/language-page/transfer-candidates.mjs
//   node tools/build-transfer-candidates.mjs
import fs from "node:fs";
import { loadDataset } from "./language-page/dataset.mjs";
import {
  buildTransferCandidates,
  MAX_PER_UNIT,
  MIN_VOCAB,
} from "./language-page/transfer-candidates.mjs";

const { units } = await loadDataset();
const missing = units.filter((d) => !d.cross_subject_transfers.length).map((d) => d.unit.id);
const { units: candidates, none } = buildTransferCandidates(units);
fs.writeFileSync(
  new URL("../data/language-page/transfer-candidates.json", import.meta.url),
  `${JSON.stringify(
    {
      note: "DRAFT candidates for units with no cross-subject transfers (F-11). Not reviewed, not shown in the product; each unit is queued for the review workflow block named in `review.block`. Generated by tools/build-transfer-candidates.mjs.",
      status: "draft",
      rule: {
        min_shared_terms: MIN_VOCAB,
        max_per_unit: MAX_PER_UNIT,
        same_grade_other_subject: true,
      },
      units_without_transfers: missing,
      candidates,
      none,
    },
    null,
    1,
  )}\n`,
);
console.log(
  `${missing.length} units without transfers; ${Object.keys(candidates).length} with candidates (${Object.values(candidates).flat().length} links); none: ${none.join(", ")}`,
);
