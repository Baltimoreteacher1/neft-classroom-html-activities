#!/usr/bin/env node
/**
 * import-session1-practice.mjs — read the district's Reveal "Session 1" practice
 * sheets into `data/reveal-session1-source.json`.
 *
 * The printed practice worksheets (scripts/generate-worksheets.mjs) open every
 * core lesson with the same support page the district sheet opens with — the
 * words for the lesson, a worked example, a NOW YOU TRY with the numbers blank,
 * and the sentence starters — so the packet a student takes home matches the
 * sheet the class worked from. That material lives in `~/Desktop/Reveal Math by
 * Unit and Lesson/`, outside the repo, so it is snapshotted here for the same
 * reason tools/import-session2-practice.mjs snapshots Session 2: a build must
 * not read a laptop's Desktop.
 *
 * IT EXTRACTS, IT DOES NOT DERIVE. Every field is text the docx states.
 *
 *   node tools/import-session1-practice.mjs           # write
 *   node tools/import-session1-practice.mjs --check    # fail if stale
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parsePractice, REVEAL_ROOT, revealLessonDirs } from "./lib/reveal-docx.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(ROOT, "data/reveal-session1-source.json");
const CHECK = process.argv.includes("--check");

if (!existsSync(REVEAL_ROOT)) {
  console.error(`Reveal source not found at ${REVEAL_ROOT} — nothing to import.`);
  process.exit(CHECK ? 0 : 1);
}

const lessons = [];
for (const { unit, lesson, base } of revealLessonDirs()) {
  const practice = join(base, "Practice", `${unit}.${lesson} Session 1.docx`);
  if (!existsSync(practice)) continue;
  lessons.push({ id: `${unit}-${lesson}`, unit, lesson, ...parsePractice(practice) });
}

const payload = {
  $comment:
    "GENERATED by tools/import-session1-practice.mjs from the district Reveal Session 1 practice sheets — do not hand-edit. Extracted text only: no answer is computed here.",
  importedLessons: lessons.length,
  lessons,
};
const serialized = `${JSON.stringify(payload, null, 2)}\n`;

if (CHECK) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, "utf8") : "";
  if (current !== serialized) {
    console.error("import-session1-practice --check: data/reveal-session1-source.json is stale");
    process.exit(1);
  }
  console.log(`import-session1-practice --check: up to date (${lessons.length} lessons)`);
} else {
  writeFileSync(OUTPUT, serialized);
  console.log(`Imported ${lessons.length} Session 1 lessons to ${OUTPUT}`);
}
