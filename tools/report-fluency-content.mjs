// Publisher content report for the Math Fluency Lab item bank (Phase 6F): every figure is computed from the files on
// disk by the same validator that gates the bank, and nothing is estimated. Writes docs/fluency-content-report.md.
//   node tools/report-fluency-content.mjs [--check]     (--check fails if the committed report is stale)
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { coverageMatrix, summarizeBank } from "../math/fluency-lab/e8/coverage.js";
import { buildGraph } from "../math/fluency-lab/e8/knowledge-graph.js";
import { MISCONCEPTIONS } from "../math/fluency-lab/e8/misconception-library.js";
import { CCSS, validateBank } from "./lib/fluency-content.mjs";

const root = new URL("../", import.meta.url);
const out = new URL("docs/fluency-content-report.md", root);
const skills = new Set(buildGraph().nodes.keys());
const miscIds = new Set(MISCONCEPTIONS.map((m) => m.id));
const counted = [];
const rejected = [];
const perGrade = {};
for (let g = 0; g <= 8; g += 1) {
  const f = new URL(`math/fluency-lab/content/items/grade-${g}.json`, root);
  if (!existsSync(f)) continue;
  const items = JSON.parse(readFileSync(f, "utf8"));
  const res = await validateBank(items, { skills, misconceptionIds: miscIds });
  counted.push(...res.counted);
  rejected.push(...res.rejected);
  perGrade[g] = {
    authored: items.length,
    counted: res.counted.length,
    rejected: res.rejected.length,
  };
}
const standards = CCSS.standards;
const sum = summarizeBank(counted, standards);
const nums = (t) =>
  (String(t).match(/\d+(?:[.,]\d+)?/g) || [])
    .map((n) => n.replace(",", "."))
    .sort()
    .join(",");
const numberMismatch = counted.filter((i) => nums(i.stem.en) !== nums(i.stem.es));
const words = (t) => String(t).trim().split(/\s+/).filter(Boolean).length;
const mcPos = { A: 0, B: 0, C: 0, D: 0, E: 0 };
for (const i of counted.filter((x) => x.type === "mc"))
  mcPos[i.answer.correct] = (mcPos[i.answer.correct] || 0) + 1;
const mcTotal = Object.values(mcPos).reduce((a, b) => a + b, 0);
const wrongWithFeedback = counted
  .filter((i) => i.type === "mc")
  .flatMap((i) => i.choices.filter((c) => c.id !== i.answer.correct));
const tagged = counted.filter((i) => (i.misconceptions || []).length).length;
const table = (rows) => rows.map((r) => `| ${r.join(" | ")} |`).join("\n");

const lines = [];
lines.push("# Math Fluency Lab item bank: content report", "");
lines.push(
  "Generated by `node tools/report-fluency-content.mjs` from the files in `math/fluency-lab/content/items/`. Every figure below is computed, not estimated. The bank is **original, machine-verified, AI-drafted content that has not had an outside expert review**; each item says so in its `provenance` field.",
  "",
);
lines.push("## What was verified, and what was not", "");
lines.push(
  "- **Verified by machine:** every counted item has a complete prompt, three hints (the first two never state the answer), a worked solution, a Spanish stem, and an answer proven with exact rational arithmetic (or, for a bounded share of conceptual items, flagged for human review). The proof is re-run on every `npm run validate`.",
);
lines.push(
  "- **Not verified:** pedagogical quality, reading level, cultural fit, and the quality of the Spanish. No educator, psychometrician or translator has reviewed this bank. Item difficulty and DOK levels are the author's labels, not calibrated statistics.",
  "",
);
lines.push("## Totals", "");
lines.push(
  `- Items counted (passing every check): **${counted.length}**`,
  `- Items rejected by the validator: **${rejected.length}**`,
  `- Items marked expert-reviewed: **${sum.reviewed}**`,
  `- Conceptual items needing human review of their key: **${sum.conceptual}** (${((sum.conceptual / Math.max(1, counted.length)) * 100).toFixed(1)}%, cap 30% per grade)`,
  "",
);
lines.push(
  "| Grade | Authored | Counted | Rejected | Standards covered | Standards with no items | Standards with fewer than 3 |",
  "|---|---|---|---|---|---|---|",
);
for (const [g, s] of Object.entries(perGrade)) {
  const b = sum.byGrade[g];
  lines.push(
    `| ${g === "0" ? "K" : g} | ${s.authored} | ${s.counted} | ${s.rejected} | ${b ? `${b.standardsWithItems}/${b.standards}` : "-"} | ${b?.bare.length ?? "-"} | ${b?.thin.length ?? "-"} |`,
  );
}
lines.push(
  "",
  "Target: at least 200 counted items in each of Grades 1 to 8 (1,600 in all). Kindergarten has no authored items.",
  "",
);
const short = Object.entries(perGrade).filter(([g, s]) => g !== "0" && s.counted < 200);
lines.push(
  short.length
    ? `**Shortfall:** ${short.map(([g, s]) => `Grade ${g} has ${s.counted}`).join("; ")}.`
    : "**Target met:** every one of Grades 1 to 8 has at least 200 counted items.",
  "",
);
lines.push("## Depth of knowledge and item types", "");
lines.push(
  table([["DOK", "Items"], ...Object.entries(sum.dok).map(([k, v]) => [k, v])]).replace(
    /^\| DOK \| Items \|/,
    "| DOK | Items |\n|---|---|",
  ),
  "",
);
lines.push(
  table([
    ["Type", "Items"],
    ...Object.entries(sum.types)
      .sort((a, b) => b[1] - a[1])
      .map(([k, v]) => [k, v]),
  ]).replace(/^\| Type \| Items \|/, "| Type | Items |\n|---|---|"),
  "",
);
lines.push("## Integrity audits", "");
lines.push(
  `- Correct-answer position in multiple-choice items: ${Object.entries(mcPos)
    .filter(([, v]) => v)
    .map(([k, v]) => `${k} ${((v / mcTotal) * 100).toFixed(0)}%`)
    .join(", ")} (n=${mcTotal}).`,
);
lines.push(
  `- Wrong multiple-choice options: ${wrongWithFeedback.length}, of which ${wrongWithFeedback.filter((c) => c.why).length} carry feedback that names the likely slip.`,
);
lines.push(`- Items tagged with a library misconception: ${tagged} of ${counted.length}.`);
lines.push(
  `- Items whose English and Spanish stems carry different numbers: **${numberMismatch.length}**${
    numberMismatch.length
      ? ` (${numberMismatch
          .slice(0, 8)
          .map((i) => i.id)
          .join(", ")}${numberMismatch.length > 8 ? ", ..." : ""})`
      : ""
  }.`,
);
lines.push(
  `- Median stem length: ${[...counted.map((i) => words(i.stem.en))].sort((a, b) => a - b)[counted.length >> 1] ?? 0} words (Grades 1 and 2 are held to 25 words by the authoring brief).`,
);
lines.push(
  `- Near-duplicate stems (same wording, only numbers changed) are rejected by the validator at a similarity of 0.82 or more within a grade.`,
  "",
);
lines.push("## Standards with the fewest items", "");
const thin = coverageMatrix(counted, standards)
  .filter((r) => r.grade >= 1)
  .sort((a, b) => a.count - b.count)
  .slice(0, 12);
lines.push(
  "| Standard | Items | Text |",
  "|---|---|---|",
  ...thin.map((r) => `| ${r.code} | ${r.count} | ${r.text} |`),
  "",
);
lines.push("## Known limits", "");
lines.push(
  "- Spanish was written alongside the English by the same author and has not been reviewed by a fluent educator.",
  "- Some conceptual items (for example classifying shapes) cannot be proven by computation and rely on the author's key until a person reviews them.",
  "- The adaptive placement and mastery rules use transparent thresholds, not a calibrated psychometric model.",
  "- Kindergarten is not covered.",
  "",
);

const text = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  const current = existsSync(out) ? readFileSync(out, "utf8") : "";
  if (current !== text) {
    console.error(
      "docs/fluency-content-report.md is stale. Run: node tools/report-fluency-content.mjs",
    );
    process.exit(1);
  }
  console.log(`fluency content report is current (${counted.length} items)`);
} else {
  mkdirSync(new URL("docs/", root), { recursive: true });
  writeFileSync(out, text);
  console.log(
    `wrote docs/fluency-content-report.md (${counted.length} items counted, ${rejected.length} rejected)`,
  );
}
