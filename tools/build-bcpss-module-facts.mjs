// Regenerates db/seeds/bcpss/v2/module-facts/<unitId>.mjs: the district Wit & Wisdom pacing-guide facts for ELA units
// 1-3 (module dates, introduction, end-of-module task, anchor texts, the module's weeks) and a suggested week for
// each lesson companion. Source: data/ela-modules.json (tools/extract-ela-modules.mjs); mapping: tools/lib/ela-module-facts.mjs.
// Usage: node tools/build-bcpss-module-facts.mjs [--check]
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as seed from "../data/bcpss-curriculum-seed.mjs";
import { loadLessons } from "../functions/_lib/bcpss/lessons.js";
import { lessonRange, placeLessons, splitModuleLine } from "./lib/ela-module-facts.mjs";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repo, "db/seeds/bcpss/v2/module-facts");
const check = process.argv.includes("--check");
const data = JSON.parse(readFileSync(path.join(repo, "data/ela-modules.json"), "utf8"));
const SOURCE = "District Wit & Wisdom pacing guide, SY 2025-26";

const files = new Map();
for (const unit of seed.BCPSS_UNITS) {
  if (unit.subject !== "ELA" || unit.unit_number > 3) continue; // Module 4 is not in the district files
  const mod = data.modules.find((m) => m.grade === unit.grade && m.module === unit.unit_number);
  if (!mod) throw new Error(`no module data for ${unit.id}`);
  const set = await loadLessons(unit.id);
  if (!set) throw new Error(`no lessons for ${unit.id}`);
  const split = splitModuleLine(mod.moduleLine);
  const zero = new Set(mod.moduleZeroInWeeks);
  // Module 0 (Start Strong) is the opening weeks of the Module 1 guide; lessons are placed after it.
  const eligible = mod.weeks.filter((w) => !zero.has(w.n)).map((w) => w.n);
  const placed = placeLessons({ lessons: set.lessons, weeks: mod.weeks, eligible });
  const out = {
    unit_id: unit.id,
    module: mod.module,
    source: `${SOURCE}, Module ${mod.module}`,
    title: split?.title ?? null,
    essential_question: split?.essential_question ?? null,
    writing: split?.writing ?? null,
    start: mod.dates.start,
    end: mod.dates.end,
    introduction: mod.introduction,
    end_of_module_task: mod.endOfModuleTask,
    anchor_texts: mod.anchorTexts.slice(0, 12),
    module_zero_weeks: mod.moduleZeroInWeeks,
    weeks: mod.weeks.map((w) => ({
      n: w.n,
      label: w.label,
      start: w.start,
      end: w.end,
      lessons: lessonRange(w.lessonNumbers),
      texts: w.texts.slice(0, 4),
    })),
    lesson_weeks: placed,
  };
  const rows = (list) => `[\n${list.map((x) => `  ${JSON.stringify(x)}`).join(",\n")}\n ]`;
  const fields = Object.entries(out)
    .map(
      ([k, v]) =>
        ` ${JSON.stringify(k)}: ${["weeks", "lesson_weeks"].includes(k) ? rows(v) : JSON.stringify(v)}`,
    )
    .join(",\n");
  files.set(
    `${unit.id}.mjs`,
    `// GENERATED by tools/build-bcpss-module-facts.mjs — do not edit.\n// District module facts for ${unit.id}.\n\nexport default {\n${fields}\n};\n`,
  );
}

if (check) {
  let have = [];
  try {
    have = readdirSync(outDir).filter((f) => f.endsWith(".mjs"));
  } catch {}
  const stale = [];
  for (const [name, body] of files) {
    let cur = "";
    try {
      cur = readFileSync(path.join(outDir, name), "utf8");
    } catch {}
    if (cur !== body) stale.push(name);
    have = have.filter((f) => f !== name);
  }
  for (const extra of have) stale.push(`${extra} (no such unit)`);
  if (stale.length) {
    console.error(
      `module-facts is stale (${stale.length} file(s), e.g. ${stale[0]}): run node tools/build-bcpss-module-facts.mjs`,
    );
    process.exit(1);
  }
  console.log(`module-facts current (${files.size} units)`);
} else {
  mkdirSync(outDir, { recursive: true });
  for (const f of readdirSync(outDir))
    if (f.endsWith(".mjs") && !files.has(f)) rmSync(path.join(outDir, f));
  for (const [name, body] of files) writeFileSync(path.join(outDir, name), body);
  console.log(`wrote ${files.size} unit files to db/seeds/bcpss/v2/module-facts`);
}
