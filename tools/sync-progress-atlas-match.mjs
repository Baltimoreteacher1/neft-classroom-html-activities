#!/usr/bin/env node
/* =============================================================================
 * sync-progress-atlas-match.mjs — keep the Learning Atlas on the ONE answer
 * matcher the rest of the site uses.
 * -----------------------------------------------------------------------------
 * assets/my-progress/progress-atlas-match.js is a classic script (the My
 * Progress pages are static HTML and /engine/ is not served), so it cannot
 * import engine/core/answer-match.js. It is generated from that file instead,
 * through the same emitter the homework pages and the Study Pack engine use
 * (scripts/homework-answer-match.mjs), and exposes `NTAnswerMatch.isRight`.
 *
 *   node tools/sync-progress-atlas-match.mjs           rewrite the asset
 *   node tools/sync-progress-atlas-match.mjs --check   exit 1 when it is stale
 * ========================================================================== */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { CORE_ANSWER_MATCH_JS } from "../scripts/homework-answer-match.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const TARGET = resolve(ROOT, "assets/my-progress/progress-atlas-match.js");

export function expected() {
  return [
    "/* GENERATED by tools/sync-progress-atlas-match.mjs from engine/core/answer-match.js — do not edit. */",
    CORE_ANSWER_MATCH_JS,
    '(typeof window !== "undefined" ? window : globalThis).NTAnswerMatch = NTAnswerMatch;',
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const want = expected();
  let have = "";
  try {
    have = readFileSync(TARGET, "utf8");
  } catch (_e) {
    /* missing: handled below */
  }
  if (process.argv.includes("--check")) {
    if (have !== want) {
      console.error(
        "progress-atlas-match.js is stale — run: node tools/sync-progress-atlas-match.mjs",
      );
      process.exit(1);
    }
    console.log("progress-atlas-match.js is current.");
  } else if (have !== want) {
    writeFileSync(TARGET, want);
    console.log("progress-atlas-match.js refreshed.");
  } else {
    console.log("progress-atlas-match.js already current.");
  }
}
