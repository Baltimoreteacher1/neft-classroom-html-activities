#!/usr/bin/env node
// Compiles engine/design/tokens.json into engine/styles/ds-tokens.generated.css
// and prints the computed contrast table used by docs/style-guide.md.
//
//   node tools/build-design-tokens.mjs           write the CSS
//   node tools/build-design-tokens.mjs --check   fail if the CSS on disk is stale
//   node tools/build-design-tokens.mjs --table   print the contrast table (markdown)
//
// It FAILS (exit 1) when a declared contrast pair misses its floor, or when any
// token falls in the forbidden violet/purple/magenta hue range. Nothing about
// colour in the guide is typed by hand: tints and "ink" variants are derived
// here, and every ratio is computed here.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  contrast,
  darkenToContrast,
  isForbiddenHue,
  mix,
  over,
  parseColor,
  toHex,
} from "./lib/color-math.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// The env overrides exist so tools/design-tokens.test.mjs can drive the REAL script at seeded defects.
const SRC = process.env.DS_TOKENS_SRC || resolve(ROOT, "engine/design/tokens.json");
const OUT = process.env.DS_TOKENS_OUT || resolve(ROOT, "engine/styles/ds-tokens.generated.css");
const GUIDE = process.env.DS_TOKENS_GUIDE || resolve(ROOT, "docs/style-guide.md");
const BEGIN = "<!-- contrast-table:begin -->";
const END = "<!-- contrast-table:end -->";

export function buildTokens(tokens) {
  const base = {};
  for (const [k, v] of Object.entries(tokens.palette)) {
    const c = parseColor(v);
    if (!c) throw new Error(`palette.${k}: not a colour: ${v}`);
    base[k] = c;
  }
  const colours = { ...base };
  const d = tokens.derive;
  for (const key of ["tealInk", "amberInk"]) {
    const rule = d[key];
    colours[key] = darkenToContrast(
      base[rule.from],
      rule.onBackgrounds.map((n) => base[n]),
      rule.minContrast,
    );
  }
  {
    const rule = d.muted;
    const lifted = mix(base[rule.from], base[rule.toward], rule.amount);
    colours.muted = darkenToContrast(
      lifted,
      rule.onBackgrounds.map((n) => base[n]),
      rule.minContrast,
    );
  }
  const tints = {};
  for (const name of ["navy", "teal", "amber", "success", "error"]) {
    for (const pct of d.tintSteps) tints[`${name}-${pct}`] = mix(base.white, base[name], pct / 100);
  }
  return { base, colours, tints };
}

function resolveRole(spec, colours, canvas) {
  if (spec.includes("@")) {
    const [name, pct] = spec.split("@");
    const c = colours[name];
    return {
      css: `rgba(${Math.round(c.r)}, ${Math.round(c.g)}, ${Math.round(c.b)}, ${Number(pct) / 100})`,
      solid: over({ ...c, a: Number(pct) / 100 }, canvas),
    };
  }
  return { css: toHex(colours[spec]), solid: colours[spec] };
}

export function checkPairs(tokens, colours) {
  return tokens.contrastPairs.map((p) => {
    const fg = colours[p.fg];
    const bg = colours[p.bg];
    const ratio = contrast(fg, bg);
    return { ...p, ratio, ok: ratio >= p.min };
  });
}

export function forbiddenRows(tokens, colours) {
  return (tokens.forbiddenPairs || []).map((p) => ({
    ...p,
    ratio: contrast(colours[p.fg], colours[p.bg]),
  }));
}

export function render(tokens) {
  const { colours, tints } = buildTokens(tokens);
  const lines = [];
  lines.push(
    "/* GENERATED by tools/build-design-tokens.mjs from engine/design/tokens.json. Do not edit.",
    "   All names are namespaced --ds-* so they cannot collide with page-level or engine variables. */",
    ":root {",
  );
  for (const [k, c] of Object.entries(colours))
    lines.push(`  --ds-color-${k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)}: ${toHex(c)};`);
  for (const [k, c] of Object.entries(tints)) lines.push(`  --ds-tint-${k}: ${toHex(c)};`);
  for (const [role, spec] of Object.entries(tokens.roles))
    lines.push(`  --ds-${role}: ${resolveRole(spec, colours, colours.canvas).css};`);
  const t = tokens.type;
  for (const [k, v] of Object.entries(t.families)) lines.push(`  --ds-font-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.scale)) lines.push(`  --ds-text-${k}: ${v}rem;`);
  for (const [k, v] of Object.entries(t.lineHeight)) lines.push(`  --ds-leading-${k}: ${v};`);
  for (const [k, v] of Object.entries(t.weights)) lines.push(`  --ds-weight-${k}: ${v};`);
  lines.push(`  --ds-measure: ${t.measureCh.max}ch;`);
  for (const [k, v] of Object.entries(tokens.space)) lines.push(`  --ds-space-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.radius)) lines.push(`  --ds-radius-${k}: ${v}px;`);
  for (const [k, v] of Object.entries(tokens.elevation)) lines.push(`  --ds-elevation-${k}: ${v};`);
  const m = tokens.motion;
  lines.push(
    `  --ds-duration-fast: ${m.fastMs}ms;`,
    `  --ds-duration-base: ${m.baseMs}ms;`,
    `  --ds-duration-slow: ${m.slowMs}ms;`,
    `  --ds-duration-celebrate: ${m.celebrateMs}ms;`,
    `  --ds-easing: ${m.easing};`,
  );
  lines.push(`  --ds-target: ${tokens.target.minPx}px;`, "}", "");
  return lines.join("\n");
}

export function contrastTable(tokens) {
  const { colours } = buildTokens(tokens);
  const rows = checkPairs(tokens, colours);
  const out = ["| Foreground | Background | Ratio | Needs | Used for |", "|---|---|---:|---:|---|"];
  for (const r of rows)
    out.push(
      `| ${r.fg} \`${toHex(colours[r.fg])}\` | ${r.bg} \`${toHex(colours[r.bg])}\` | ${r.ratio.toFixed(2)} | ${r.min} | ${r.use} |`,
    );
  out.push("", "| Never use | Ratio | Why |", "|---|---:|---|");
  for (const r of forbiddenRows(tokens, colours))
    out.push(`| ${r.fg} text/graphic on ${r.bg} | ${r.ratio.toFixed(2)} | ${r.why} |`);
  return out.join("\n");
}

/** The guide with its computed contrast table spliced between the markers. */
export function guideWithTable(guide, table) {
  const a = guide.indexOf(BEGIN);
  const b = guide.indexOf(END);
  if (a < 0 || b < a) throw new Error("docs/style-guide.md is missing its contrast-table markers");
  return `${guide.slice(0, a + BEGIN.length)}\n${table}\n${guide.slice(b)}`;
}

function main() {
  const tokens = JSON.parse(readFileSync(SRC, "utf8"));
  const { colours, tints } = buildTokens(tokens);
  const problems = [];
  for (const r of checkPairs(tokens, colours))
    if (!r.ok)
      problems.push(
        `contrast ${r.fg} on ${r.bg} is ${r.ratio.toFixed(2)}, needs ${r.min} (${r.use})`,
      );
  for (const [k, c] of [...Object.entries(colours), ...Object.entries(tints)])
    if (isForbiddenHue(c))
      problems.push(`token ${k} ${toHex(c)} is in the forbidden violet/purple/magenta hue range`);
  if (problems.length) {
    console.error(`FAIL build-design-tokens:\n  ${problems.join("\n  ")}`);
    process.exit(1);
  }
  if (process.argv.includes("--table")) {
    console.log(contrastTable(tokens));
    return;
  }
  const css = render(tokens);
  if (process.argv.includes("--check")) {
    let onDisk = "";
    try {
      onDisk = readFileSync(OUT, "utf8");
    } catch {}
    const guide = readFileSync(GUIDE, "utf8");
    if (guideWithTable(guide, contrastTable(tokens)) !== guide) {
      console.error(
        "FAIL build-design-tokens --check: the contrast table in docs/style-guide.md is stale; run `node tools/build-design-tokens.mjs`",
      );
      process.exit(1);
    }
    if (onDisk !== css) {
      console.error(
        "FAIL build-design-tokens --check: engine/styles/ds-tokens.generated.css is stale; run `node tools/build-design-tokens.mjs`",
      );
      process.exit(1);
    }
    console.log(
      `PASS build-design-tokens --check (${tokens.contrastPairs.length} contrast pairs, ${Object.keys(colours).length + Object.keys(tints).length} colour tokens, none forbidden)`,
    );
    return;
  }
  writeFileSync(OUT, css);
  const guide = readFileSync(GUIDE, "utf8");
  writeFileSync(GUIDE, guideWithTable(guide, contrastTable(tokens)));
  console.log(`wrote ${OUT} (${css.split("\n").length} lines)`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
