#!/usr/bin/env node
/* Emits BOTH Cloudflare route artifacts from data/routes.json:
 *
 *   _redirects                    — the static Pages redirect file
 *   functions/_lib/redirect-map.js — the same rules as a module the Pages
 *                                    Function imports at runtime
 *
 * Why two. Cloudflare honours only the first 100 rules of `_redirects` on this
 * project: rules 1-100 return 301 and 101+ return 404, verified live against
 * production (positions 90/95/100 redirect; 101/102/105/110/150/200 do not).
 * The documented limit is 2,000 static + 100 dynamic and this file holds 333
 * rules of which 12 are dynamic, so the cutoff is not explained by the docs —
 * but it is exact and reproducible, and it had silently killed 231 short links.
 *
 * functions/_middleware.js consumes the map as a 404 FALLBACK, so a rule can
 * only ever change a response that is already a 404. Nothing that resolves
 * today can be shadowed by it, and the first 100 rules keep working exactly as
 * they do now — they are served by Pages before the fallback is ever consulted.
 *
 * Run with --check to fail instead of writing (used by tools/validate-static-site
 * and the redirect-map test) so a routes.json edit cannot ship half-applied.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();
const registryPath = resolve(root, "data/routes.json");
const redirectsPath = resolve(root, "_redirects");
const mapPath = resolve(root, "functions/_lib/redirect-map.js");
const CHECK = process.argv.includes("--check");
const registry = JSON.parse(readFileSync(registryPath, "utf8"));

validateRegistry(registry);
const stale = [
  writeRedirects(registry.redirects || [], registry.rewrites || []),
  writeRedirectMap(registry.redirects || []),
].filter(Boolean);

if (CHECK) {
  if (stale.length) {
    console.error(`Route files are stale: ${stale.join(", ")}. Run \`npm run generate-routes\`.`);
    process.exit(1);
  }
  console.log("Route files are up to date.");
} else {
  console.log("Generated Cloudflare route files from data/routes.json");
}

// Write `text` to `file` unless unchanged. In --check mode never writes; returns
// the file's basename when it WOULD have changed, so the caller can report it.
function emit(file, text) {
  let prev = null;
  try {
    prev = readFileSync(file, "utf8");
  } catch {
    /* first run */
  }
  if (prev === text) return null;
  if (!CHECK) writeFileSync(file, text, "utf8");
  return file.slice(root.length + 1);
}

function writeRedirects(redirects, rewrites) {
  const lines = [
    "# Cloudflare Pages redirects for Neft Hub static site",
    "# Generated from data/routes.json by tools/generate-route-files.mjs",
    "# Format: [source] [destination] [status]",
    "",
  ];

  for (const redirect of redirects) {
    lines.push(`${redirect.source} ${redirect.destination} ${redirect.status || 301}`);
  }

  // Status-200 rewrites (SPA fallbacks). Existing static assets always take
  // precedence over a 200 rewrite, so these only catch otherwise-unmatched
  // paths under their source prefix (e.g. clean History-API deep links).
  if (rewrites.length) {
    lines.push("", "# SPA rewrites (status 200) — keep below redirects");
    for (const rewrite of rewrites) {
      lines.push(`${rewrite.source} ${rewrite.destination} ${rewrite.status || 200}`);
    }
  }

  lines.push("");
  return emit(redirectsPath, lines.join("\n"));
}

/* The same redirects, as data the Pages Function can consult. Splat rules become
 * prefix entries; everything else is an exact-path entry. Rewrites are NOT
 * included — a 200 rewrite is asset routing, not a redirect, and Pages already
 * applies those correctly. */
function writeRedirectMap(redirects) {
  const exact = {};
  const prefix = [];

  for (const r of redirects) {
    const status = Number(r.status || 301);
    if (r.source.endsWith("/*")) {
      prefix.push([r.source.slice(0, -1), r.destination, status, r.destination.includes(":splat")]);
    } else {
      // First rule wins, matching how Pages evaluates `_redirects` top-down.
      if (!(r.source in exact)) exact[r.source] = [r.destination, status];
    }
  }

  const raw = `/* GENERATED by tools/generate-route-files.mjs — do not hand-edit.
 * Source: data/routes.json. Regenerate with \`npm run generate-routes\`.
 *
 * Cloudflare honours only the first 100 rules of _redirects on this project, so
 * functions/_middleware.js replays these as a 404 fallback. See the header of
 * the generator for the measurement behind that claim. */

/** path -> [destination, status] */
export const EXACT = ${JSON.stringify(exact, null, 2)};

/** [prefix, destination, status, destinationTakesSplat] */
export const PREFIX = ${JSON.stringify(prefix, null, 2)};
`;

  const body = execFileSync("npx", ["biome", "format", `--stdin-file-path=${mapPath}`], {
    input: raw,
    encoding: "utf8",
    cwd: root,
  });
  return emit(mapPath, body);
}

function validateRegistry(value) {
  const errors = [];
  const ids = new Set();
  const paths = new Set();

  if (!Array.isArray(value.routes)) errors.push("routes must be an array");
  if (!Array.isArray(value.redirects)) errors.push("redirects must be an array");
  if (value.rewrites !== undefined && !Array.isArray(value.rewrites))
    errors.push("rewrites must be an array when present");

  for (const route of value.routes || []) {
    if (!route.id) errors.push("route missing id");
    if (!route.title) errors.push(`${route.id || "unknown route"} missing title`);
    if (!route.path || !route.path.startsWith("/"))
      errors.push(`${route.id || "unknown route"} has invalid path`);
    if (!Array.isArray(route.family) || route.family.length === 0)
      errors.push(`${route.id || "unknown route"} missing family array`);
    if (ids.has(route.id)) errors.push(`duplicate route id: ${route.id}`);
    if (paths.has(route.path)) errors.push(`duplicate route path: ${route.path}`);
    ids.add(route.id);
    paths.add(route.path);
  }

  for (const redirect of value.redirects || []) {
    if (!redirect.source?.startsWith("/"))
      errors.push(`invalid redirect source: ${redirect.source}`);
    if (!redirect.destination?.startsWith("/") && !redirect.destination?.startsWith("http"))
      errors.push(`invalid redirect destination for ${redirect.source}`);
    if (![301, 302, 307, 308].includes(Number(redirect.status || 301)))
      errors.push(`invalid redirect status for ${redirect.source}`);
  }

  for (const rewrite of value.rewrites || []) {
    if (!rewrite.source?.startsWith("/")) errors.push(`invalid rewrite source: ${rewrite.source}`);
    if (!rewrite.destination?.startsWith("/"))
      errors.push(`invalid rewrite destination for ${rewrite.source}`);
    if (Number(rewrite.status || 200) !== 200)
      errors.push(`rewrite status must be 200 for ${rewrite.source}`);
  }

  if (errors.length) {
    console.error("Route registry validation failed:");
    errors.forEach((error) => console.error(`- ${error}`));
    process.exit(1);
  }
}
