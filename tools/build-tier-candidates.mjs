#!/usr/bin/env node
// Builds the repo-resident word-frequency list, the tier reclassification candidates and the tier baseline
// (data/language-page/*.json). Rubric and limits: tools/language-page/tier-rubric.mjs.
// Re-tiering is Joel's decision (D5): this script never edits a seed. Nothing in `approved` is applied either.
//   node tools/build-tier-candidates.mjs
import fs from "node:fs";
import { loadDataset } from "./language-page/dataset.mjs";
import {
  buildCandidates,
  buildWordFrequency,
  RUBRIC,
  tierSnapshot,
} from "./language-page/tier-rubric.mjs";

const OUT = new URL("../data/language-page/", import.meta.url);
const write = (name, value) =>
  fs.writeFileSync(new URL(name, OUT), `${JSON.stringify(value, null, 1)}\n`);
// One word per line keeps the 3,000-word list diffable without the indent bloat.
const writeList = (name, { meta, words }) =>
  fs.writeFileSync(
    new URL(name, OUT),
    `{"meta":${JSON.stringify(meta)},\n"words":{\n${Object.entries(words)
      .map(([w, e]) => `${JSON.stringify(w)}:${JSON.stringify(e)}`)
      .join(",\n")}\n}}\n`,
  );

const { units } = await loadDataset();
const list = buildWordFrequency(units);
const { candidates, counts } = buildCandidates(list, units);
fs.mkdirSync(OUT, { recursive: true });
writeList("word-frequency.json", list);
write("tier-baseline.json", {
  note: "Tiers as of the audit. G-43 fails if a tier differs from this unless the (unit, term) is listed in `approved` by Joel.",
  approved: [],
  tiers: tierSnapshot(units),
});
write("tier-candidates.json", {
  note: "Reclassification CANDIDATES for Joel (D5). No tier was changed. Generated by tools/build-tier-candidates.mjs.",
  status: "draft",
  rubric: RUBRIC,
  counts,
  candidates,
});
console.log(JSON.stringify(counts), `${Object.keys(list.words).length} words in list`);
