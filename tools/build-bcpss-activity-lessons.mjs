// Regenerates db/seeds/bcpss/v2/lesson-links/<unitId>.mjs: which lesson companion(s) each Language Studio activity
// belongs to, the reverse index (which activities each lesson practises), and, for Grade 6 math, the Reveal Math
// lessons that teach the same vocabulary. The mapping rules live in tools/lib/bcpss-activity-lessons.mjs.
// Usage: node tools/build-bcpss-activity-lessons.mjs [--check]
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as seed from "../data/bcpss-curriculum-seed.mjs";
import { loadLessons } from "../functions/_lib/bcpss/lessons.js";
import { loadStudio } from "../functions/_lib/bcpss/studio.js";
import { linkUnit, revealFor } from "./lib/bcpss-activity-lessons.mjs";
import { loadCurriculumManifest, loadLessonConfig } from "./lib/curriculum-source.mjs";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(repo, "db/seeds/bcpss/v2/lesson-links");
const check = process.argv.includes("--check");

/** Reveal Math lessons this repo carries: id, unit, English title and the lesson's own vocabulary terms. */
function revealCatalog() {
  const out = [];
  for (const l of loadCurriculumManifest().lessons) {
    const terms = (loadLessonConfig(l.id).vocabulary || []).map((v) => v.term).filter(Boolean);
    if (terms.length) out.push({ id: l.id, unit: l.unit, title: l.title.en, terms });
  }
  return out;
}

const reveal = revealCatalog();
const files = new Map();
for (const unit of seed.BCPSS_UNITS) {
  const studio = await loadStudio(unit.id);
  const set = await loadLessons(unit.id);
  if (!studio || !set) throw new Error(`no studio or lessons for ${unit.id}`);
  const linked = linkUnit({ studio, lessons: set.lessons });
  const revealByLesson =
    unit.grade === "6" && unit.subject === "Math"
      ? new Map(revealFor({ lessons: set.lessons, reveal }).map((r) => [r.id, r.reveal]))
      : new Map();
  const data = {
    unit_id: unit.id,
    activities: linked.activities,
    lessons: linked.lessons.map((l) => ({
      ...l,
      ...(revealByLesson.get(l.id)?.length ? { reveal: revealByLesson.get(l.id) } : {}),
    })),
  };
  // One compact line per activity / lesson row keeps the files small and the diffs readable.
  const rows = (list) => `[\n${list.map((x) => `  ${JSON.stringify(x)}`).join(",\n")}\n ]`;
  const fields = Object.entries(data)
    .map(
      ([key, value]) =>
        ` ${JSON.stringify(key)}: ${Array.isArray(value) ? rows(value) : JSON.stringify(value)}`,
    )
    .join(",\n");
  files.set(
    `${unit.id}.mjs`,
    `// GENERATED by tools/build-bcpss-activity-lessons.mjs — do not edit.\n// Activity-to-lesson links for ${unit.id}.\n\nexport default {\n${fields}\n};\n`,
  );
}

if (check) {
  const have = new Set(readdirSync(outDir).filter((f) => f.endsWith(".mjs")));
  const stale = [];
  for (const [name, body] of files) {
    let cur = "";
    try {
      cur = readFileSync(path.join(outDir, name), "utf8");
    } catch {}
    if (cur !== body) stale.push(name);
    have.delete(name);
  }
  for (const extra of have) stale.push(`${extra} (no such unit)`);
  if (stale.length) {
    console.error(
      `lesson-links is stale (${stale.length} file(s), e.g. ${stale[0]}): run node tools/build-bcpss-activity-lessons.mjs`,
    );
    process.exit(1);
  }
  console.log(
    `lesson-links current (${files.size} units, ${reveal.length} Reveal Math lessons considered)`,
  );
} else {
  mkdirSync(outDir, { recursive: true });
  for (const f of readdirSync(outDir))
    if (f.endsWith(".mjs") && !files.has(f)) rmSync(path.join(outDir, f));
  for (const [name, body] of files) writeFileSync(path.join(outDir, name), body);
  console.log(`wrote ${files.size} unit files to db/seeds/bcpss/v2/lesson-links`);
}
