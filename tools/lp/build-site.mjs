#!/usr/bin/env node
// Builds The Language Page front layer into lp/ (committed output, like the repo's other generated pages).
//   node tools/lp/build-site.mjs           write every page, the sprite, the search index and the route list
//   node tools/lp/build-site.mjs --check   exit 1 if anything on disk differs from what would be written
// Sources: tools/lp/data/** (content, i18n), tools/lp/site/** (renderers). Hand-written assets live in lp/assets/.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadData } from "./site/data.mjs";
import { spriteSvg } from "./site/icons.mjs";
import { renderAll } from "./site/routes.mjs";
import { hashFile } from "./site/util.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(ROOT, "lp");
const CHECK = process.argv.includes("--check");

const data = loadData(ROOT);
const assetPath = (f) => path.join(OUT, "assets", f);
const assets = {
  css: hashFile(assetPath("site.css")),
  prefs: hashFile(assetPath("prefs.js")),
  site: hashFile(assetPath("site.js")),
  lib: hashFile(assetPath("lib.js")),
};
const files = new Map(); // relative path under lp/ -> content
const { pages, searchIndex, routes, unitsForTools } = renderAll(data, assets);
for (const p of pages) files.set(path.join(p.path.replace(/^\//, ""), "index.html"), p.html);
files.set("assets/icons.svg", spriteSvg());
files.set("assets/search-index.json", `${JSON.stringify(searchIndex)}\n`);
files.set("assets/units.json", `${JSON.stringify(unitsForTools)}\n`);
files.set(
  "routes.json",
  `${JSON.stringify({ $comment: "Generated by tools/lp/build-site.mjs. Pages served on thelanguagepage.com.", routes }, null, 1)}\n`,
);

const jsList = (list) =>
  list.length ? `[\n${list.map((x) => `  ${JSON.stringify(x)},`).join("\n")}\n]` : "[]";
// The Pages Function routes thelanguagepage.com paths to lp/ from this module (functions cannot read dist/ files).
const fnModule = `// GENERATED by tools/lp/build-site.mjs — do not edit. The front-layer pages served on thelanguagepage.com.
export const LP_ROUTES = ${jsList(routes.map((r) => r.path))};
export const LP_SITEMAP = ${jsList(routes.filter((r) => !r.noindex).map((r) => r.path))};
export const LP_MIC_ROUTES = ${jsList(routes.filter((r) => r.mic).map((r) => r.path))};
`;
const fnPath = path.join(ROOT, "functions/_lib/lp-routes.js");

let stale = 0;
const write = (abs, content) => {
  const current = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null;
  if (current === content) return;
  if (CHECK) {
    stale++;
    console.error(`stale: ${path.relative(ROOT, abs)}`);
    return;
  }
  fs.mkdirSync(path.dirname(abs), { recursive: true });
  fs.writeFileSync(abs, content);
};
for (const [rel, content] of files) write(path.join(OUT, rel), content);
write(fnPath, fnModule);

// Remove generated pages that no longer have a route (only index.html files the generator owns).
const owned = new Set([...files.keys()].map((r) => path.join(OUT, r)));
const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) return p === path.join(OUT, "assets") ? [] : walk(p);
    return e.name === "index.html" ? [p] : [];
  });
for (const f of walk(OUT)) {
  if (owned.has(f)) continue;
  if (CHECK) {
    stale++;
    console.error(`orphan: ${path.relative(ROOT, f)}`);
  } else fs.rmSync(f);
}

if (CHECK && stale) {
  console.error(`FAIL lp build is stale (${stale} file(s)). Run: node tools/lp/build-site.mjs`);
  process.exit(1);
}
console.log(
  `${CHECK ? "PASS lp build fresh" : "lp: wrote"} ${pages.length} pages, ${searchIndex.length} search entries`,
);
