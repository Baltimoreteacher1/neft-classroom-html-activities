// Regenerates db/seeds/bcpss/v2/index.mjs: one lazy loader per authored unit.
// Lazy on purpose: ~30 KB per unit x 162 units must not be parsed at Worker start-up.
// Usage: node tools/build-bcpss-studio-index.mjs [--check]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "../db/seeds/bcpss/v2");
const ids = readdirSync(path.join(root, "units"))
  .filter((f) => f.endsWith(".mjs"))
  .map((f) => f.replace(/\.mjs$/, ""))
  .sort();
const famDir = path.join(root, "family");
const famIds = existsSync(famDir)
  ? readdirSync(famDir)
      .filter((f) => f.endsWith(".mjs"))
      .map((f) => f.replace(/\.mjs$/, ""))
      .sort()
  : [];
const body = `// GENERATED by tools/build-bcpss-studio-index.mjs — do not edit.
// Lazy loaders for the authored Language Studio content (one module per unit).

export const STUDIO_LOADERS = {
${ids.map((id) => `  "${id}": () => import("./units/${id}.mjs"),`).join("\n")}
};

export const STUDIO_UNIT_IDS = Object.keys(STUDIO_LOADERS);

export const FAMILY_LOADERS = {
${famIds.map((id) => `  "${id}": () => import("./family/${id}.mjs"),`).join("\n")}
};
`;
const out = path.join(root, "index.mjs");

// Compact per-unit summary (words + mentor sentence) for pure modules such as Year Pathways, which
// must not load every full unit module. Derived from the unit files; never edit by hand.
const summaries = {};
for (const id of ids) {
  const studio = (await import(pathToFileURL(path.join(root, "units", `${id}.mjs`)).href)).default;
  summaries[id] = {
    tier2_tier3_vocab: studio.vocab.map((v) => ({
      term: v.term,
      tier: v.tier,
      student_friendly_def: v.def,
      kid_def: v.def,
      cognate_es: v.es,
      icon: v.icon || null,
    })),
    mentor_sentence_unpacking: {
      mentor_sentence: studio.mentor.text,
      chunks: studio.mentor.chunks.map((k) => ({
        text: k.text,
        role: k.role,
        color_token: k.tone,
        student_question: k.ask,
      })),
    },
    unit_example_frame: studio.frames.l3_4[0],
  };
}
const summaryBody = `// GENERATED by tools/build-bcpss-studio-index.mjs — do not edit.
// Per-unit words and mentor sentence from the authored Language Studio content.

export const STUDIO_SUMMARIES = ${JSON.stringify(summaries, null, 1)};
`;
const summaryOut = path.join(root, "summaries.mjs");
if (process.argv.includes("--check")) {
  let cur = "";
  try {
    cur = readFileSync(out, "utf8");
  } catch {}
  let curSum = "";
  try {
    curSum = readFileSync(summaryOut, "utf8");
  } catch {}
  if (cur !== body || curSum !== summaryBody) {
    console.error(
      "v2/index.mjs or summaries.mjs is stale: run node tools/build-bcpss-studio-index.mjs",
    );
    process.exit(1);
  }
  console.log(`v2/index.mjs current (${ids.length} units, ${famIds.length} family guides)`);
} else {
  writeFileSync(out, body);
  writeFileSync(summaryOut, summaryBody);
  console.log(`wrote v2/index.mjs (${ids.length} units, ${famIds.length} family guides)`);
}
