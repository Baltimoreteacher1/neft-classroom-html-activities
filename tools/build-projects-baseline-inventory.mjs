#!/usr/bin/env node
/**
 * Writes data/projects-baseline-inventory.json — the zero-loss baseline of the
 * Projects surface (every project, version, companion, route, asset, rubric,
 * save/resume key, portfolio/certificate hook, print/export action, SCORM/Canvas
 * entry and standard). Read-only scan, deterministic: a rerun is byte-identical.
 *
 *   node tools/build-projects-baseline-inventory.mjs          write the file
 *   node tools/build-projects-baseline-inventory.mjs --check  fail if the file differs from a fresh scan
 *
 * The file is a SNAPSHOT. validate:projects-registry holds later work to it:
 * a URL or a capability present here may not disappear. Regenerate it only on
 * purpose, and read the diff — the diff is the list of what changed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, scanProjects } from "./lib/projects-inventory.mjs";

export const INVENTORY_PATH = "data/projects-baseline-inventory.json";

export async function buildInventory() {
  const scan = await scanProjects();
  return {
    schemaVersion: 1,
    note:
      "Generated by tools/build-projects-baseline-inventory.mjs. Unit numbers are CURRENT Reveal-TOC " +
      "numbers; legacyFolder is the /math/unit-N/ folder, which differs for unit-1 and unit-10. " +
      "Do not hand-edit.",
    ...scan,
  };
}

export const serialize = (inv) => `${JSON.stringify(inv, null, 2)}\n`;

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = serialize(await buildInventory());
  const path = join(ROOT, INVENTORY_PATH);
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== text) {
      console.error(
        `${INVENTORY_PATH} is out of date. Run: node tools/build-projects-baseline-inventory.mjs`,
      );
      process.exit(1);
    }
    console.log(`${INVENTORY_PATH}: fresh`);
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${INVENTORY_PATH} (${text.length} bytes)`);
  }
}
