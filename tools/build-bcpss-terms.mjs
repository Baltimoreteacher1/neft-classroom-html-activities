#!/usr/bin/env node
// Builds the shared, de-duplicated BCPSS term bank (db/seeds/bcpss/v2/terms.mjs) from every unit's authored vocabulary
// Languages: English (the term) and Spanish (authored gloss; review_status "machine" until a human approves it).
//   node tools/build-bcpss-terms.mjs            # write terms.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { STUDIO_LOADERS, STUDIO_UNIT_IDS } from "../db/seeds/bcpss/v2/index.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "../db/seeds/bcpss/v2");
const band = (g) =>
  ["k", "1", "2"].includes(g) ? "K-2" : ["3", "4", "5"].includes(g) ? "3-5" : "6-8";
const slug = (t) =>
  t
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const FALSE_FRIEND = /false friend|careful|do not confuse|not the same|means .* not/i;
const COGNATE = /cognate|true cognates|same root|share a (latin )?root/i;

const terms = new Map();
for (const id of STUDIO_UNIT_IDS) {
  const unitGrade = id.split("-")[0].slice(1);
  const studio = (await STUDIO_LOADERS[id]()).default;
  for (const v of studio.vocab) {
    const key = slug(v.term);
    const t = terms.get(key) || {
      id: key,
      term: v.term,
      pos: v.pos,
      tier: v.tier,
      bands: new Set(),
      defs: {},
      units: [],
      family: new Set(),
      icon: null,
      es: new Map(),
      notes: [],
    };
    const b = band(unitGrade);
    t.bands.add(b);
    t.defs[b] ||= v.def;
    t.tier = Math.max(t.tier, v.tier);
    t.units.push(id);
    for (const f of v.family || []) t.family.add(f);
    t.icon ||= v.icon || null;
    if (v.es) t.es.set(v.es, (t.es.get(v.es) || 0) + 1);
    if (v.es_note) t.notes.push(v.es_note);
    terms.set(key, t);
  }
}

const order = ["K-2", "3-5", "6-8"];
const out = [...terms.values()]
  .sort((a, b) => (a.id < b.id ? -1 : 1))
  .map((t) => {
    const es = [...t.es.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] || null;
    const note = t.notes.find((n) => FALSE_FRIEND.test(n)) || t.notes[0] || null;
    const cognate = t.notes.some((n) => FALSE_FRIEND.test(n))
      ? "false_friend"
      : t.notes.some((n) => COGNATE.test(n))
        ? "true"
        : "none";
    const gloss = (text) => ({ text: text || null, review_status: text ? "machine" : "pending" });
    return {
      id: t.id,
      term: t.term,
      pos: t.pos,
      tier: t.tier,
      grade_bands: order.filter((b) => t.bands.has(b)),
      defs: Object.fromEntries(order.filter((b) => t.defs[b]).map((b) => [b, t.defs[b]])),
      units: t.units,
      family: [...t.family],
      ...(t.icon ? { icon: t.icon } : {}),
      image_id: null,
      audio_id: null,
      glosses: { es: gloss(es) },
      cognate,
      notes: note,
    };
  });

writeFileSync(
  path.join(root, "terms.mjs"),
  `// GENERATED by tools/build-bcpss-terms.mjs — do not edit. Glosses are machine drafts until review_status is "human".\nexport const TERMS = ${JSON.stringify(out)};\n`,
);
console.log(`${out.length} terms; Spanish glosses ${out.filter((t) => t.glosses.es.text).length}`);
