#!/usr/bin/env node
// Project Studio (Create) · exhaustive sweep + integration ledger.
// Builds EVERY source the Customize adapters list (all four families) into EVERY format it supports, with each
// adjustment, and counts what really works. Writes the generated ledger into access-practice-lab/CREATE.md between
// the ledger markers: the route dispositions (src/create/routes.js), the external pages, and the measured format
// coverage. `--check` fails when the file is stale or when any build has a validation error.
//
//   node tools/create-coverage.mjs           write the ledger
//   node tools/create-coverage.mjs --check   verify (used by tools/create-studio.test.mjs is NOT required; run in qa)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { fetchJson } from "./studio-customize-adapters-helpers.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const DOC = `${ROOT}access-practice-lab/CREATE.md`;
const LAB = `${ROOT}access-practice-lab/src`;
const { ADAPTERS, customizeFrom } = await import(`${LAB}/studio/adapters/registry.js`);
const B = await import(`${LAB}/create/build.js`);
const R = await import(`${LAB}/create/routes.js`);

const ADJUSTMENTS = [
  {},
  { support: "more" },
  { amount: "shorter" },
  { amount: "more" },
  { challenge: "more" },
  { support: "more", amount: "more", challenge: "more" },
];

export async function sweep() {
  const families = {};
  const failures = [];
  let builds = 0;
  for (const [family, adapter] of Object.entries(ADAPTERS)) {
    const rows = await adapter.list({ fetchJson });
    const f = (families[family] = {
      label: adapter.label.en,
      sources: rows.length,
      read: 0,
      formats: {},
    });
    for (const fmt of B.FORMATS) f.formats[fmt.id] = 0;
    for (const row of rows) {
      let activity;
      try {
        ({ activity } = await customizeFrom(family, row.id, {
          fetchJson,
          now: 0,
          newId: () => "s0000000000",
        }));
      } catch (e) {
        failures.push(`${family}/${row.id}: could not read (${e.code || e.message})`);
        continue;
      }
      f.read++;
      for (const fmt of B.availableFormats(activity)) {
        let ok = true;
        for (const adjust of ADJUSTMENTS) {
          const r = B.buildResource(activity, { format: fmt.id, adjust });
          builds++;
          if (r.format !== fmt.id)
            (ok = false), failures.push(`${family}/${row.id} ${fmt.id}: fell back`);
          if (r.validation.errors.length) {
            ok = false;
            failures.push(
              `${family}/${row.id} ${fmt.id} ${JSON.stringify(adjust)}: ${r.validation.errors.map((e) => e.code).join(",")}`,
            );
          }
        }
        if (ok) f.formats[fmt.id]++;
      }
    }
  }
  return { families, failures, builds };
}

const DISPOSITION_LABEL = {
  source: "Create from this page",
  hub: "Create with a source picker",
  workspace: "Already a creation tool",
  excluded: "Not offered",
};

export function renderLedger({ families, builds }) {
  const lines = [];
  lines.push("Generated by `node tools/create-coverage.mjs`; do not edit by hand.", "");
  lines.push("### Format coverage (measured)", "");
  lines.push(
    `Every listed source was copied and built into every format it supports, with ${ADJUSTMENTS.length} adjustment settings each (${builds.toLocaleString("en-US")} builds). A format counts for a source only when every setting validated with zero errors.`,
    "",
  );
  lines.push(`| Source family | Sources read | ${B.FORMATS.map((f) => f.label.en).join(" | ")} |`);
  lines.push(`| --- | --- | ${B.FORMATS.map(() => "---").join(" | ")} |`);
  for (const [id, f] of Object.entries(families))
    lines.push(
      `| \`${id}\` (${f.label}) | ${f.read} / ${f.sources} | ${B.FORMATS.map((x) => f.formats[x.id]).join(" | ")} |`,
    );
  lines.push(
    "",
    "PDF and Word come from the Worksheet and Exit ticket formats; HTML from every format.",
    "",
  );
  lines.push("### Lab routes", "");
  const by = { source: [], hub: [], workspace: [], excluded: [] };
  for (const [view, cap] of Object.entries(R.ROUTES).sort(([a], [b]) => a.localeCompare(b)))
    by[cap.disposition].push([view, cap.note]);
  const total = Object.keys(R.ROUTES).length;
  lines.push(
    `${total} route views: ${by.source.length} source, ${by.hub.length} hub, ${by.workspace.length} workspace, ${by.excluded.length} excluded. Any hub or source route with \`?bcpssUnit=<id>\` becomes a BCPSS unit source.`,
    "",
  );
  lines.push("| Route view | Disposition | Reason |", "| --- | --- | --- |");
  for (const d of ["source", "hub", "workspace", "excluded"])
    for (const [view, note] of by[d])
      lines.push(`| \`${view}\` | ${DISPOSITION_LABEL[d]} | ${note} |`);
  lines.push(
    "",
    "### Pages outside the lab",
    "",
    "| Page | Disposition | What Create reads |",
    "| --- | --- | --- |",
  );
  for (const p of R.EXTERNAL_PAGES)
    lines.push(`| \`${p.path}\` | ${DISPOSITION_LABEL[p.disposition]} | ${p.note} |`);
  return lines.join("\n");
}

const BEGIN = "<!-- ledger:begin -->";
const END = "<!-- ledger:end -->";

export function withLedger(doc, ledger) {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) throw new Error("CREATE.md has no ledger markers");
  return `${doc.slice(0, a + BEGIN.length)}\n\n${ledger}\n\n${doc.slice(b)}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const result = await sweep();
  const doc = readFileSync(DOC, "utf8");
  const next = withLedger(doc, renderLedger(result));
  for (const [id, f] of Object.entries(result.families))
    console.log(`${id}: read ${f.read}/${f.sources}`, f.formats);
  console.log(`builds: ${result.builds}, failures: ${result.failures.length}`);
  for (const f of result.failures.slice(0, 20)) console.log(`  FAIL ${f}`);
  if (process.argv.includes("--check")) {
    if (next !== doc) {
      console.error(
        "create-coverage: CREATE.md ledger is stale. Run node tools/create-coverage.mjs",
      );
      process.exit(1);
    }
    if (result.failures.length) process.exit(1);
    if (result.builds < 1000) {
      console.error("create-coverage: swept too few builds; the sweep stopped finding sources");
      process.exit(1);
    }
    console.log("create-coverage: OK");
  } else {
    writeFileSync(DOC, next);
    console.log("create-coverage: wrote CREATE.md ledger");
    if (result.failures.length) process.exitCode = 1;
  }
}
