#!/usr/bin/env node
/* Writes the generated unit-art block of assets/dimension-surfaces.css: one baked
 * isometric emblem per unit (in the unit's own colour) and the Units page stage.
 * Colours come from the --unit-N tokens in assets/dimension.css; drawings from
 * tools/lib/iso-art.mjs. `--check` fails when the block is stale. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { REPO_ROOT } from "./lib/curriculum-source.mjs";
import {
  surfaceStageArt,
  surfaceStageNames,
  unitEmblemArt,
  unitsStageArt,
} from "./lib/iso-art.mjs";

const SHEET = resolve(REPO_ROOT, "assets/dimension-surfaces.css");
const BEGIN = "/* unit-art:begin (generated by tools/generate-unit-art.mjs; do not hand-edit) */";
const END = "/* unit-art:end */";

const tokens = readFileSync(resolve(REPO_ROOT, "assets/dimension.css"), "utf8");
const hexes = Array.from({ length: 10 }, (_, i) => {
  const hex = tokens.match(new RegExp(`--unit-${i + 1}:\\s*(#[0-9a-fA-F]{6})`))?.[1];
  if (!hex) throw new Error(`--unit-${i + 1} missing from assets/dimension.css`);
  return hex;
});

const lines = hexes.map((hex, i) => `  --unit-art-${i + 1}: ${unitEmblemArt(i + 1, hex)};`);
lines.push(`  --dm-art-units: ${unitsStageArt(hexes)};`);
for (const name of surfaceStageNames) lines.push(`  --dm-art-${name}: ${surfaceStageArt(name)};`);
const block = `${BEGIN}\n:root {\n${lines.join("\n")}\n}\n${END}`;

const css = readFileSync(SHEET, "utf8");
const start = css.indexOf(BEGIN);
const end = css.indexOf(END);
if (start < 0 || end < start)
  throw new Error("unit-art block markers missing from assets/dimension-surfaces.css");
const next = css.slice(0, start) + block + css.slice(end + END.length);
if (process.argv.includes("--check")) {
  if (next !== css) {
    console.error(
      "assets/dimension-surfaces.css unit-art block is stale: run node tools/generate-unit-art.mjs",
    );
    process.exit(1);
  }
  console.log("unit art is current");
} else if (next !== css) {
  writeFileSync(SHEET, next);
  console.log("Updated unit art in assets/dimension-surfaces.css");
} else console.log("unit art unchanged");
