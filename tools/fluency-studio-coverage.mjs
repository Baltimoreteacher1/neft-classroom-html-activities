// Writes docs/fluency-studio-coverage.md: for every skill, which Studio engine explains its generated problems,
// whether Build, a simulator and the Detective exist, and what is not modeled. Run: node tools/fluency-studio-coverage.mjs
import { writeFileSync } from "node:fs";
import { JSDOM } from "jsdom";

const dom = new JSDOM("<!doctype html><body></body>", { url: "https://example.test/" });
for (const [key, value] of Object.entries({
  window: dom.window,
  document: dom.window.document,
  localStorage: dom.window.localStorage,
}))
  Object.defineProperty(globalThis, key, { value, configurable: true, writable: true });
const { ALL_SKILLS, generateProblem, seededRandom } = await import(
  "../math/fluency-lab/problem-bank.js"
);
const { lessonFor, hasBuild, SIM_FOR } = await import("../math/fluency-lab/studio/engines.js");
const { detectiveFor } = await import("../math/fluency-lab/studio/detective.js");

const lines = [
  "# Fluency Lab Discovery Studio: coverage",
  "",
  "Generated by `node tools/fluency-studio-coverage.mjs` from 60 generated problems per skill. **Model** is the share of those problems a validated engine can draw and animate; the rest use the worded-steps player (Watch, Try with the hint ladder, Detective), which has no manipulable model. Every engine is checked by `tools/fluency-studio.test.mjs`: each frame is a legal state, the engine's answer equals the lab's answer, hints never state the answer, and every Build action is validated.",
  "",
  "| Grade | Skill | Model | Engine | Build | Explore sim | Detective | Predict / explain |",
  "| --- | --- | --- | --- | --- | --- | --- | --- |",
];
let modeledSkills = 0;
for (const skill of ALL_SKILLS) {
  const rng = seededRandom(1234 + skill.grade * 97 + skill.id.length);
  let hit = 0;
  let build = 0;
  let predict = 0;
  const engines = new Set();
  for (let n = 0; n < 60; n += 1) {
    const l = lessonFor(generateProblem(skill, rng));
    if (!l?.modeled) continue;
    hit += 1;
    engines.add(l.engine.id);
    if (hasBuild(l)) build += 1;
    if (l.engine.predicts(l.spec).length) predict += 1;
  }
  if (hit) modeledSkills += 1;
  const pct = (v) => (v ? `${Math.round((v / 60) * 100)}%` : "none");
  lines.push(
    `| ${skill.grade} | ${skill.id} | ${pct(hit)} | ${[...engines].join(", ") || "worked steps"} | ${pct(build)} | ${SIM_FOR[skill.id] || "none"} | ${detectiveFor(skill, 1) ? "yes" : "no"} | ${pct(predict)} |`,
  );
}
lines.push(
  "",
  `${modeledSkills} of ${ALL_SKILLS.length} skill entries have a manipulable model for at least some generated problems.`,
  "",
);
writeFileSync(new URL("../docs/fluency-studio-coverage.md", import.meta.url), lines.join("\n"));
console.log(`coverage written: ${modeledSkills}/${ALL_SKILLS.length} skill entries modeled`);
