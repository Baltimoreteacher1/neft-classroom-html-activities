// One inventory row per family-practice page, built from the generated page + its sidecar/config.
import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { lessonPath, REPO_ROOT } from "./curriculum-source.mjs";
import { readRouteConfig, resolvesInRepo } from "./family-mission-checks.mjs";

const exists = (rel) => existsSync(join(REPO_ROOT, rel));

/** Files that feed a page: the lesson config, its sidecar, and every shared data file the generator reads for it. */
function contentSources(ctx, page) {
  const out = [`lessons/${ctx.baseId}/config.json`, `data/family-homework-notes/${ctx.id}.json`];
  const maybe = [
    ctx.session > 1 && "data/part-two-session2-practice.json",
    `data/es-translations/${ctx.baseId}.json`,
    "data/family-glossary.json",
    "data/family-plain-definitions.json",
    "data/family-homework-titles-es.json",
    "data/family-homework-ladder.json",
    "data/homework-external-resources.json",
    "data/homework-feedback-spanish.json",
    "data/homework-choices-spanish.json",
    page.html.includes("cga-round") && "data/homework-confused-grownup-tags.json",
    "data/reveal-toc-2025.json",
  ];
  return [...out, ...maybe.filter((p) => p && exists(p))];
}

function printables(id, page) {
  const dir = lessonPath(id, "downloads");
  const files = existsSync(dir)
    ? readdirSync(dir).filter(
        (f) => /(family|homework|practice-workbook)/.test(f) && /\.(pdf|docx)$/.test(f),
      )
    : [];
  const onPage = page.links
    .filter((l) => /weekly-sheet|\.pdf|\.docx/i.test(l.href))
    .map((l) => l.href);
  return [
    ...(exists(`lessons/${id}/homework.docx`) ? [`lessons/${id}/homework.docx`] : []),
    ...files.map((f) => `lessons/${id}/downloads/${f}`),
    ...[...new Set(onPage)],
  ];
}

function byTier(problems) {
  const tiers = {};
  const types = {};
  for (const p of problems) {
    tiers[p.tier] = (tiers[p.tier] || 0) + 1;
    types[p.type] = (types[p.type] || 0) + 1;
  }
  return {
    total: problems.length,
    core: problems.filter((p) => p.tier !== "more").length,
    tiers,
    types,
  };
}

function familyRoute(page) {
  const cfg = readRouteConfig(page);
  const fmt = (name, r) =>
    r ? `${name}: ${r.tabs.join(">")} (${r.problemLimit || "all"} problems)` : "";
  return {
    url: `/lessons/${page.id}/homework.html`,
    defaultMode: page.route.defaultMode,
    modes: [fmt("quick", cfg?.quick), fmt("full", cfg?.full)].filter(Boolean),
  };
}

function statedGoal(page) {
  const cfg = readRouteConfig(page);
  const chips = page.route.buttons
    .map((b) => (/(\d+–\d+)\s*min/.exec(b.text) || [])[1])
    .filter(Boolean);
  return {
    quickClaim: page.route.quickClaim,
    goalFirstPaint: [...new Set(page.route.goalCounts)],
    goalAvailable: [...new Set(page.route.availCounts)],
    goalRuntime: cfg ? { quick: cfg.quick?.problemLimit, full: "all" } : null,
    timeChips: chips,
  };
}

export function inventoryRow({ page, ctx, findings, answerTally }) {
  const internal = [
    ...new Set(page.links.filter((l) => l.href.startsWith("/")).map((l) => l.href)),
  ];
  const broken = internal.filter((h) => !h.startsWith("/api/") && !resolvesInRepo(h));
  const defects = {};
  for (const f of findings) defects[f.rule] = (defects[f.rule] || 0) + 1;
  return {
    unit: ctx.unit,
    lessonId: ctx.id,
    baseLessonId: ctx.baseId,
    session: ctx.session,
    outOfScope: ctx.outOfScope,
    title: ctx.title,
    objective: ctx.sidecar?.learningTonight?.en || ctx.config?.contentObjective || "",
    standard: ctx.config?.standard || "",
    familyRoute: familyRoute(page),
    contentSources: contentSources(ctx, page),
    problemCount: byTier(page.problems),
    statedGoal: statedGoal(page),
    topic: page.topic,
    modelFamily: { family: ctx.family, rule: ctx.familyRule },
    hasEN: page.langPairs.length > 0,
    hasES: page.langPairs.some((p) => p.paired && p.es),
    v3Present: Boolean(ctx.sidecar?.v3),
    printableLinks: printables(ctx.id, page),
    internalLinks: { total: internal.length, resolved: internal.length - broken.length, broken },
    answerKeys: answerTally,
    defects,
  };
}

const cell = (s) => String(s ?? "").replace(/\|/g, "/");

/** The human-readable table (inventory.md). */
export function inventoryMarkdown(rows) {
  const lines = [
    "# Family Practice content inventory",
    "",
    "Generated by `node scripts/build-family-mission-inventory.mjs` from the generated pages, sidecars and configs. Do not edit by hand.",
    "",
    `${rows.length} pages. Unit 10 rows are flagged out of scope (the unit is not taught).`,
    "",
    "| Page | Unit | S | Title | Standard | Family (rule) | Topic | Core / total items | Goal (quick claim / first paint) | EN | ES | v3 | Defects |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const r of rows) {
    const d =
      Object.entries(r.defects)
        .map(([k, v]) => `${k}:${v}`)
        .join(" ") || "clean";
    lines.push(
      `| ${r.lessonId}${r.outOfScope ? " (out of scope)" : ""} | ${r.unit} | ${r.session} | ${cell(r.title)} | ${r.standard} | ${r.modelFamily.family} (${r.modelFamily.rule}) | ${r.topic} | ${r.problemCount.core} / ${r.problemCount.total} | ${r.statedGoal.quickClaim} / ${r.statedGoal.goalFirstPaint.join(",")} | ${r.hasEN ? "yes" : "NO"} | ${r.hasES ? "yes" : "NO"} | ${r.v3Present ? "yes" : "NO"} | ${d} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

const count = (rows, key) => {
  const out = {};
  for (const r of rows) out[key(r)] = (out[key(r)] || 0) + 1;
  return Object.entries(out).sort((a, b) =>
    String(a[0]).localeCompare(String(b[0]), "en", { numeric: true }),
  );
};
const table = (head, entries) => [
  `| ${head} | pages |`,
  "| --- | --- |",
  ...entries.map(([k, v]) => `| ${k} | ${v} |`),
  "",
];

/** docs/family-mission/coverage.md: what is counted, what is defective, what is clean. */
export function coverageMarkdown(rows) {
  const scope = rows.filter((r) => !r.outOfScope);
  const rules = {};
  for (const r of scope)
    for (const [rule, n] of Object.entries(r.defects))
      (rules[rule] ||= { pages: 0, findings: 0 }), rules[rule].pages++, (rules[rule].findings += n);
  const clean = scope.filter((r) => Object.keys(r.defects).length === 0);
  const cleanBesideGoal = scope.filter((r) =>
    Object.keys(r.defects).every((rule) => rule === "COUNT_STATIC_GOAL"),
  );
  const keys = scope.reduce(
    (t, r) => ({
      ok: t.ok + r.answerKeys.ok,
      mismatch: t.mismatch + r.answerKeys.mismatch,
      uncheckable: t.uncheckable + r.answerKeys.uncheckable,
    }),
    { ok: 0, mismatch: 0, uncheckable: 0 },
  );
  return [
    "# Family Practice coverage",
    "",
    "Generated by `node scripts/build-family-mission-inventory.mjs`. Do not edit by hand.",
    "",
    `${rows.length} pages (${scope.length} in scope, ${rows.length - scope.length} Unit 10 pages flagged out of scope and excluded from every count below).`,
    "",
    "## Pages by unit",
    ...table(
      "Unit",
      count(scope, (r) => r.unit),
    ),
    "## Pages by model family",
    ...table(
      "Family",
      count(scope, (r) => r.modelFamily.family),
    ),
    "## Pages by route",
    ...table(
      "Route (opens on, modes offered)",
      count(
        scope,
        (r) => `opens on ${r.familyRoute.defaultMode}; ${r.familyRoute.modes.join(" / ")}`,
      ),
    ),
    "## Pages by session",
    ...table(
      "Session",
      count(scope, (r) => r.session),
    ),
    "## Defect classes (pages affected, findings)",
    "| Rule | pages | findings |",
    "| --- | --- | --- |",
    ...Object.entries(rules)
      .sort()
      .map(([k, v]) => `| ${k} | ${v.pages} | ${v.findings} |`),
    "",
    "## Validated clean",
    `${clean.length} of ${scope.length} in-scope pages have no finding under any rule.`,
    `${cleanBesideGoal.length} of ${scope.length} have no finding apart from COUNT_STATIC_GOAL, the first-paint goal chip that every page prints (the page script corrects it after load).`,
    "",
    "## Answer keys",
    `Recomputed independently from the stem: ${keys.ok} correct, ${keys.mismatch} wrong. Un-checkable (word problems, sorting, tables, open response; NOT verified by this gate): ${keys.uncheckable}.`,
    "",
  ].join("\n");
}
