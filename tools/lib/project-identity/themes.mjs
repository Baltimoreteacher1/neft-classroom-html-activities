/* Single source of truth for the Projects identity layer: one visual identity per project.
   Everything the pages, the Studio and the gallery show of a project's look derives from here
   (tools/build-project-identity.mjs writes the CSS tokens and the art files).

   palette slots
     ink / deep   dark ends of the hero gradient (white text sits on these: contrast >= 7)
     accent       primary action + step colour. Text-safe: >= 4.5 against white AND against paper.
     accentB      second text-safe colour (links, rules, chart ink) that is clearly a different hue
     glow         bright highlight for use on ink/deep only (never as text on paper)
     paper / tint page background and soft panel background (light)
   layout: split = text left, art right | poster = art full-bleed under a scrim, text over it
   tone:   dark = ink/deep hero with white text | light = tint hero with ink text (split only) */

