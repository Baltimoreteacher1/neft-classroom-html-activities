#!/usr/bin/env node
/**
 * Generates access-practice-lab/content/bank/index.json: one compact row per set and per item (no stimulus text, no answer
 * keys) so the chooser, the teacher content explorer and the coverage dashboard can list and filter the bank without loading
 * 40 files. `--check` fails when the committed index is stale. Counts here are read from the files, never typed.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { BANK_DIR, loadBank } from "./validate-access-bank.mjs";

export function buildIndex(sets = loadBank()) {
  const rows = sets.map(({ set }) => ({
    id: set.id,
    title: set.title,
    grade: set.grade,
    domain: set.domain,
    minutes: set.minutes,
    description: set.description,
    reviewStatus: set.bank?.reviewStatus,
    items: set.items.map((i) => ({
      id: i.id,
      type: i.type,
      klu: i.klu,
      context: i.context,
      band: i.meta.band,
      cognitive: i.meta.cognitive,
      languageDemand: i.meta.languageDemand,
      functions: i.meta.functions,
      features: i.meta.features,
      explicit: i.meta.wida.explicit,
      standard: i.meta.standard,
      parallel: i.meta.parallel || null,
      stem: i.stem.length > 140 ? `${i.stem.slice(0, 137)}...` : i.stem,
    })),
  }));
  return {
    schema: 1,
    bankVersion: 1,
    note: "Generated by tools/access-acc-bank-index.mjs. Practice material; not WIDA or DRC content.",
    sets: rows,
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = `${JSON.stringify(buildIndex(), null, 1)}\n`;
  const file = join(BANK_DIR, "index.json");
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {}
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(
        "access-acc-bank-index: content/bank/index.json is stale — run `node tools/access-acc-bank-index.mjs`.",
      );
      process.exit(1);
    }
    console.log("access-acc-bank-index: index.json is current.");
  } else if (current !== next) {
    writeFileSync(file, next);
    console.log("access-acc-bank-index: wrote content/bank/index.json.");
  } else console.log("access-acc-bank-index: already current.");
}
