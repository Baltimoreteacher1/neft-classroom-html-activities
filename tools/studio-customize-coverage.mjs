#!/usr/bin/env node
// Customize Activity coverage matrix: family x editable properties x status x limitation, as Markdown.
// Writes (or, with --check, verifies) the table between the coverage markers in access-practice-lab/CUSTOMIZE.md. Only
// that region is ever edited. The rows are access-practice-lab/src/studio/adapters/coverage.js; editable properties
// come from the adapters themselves, so the table cannot promise what an adapter does not list.
//
//   node tools/studio-customize-coverage.mjs           # refresh the table in CUSTOMIZE.md
//   node tools/studio-customize-coverage.mjs --check   # exit 1 when the table is stale
//   node tools/studio-customize-coverage.mjs --print   # print the table, change nothing
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { coverageRows } from "../access-practice-lab/src/studio/adapters/coverage.js";
import { PROPERTIES } from "../access-practice-lab/src/studio/adapters/properties.js";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FILE = resolve(ROOT, "access-practice-lab/CUSTOMIZE.md");
const BEGIN = "<!-- coverage:begin -->";
const END = "<!-- coverage:end -->";

const cell = (s) => String(s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const editable = (row) =>
  row.editable.length ? row.editable.map((id) => `\`${id}\``).join(" ") : "none";

/** The generated Markdown (no markers). */
export function renderMatrix(rows = coverageRows()) {
  const count = (status) => rows.filter((r) => r.status === status).length;
  const lines = [
    "Generated by `node tools/studio-customize-coverage.mjs`; do not edit by hand. Source: `src/studio/adapters/coverage.js`.",
    "",
    `${rows.length} families inspected: ${count("adapter")} with an adapter, ${count("via-transform")} via a transform, ${count("not-supported")} not supported.`,
    "",
    "| Family | Status | Editable properties | What carries over, and what does not | Evidence |",
    "| --- | --- | --- | --- | --- |",
    ...rows.map(
      (r) =>
        `| \`${r.family}\` (${cell(r.label.en)}) | ${r.status} | ${cell(editable(r))} | ${cell(r.reason.en)} | ${cell(r.evidence)} |`,
    ),
    "",
    "Editable property ids:",
    "",
    ...Object.entries(PROPERTIES).map(([id, p]) => `- \`${id}\`: ${p.label.en}`),
  ];
  return lines.join("\n");
}

/** CUSTOMIZE.md text with the region between the markers replaced by `body`; null when the markers are missing. */
export function withMatrix(doc, body) {
  const a = doc.indexOf(BEGIN);
  const b = doc.indexOf(END);
  if (a < 0 || b < a) return null;
  return `${doc.slice(0, a + BEGIN.length)}\n\n${body}\n\n${doc.slice(b)}`;
}

function main(argv) {
  const body = renderMatrix();
  if (argv.includes("--print")) {
    console.log(body);
    return 0;
  }
  const doc = readFileSync(FILE, "utf8");
  const next = withMatrix(doc, body);
  if (next === null) {
    console.error(`coverage markers ${BEGIN} / ${END} are missing in ${FILE}`);
    return 1;
  }
  if (argv.includes("--check")) {
    if (next === doc) {
      console.log("coverage matrix is current");
      return 0;
    }
    console.error(
      "coverage matrix in CUSTOMIZE.md is stale: run node tools/studio-customize-coverage.mjs",
    );
    return 1;
  }
  if (next === doc) console.log("coverage matrix already current");
  else {
    writeFileSync(FILE, next);
    console.log("coverage matrix written to access-practice-lab/CUSTOMIZE.md");
  }
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  process.exitCode = main(process.argv.slice(2));
