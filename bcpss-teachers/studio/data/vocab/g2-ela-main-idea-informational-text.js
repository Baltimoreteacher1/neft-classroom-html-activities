/** A labelled rounded box on the 480 x 320 canvas. */
const box = (
  x,
  y,
  w,
  h,
  fill,
  text,
  { size = 17, ink = "ink", stroke = "ink", sw = 3, lines = null } = {},
) => [
  { t: "rect", x, y, w, h, rx: 12, fill, stroke, sw },
  {
    t: "text",
    x: x + w / 2,
    y: y + h / 2 + size * 0.35 - (lines ? lines - 1 : 0) * size * 0.6,
    text,
    size,
    weight: 700,
    fill: ink,
  },
];

