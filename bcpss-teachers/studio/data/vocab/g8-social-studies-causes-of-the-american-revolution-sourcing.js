const rect = (x, y, w, h, fill = "paper", stroke = "navy", sw = 2.5) => ({
  t: "rect",
  x,
  y,
  w,
  h,
  rx: 10,
  fill,
  stroke,
  sw,
});
const txt = (x, y, text, o = {}) => ({
  t: "text",
  x,
  y,
  text,
  size: 13,
  fill: "ink",
  weight: 700,
  anchor: "middle",
  ...o,
});
const wrap = (s, w, size) => {
  if (s.includes("\n")) return s;
  const max = Math.max(6, Math.floor((w - 14) / (size * 0.6)));
  const out = [];
  let cur = "";
  for (const word of s.split(" ")) {
    if (cur && `${cur} ${word}`.length > max) {
      out.push(cur);
      cur = word;
    } else cur = cur ? `${cur} ${word}` : word;
  }
  out.push(cur);
  return out.join("\n");
};
const box = (x, y, w, h, text, fill = "paper", size = 13, stroke = "navy") => [
  rect(x, y, w, h, fill, stroke),
  txt(x + w / 2, y + h / 2, wrap(text, w, size), { size }),
];
const line = (x1, y1, x2, y2, o = {}) => ({
  t: "line",
  x1,
  y1,
  x2,
  y2,
  stroke: "ink",
  strokeWidth: 2.5,
  ...o,
});
const tip = (x, y, dir) => ({
  t: "poly",
  fill: "ink",
  points:
    dir === "up"
      ? [
          [x, y],
          [x - 7, y + 12],
          [x + 7, y + 12],
        ]
      : dir === "down"
        ? [
            [x, y],
            [x - 7, y - 12],
            [x + 7, y - 12],
          ]
        : dir === "left"
          ? [
              [x, y],
              [x + 12, y - 7],
              [x + 12, y + 7],
            ]
          : [
              [x, y],
              [x - 12, y - 7],
              [x - 12, y + 7],
            ],
});
/** Horizontal arrow between two boxes at height y. */
const hop = (x1, x2, y) => [line(x1, y, x2 - 4, y), tip(x2, y, "right")];
const shapes = (alt, items, h = 240) => ({
  kind: "shapes",
  alt,
  w: 480,
  h,
  items: items.flat(Infinity),
});
/** A row of n boxes joined by arrows. */
const chain = (alt, labels, fills = [], h = 200, size = 12) => {
  const n = labels.length;
  const gap = 26;
  const w = (456 - gap * (n - 1)) / n;
  return shapes(
    alt,
    labels.flatMap((l, i) => {
      const x = 12 + i * (w + gap);
      return [
        box(x, 50, w, h - 100, l, fills[i] || "paper", size),
        ...(i < n - 1 ? hop(x + w + 1, x + w + gap - 2, h / 2) : []),
      ];
    }),
    h,
  );
};
