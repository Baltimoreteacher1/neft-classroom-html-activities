export const OP_KEYS = { "+": "opAdd", [MINUS]: "opSub", "×": "opMul", "÷": "opDiv" };

/** Looks up a string and fills {placeholders}. Falls back to English, then to the key. */
export function t(lang, key, vars = {}) {
  const raw = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  if (typeof raw !== "string") return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name) => (name in vars ? String(vars[name]) : `{${name}}`));
}
