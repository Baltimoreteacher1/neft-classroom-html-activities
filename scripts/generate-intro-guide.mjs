#!/usr/bin/env node
/**
 * generate-intro-guide: builds the printable teacher introduction files in access-practice-lab/guides/ from ONE source,
 * src/intro/data.js (through quick-guide-model.js, lesson-backup-model.js and presenter-notes.js):
 *   quick-guide.pdf / .docx             two Letter pages: the 20-minute exploration and the featured lesson
 *   featured-lesson-backup.pdf / .docx  page 1 student-facing, page 2 teacher-facing: use it if the activity will not load
 *   presenter-notes.pdf / .docx         the 30-minute presenter script (4 pages at most)
 *   qr-start.svg / qr-start.png         the ONE QR code, for ENTRANCE.url (shared/qr/qr-code.mjs; decoder-verified in the tests)
 *   src/intro/qr-start-svg.js           the same SVG as an importable string for the on-screen presenter view
 *   docs/languageos/pd-presenter-notes.md   the presenter script as plain Markdown
 * Output is deterministic: no timestamps appear in visible text. Run:  npm run generate:intro-guide  (--only=guide|backup|notes|qr)
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { Resvg } from "@resvg/resvg-js";
import { absUrl, ENTRANCE } from "../access-practice-lab/src/intro/data.js";
import { buildBackupModel } from "../access-practice-lab/src/intro/lesson-backup-model.js";
import { guideSheets } from "../access-practice-lab/src/intro/quick-guide-html.js";
import { buildGuideModel } from "../access-practice-lab/src/intro/quick-guide-model.js";
import { toHtml } from "../access-practice-lab/src/util.js";
import { qrSvg } from "../shared/qr/qr-code.mjs";
import { printDocument, renderPdfs } from "./lib/intro-guide-pdf.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LAB = join(ROOT, "access-practice-lab");
const GUIDES = join(LAB, "guides");
mkdirSync(GUIDES, { recursive: true });

const only = process.argv.find((a) => a.startsWith("--only="))?.slice(7);
const want = (name) => !only || only === name;
const QR_SRC = "/access-practice-lab/guides/qr-start.svg";

// The one QR code: black on white with a four-module quiet zone. qr-start.svg is the print master, the PNG is for Word.
const svg = qrSvg(ENTRANCE.url, { px: 144 });
writeFileSync(join(GUIDES, "qr-start.svg"), `${svg}\n`);
writeFileSync(
  join(GUIDES, "qr-start.png"),
  new Resvg(svg, { fitTo: { mode: "width", value: 576 } }).render().asPng(),
);
writeFileSync(
  join(LAB, "src", "intro", "qr-start-svg.js"),
  `// Generated by scripts/generate-intro-guide.mjs from ENTRANCE.url in data.js. Do not edit by hand.
// The ONE QR code of the introduction (decoder-verified in tools/access-intro-guide.test.mjs).
export const QR_START_URL = ${JSON.stringify(ENTRANCE.url)};
const SVG = ${JSON.stringify(svg)};

/** The QR as markup. Pass \`label\` for a screen reader name; without it the image is decorative. */
export function qrStartSvg({ px = 144, label = "" } = {}) {
  const aria = label ? \` role="img" aria-label="\${label.replace(/"/g, "&quot;")}"\` : ' aria-hidden="true"';
  return SVG.replace(/ width="\\d+" height="\\d+"/, \` width="\${px}" height="\${px}"\`).replace(/ aria-hidden="true"/, aria);
}
`,
);

if (want("guide")) {
  const model = buildGuideModel();
  const body = toHtml(guideSheets(model, { href: absUrl, qr: { start: QR_SRC } }));
  await renderPdfs([
    {
      out: join(GUIDES, "quick-guide.pdf"),
      doc: printDocument({
        title: `${model.siteName} ${model.title}`,
        bodyHtml: `<div class="ig">${body}</div>`,
      }),
    },
  ]);
  const { buildGuideDocx } = await import("./lib/intro-guide-docx.mjs");
  writeFileSync(join(GUIDES, "quick-guide.docx"), await buildGuideDocx(model));
}

if (want("backup")) {
  const model = buildBackupModel();
  const { backupBody } = await import("./lib/intro-backup-html.mjs");
  await renderPdfs([
    {
      out: join(GUIDES, "featured-lesson-backup.pdf"),
      doc: printDocument({ title: model.title, bodyHtml: backupBody(model) }),
    },
  ]);
  const { buildBackupDocx } = await import("./lib/intro-backup-docx.mjs");
  writeFileSync(join(GUIDES, "featured-lesson-backup.docx"), await buildBackupDocx(model));
}

if (want("notes")) {
  const { NOTES_TITLE, notesBody, notesMarkdown } = await import("./lib/intro-notes-html.mjs");
  const { buildNotesDocx } = await import("./lib/intro-notes-docx.mjs");
  await renderPdfs([
    {
      out: join(GUIDES, "presenter-notes.pdf"),
      doc: printDocument({ title: NOTES_TITLE, bodyHtml: notesBody() }),
    },
  ]);
  writeFileSync(join(GUIDES, "presenter-notes.docx"), await buildNotesDocx());
  const mdPath = join(ROOT, "docs", "languageos", "pd-presenter-notes.md");
  mkdirSync(dirname(mdPath), { recursive: true });
  writeFileSync(mdPath, notesMarkdown());
}
console.log("generate-intro-guide: wrote files in access-practice-lab/guides/");
