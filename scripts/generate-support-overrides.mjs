#!/usr/bin/env node
/* =============================================================================
 * generate-support-overrides.mjs
 *
 * data/lesson-support-applicability-review.json is the AUTHORED file: one entry
 * per instructional decision, each carrying its reason and the evidence it was
 * read from. This derives the small runtime shape the lesson surfaces fetch.
 *
 * Two files rather than one, on purpose. The review file is prose-heavy and
 * exists to be argued with; shipping it to every lesson page would send a
 * paragraph of rationale to a browser that needs one boolean. But hand-editing
 * BOTH is how a suppression comes to exist in the runtime file with no recorded
 * reason behind it, so the derived file is generated and
 * `validate:lesson-supports` fails if it is stale.
 *
 *   --check   verify the derived file matches, write nothing (CI / gate mode)
 * ========================================================================== */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const REVIEW_PATH = join(ROOT, "data", "lesson-support-applicability-review.json");
const OUT_PATH = join(ROOT, "data", "lesson-support-overrides.json");

/** support key → the applicability flag the catalogue's `requires` rule reads. */
const SUPPRESSION_FLAG = {
  calculator: "computationIsObjective",
  "multiplication-chart": "factRecallIsObjective",
};

export function buildOverrides(review) {
  const lessons = {};
  const ensure = (id) => (lessons[id] ||= {});
  for (const r of review.reviews || []) {
    const entry = ensure(r.lessonId);
    if (r.decision === "suppress") {
      const flag = SUPPRESSION_FLAG[r.support];
      if (flag) entry[flag] = true;
      else {
        entry.exclude ||= [];
        entry.exclude.push({ key: r.support, reason: r.reason });
      }
    } else if (r.decision === "pin") {
      entry.pin ||= [];
      if (!entry.pin.includes(r.support)) entry.pin.push(r.support);
    }
    // "allow" is recorded for the audit trail and deliberately produces NO
    // runtime entry: allowing is the default, and writing it out would make an
    // explicitly-reviewed allow indistinguishable from an unreviewed one.
  }
  // Drop lessons whose only decisions were "allow".
  for (const [id, v] of Object.entries(lessons)) {
    if (!Object.keys(v).length) delete lessons[id];
  }
  return {
    _note:
      "GENERATED by scripts/generate-support-overrides.mjs from " +
      "data/lesson-support-applicability-review.json. Do not hand-edit: the next " +
      "generator run overwrites it, and a suppression recorded only here has no " +
      "reason or evidence behind it. Edit the review file and re-run.",
    _fields: {
      computationIsObjective:
        "Suppresses the calculator: doing the computation is what this lesson teaches.",
      factRecallIsObjective:
        "Suppresses the multiplication chart, for the same reason applied to fact recall.",
      pin: "Support content that stays visible even under reduced visual load.",
      exclude: "Supports never offered for this lesson, each with a recorded reason.",
    },
    lessons,
  };
}

function main() {
  const review = JSON.parse(readFileSync(REVIEW_PATH, "utf8"));
  const next = `${JSON.stringify(buildOverrides(review), null, 2)}\n`;
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT_PATH, "utf8");
    } catch {
      /* missing counts as stale */
    }
    if (current !== next) {
      console.error(
        "FAIL: data/lesson-support-overrides.json is stale.\n" +
          "  Run: node scripts/generate-support-overrides.mjs",
      );
      process.exit(1);
    }
    console.log("✓ lesson-support-overrides.json is current");
    return;
  }
  writeFileSync(OUT_PATH, next, "utf8");
  const n = Object.keys(buildOverrides(review).lessons).length;
  console.log(
    `✓ generated data/lesson-support-overrides.json — ${n} lesson(s) with runtime decisions, ` +
      `${(review.reviews || []).length} reviewed decision(s) total`,
  );
}

if (process.argv[1] && process.argv[1].endsWith("generate-support-overrides.mjs")) main();
