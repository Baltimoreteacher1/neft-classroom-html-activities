#!/usr/bin/env node
// soften-warmup-onramps.mjs — a warm-up opens the day; it does not screen for it.
//
//   node scripts/soften-warmup-onramps.mjs [--dry-run]
//
// WHY
//
// 310 warm-up questions review the previous lesson, and a large share of them
// opened at the previous lesson's FULL difficulty. Lesson 2-7 asked 936 ÷ 8 as
// its first question of the morning and 1,472 ÷ 4 as its second — two long
// divisions with regrouping before anybody had picked up a pencil. 5-6 opened
// with a REVERSE volume problem (given the volume, find the height) and only
// then asked for a volume. 5-8 opened with the whole surface-area formula,
// 2(lw + lh + wh), and asked the number of faces on a prism afterwards. In each
// case the recall item the class could all answer existed — it was just sitting
// at position 3 or 4, behind the item that stalls the room.
//
// This applies one rule: EASIEST FIRST. Q1 and Q2 are single-step with friendly
// numbers, the harder item keeps its place further down, and a reasoning
// question may close. Every replacement keeps the SAME mathematics as the item
// it replaces — this is a re-ordering and a re-numbering, not a change of what
// is reviewed. `warmup.reviews` / `prevLessonId` / `prevLessonTitle` are never
// touched, so tools/warmup-sequencing.test.mjs still anchors every set.
//
// THREE RULES, none of which the shape of the data enforces on its own:
//
//   1. BILINGUAL, ATOMICALLY. stem/stemEs, choices/choicesEs and
//      explanation/explanationEs are written together as one object below.
//      There is no path through this file that updates one and not the other,
//      and tools/warmup-answers.test.mjs re-checks the number agreement after.
//   2. TAGS ARE POSITIONAL. `misconceptionTags[i]` claims that choice i is what
//      that specific error produces. Every tag here was re-derived from the new
//      numbers ("14 in³" is op-added-instead-of-multiplied because 10 + 4 = 14),
//      and a position whose error no longer lands on its choice is set to null
//      rather than left pointing at nothing. Tags are not dropped wholesale —
//      they feed the misconception pipeline.
//   3. ANSWERS ARE COMPUTED, NOT EYEBALLED. Every rewritten question is
//      re-checked by tools/warmup-answers.test.mjs, which recomputes the answer
//      from the stem's own numbers in exact rational arithmetic. Where a stem
//      is not machine-checkable the question was still hand-derived, and where
//      an existing question could not be verified at all it was LEFT ALONE — an
//      unchanged hard question beats a wrong easy one.
//
// Warm-ups are NOT regenerated by any build step (scripts/generate-warmups.mjs
// defaults to --check and reads spiral-review/bank.json, which these did not
// come from), so the lesson configs are the source of truth. Variants inherit:
// this file copies each rewritten parent warm-up into its small-group and
// catch-up variants with the ids rewritten, which is exactly what
// generate-warmups.mjs does for variants and what warmup-sequencing.test.mjs
// requires.
//
// Idempotent: re-running writes nothing once the easier set is in place.

