/** Small-group and catch-up variants of `id` that carry a warmup of their own. */
function variantsOf(id) {
  return readdirSync(LESSONS, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((name) => /^(?:group1|group2|catchup)$/.test(name.slice(id.length + 1)))
    .filter((name) => name.startsWith(`${id}-`))
    .filter((name) => existsSync(join(LESSONS, name, "config.json")))
    .sort();
}

let changed = 0;
let alreadyRight = 0;
const touched = [];

for (const [id, questions] of Object.entries(QUESTIONS)) {
  const file = join(LESSONS, id, "config.json");
  if (!existsSync(file)) {
    console.error(`  SKIP ${id} — no config.json on disk`);
    continue;
  }
  const config = JSON.parse(readFileSync(file, "utf8"));
  if (!config.warmup) {
    console.error(`  SKIP ${id} — no warmup to soften`);
    continue;
  }

  /* Targets: the lesson itself, then every variant, which inherits verbatim
   * apart from the per-question id. warmup-sequencing.test.mjs compares them
   * with the id stripped, so this is the shape it requires. */
  for (const target of [id, ...variantsOf(id)]) {
    const path = join(LESSONS, target, "config.json");
    const cfg = JSON.parse(readFileSync(path, "utf8"));
    if (!cfg.warmup) continue;
    const next = {
      ...cfg.warmup,
      questions: questions.map((q, i) => ({ id: `warmup-${target}-${i + 1}`, ...q })),
    };
    if (JSON.stringify(cfg.warmup) === JSON.stringify(next)) {
      alreadyRight += 1;
      continue;
    }
    cfg.warmup = next;
    if (!DRY) writeFileSync(path, `${JSON.stringify(cfg, null, 2)}\n`);
    changed += 1;
    touched.push(target);
  }
}

console.log(
  `${DRY ? "--dry-run: would rewrite" : "Rewrote"} ${changed} warmup(s) ` +
    `across ${Object.keys(QUESTIONS).length} lesson families ` +
    `(${alreadyRight} already carried the easier set).`,
);
if (touched.length) console.log(`  ${touched.join(", ")}`);
