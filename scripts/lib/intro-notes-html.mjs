// The presenter notes as print markup (for the PDF) and as Markdown (docs/languageos/pd-presenter-notes.md).
// Both read presenter-notes.js, which reads data.js, so the script, the PDF, the Word file and the on-screen
// presenter view cannot differ.

import {
  absUrl,
  ENTRANCE,
  FEATURED_LESSON,
  shortUrl,
} from "../../access-practice-lab/src/intro/data.js";
import {
  BACKUP_ALL,
  DOWNLOAD_NAMES,
  HANDOFF,
  PRESENTER_NOTES,
  ROOM_SETUP,
} from "../../access-practice-lab/src/intro/presenter-notes.js";
import { html, toHtml } from "../../access-practice-lab/src/util.js";

export const NOTES_TITLE = "The Language Page: 30-Minute Presenter Notes";
export const BACKUP_LABELS = [["audio"], ["microphones"], ["network"]];
const bullets = (items) => html`<ul>${items.map((i) => html`<li>${i}</li>`)}</ul>`;

function rowBlock(r, i) {
  return html`<section class="pn-row" aria-labelledby="pn-r${i}">
    <h3 id="pn-r${i}"><span class="pn-time">${r.range} min</span> ${r.title}</h3>
    <p class="pn-open"><strong>Link:</strong> <a href="${absUrl(r.route)}">${r.openLabel}</a> <span class="ig-url">${shortUrl(r.route)}</span></p>
    <p class="pn-say"><strong>Say:</strong> ${r.say.map((s) => `“${s}”`).join(" ")}</p>
    <div class="pn-cols">
      <div><h4>You</h4>${bullets(r.presenterDoes)}</div>
      <div><h4>Teachers</h4>${bullets(r.teachersDo)}
        <p><strong>Watch for:</strong> ${r.watchFor}</p>
        <p><strong>Backup:</strong> ${r.backup}</p></div>
    </div>
  </section>`;
}

export function notesBody() {
  const body = html`<article class="ig-sheet pn" aria-labelledby="pn-h1">
    <header class="pn-head">
      <div>
        <h1 id="pn-h1">${NOTES_TITLE}</h1>
        <p>Run this script top to bottom. The times match the schedule: 0–3, 3–8, 8–13, 13–23, 23–27, 27–30, then the 20-minute exploration.</p>
        <p><strong>One link for teachers:</strong> <a href="${ENTRANCE.url}">${ENTRANCE.short}</a></p>
      </div>
      <figure class="ig-qr"><img src="/access-practice-lab/guides/qr-start.svg" width="92" height="92" alt="QR code for ${ENTRANCE.short}, the teacher starting page."></figure>
    </header>
    <h2>Before the room fills</h2>
    ${bullets(ROOM_SETUP)}
    <h2>The 30 minutes</h2>
    ${PRESENTER_NOTES.map(rowBlock)}
    <section class="pn-row" aria-labelledby="pn-hand">
      <h3 id="pn-hand"><span class="pn-time">30 min</span> ${HANDOFF.title}</h3>
      <p class="pn-open"><strong>Link:</strong> <a href="${absUrl(HANDOFF.route)}">${HANDOFF.openLabel}</a> <span class="ig-url">${shortUrl(HANDOFF.route)}</span></p>
      <p><strong>On screen:</strong> ${HANDOFF.onScreen}</p>
      <p class="pn-say"><strong>Say:</strong> ${HANDOFF.say.map((s) => `“${s}”`).join(" ")}</p>
      <div class="pn-cols">
        <div><h4>How teachers choose a focus</h4>${bullets(HANDOFF.chooseFocus)}</div>
        <div><h4>You</h4>${bullets(HANDOFF.presenterDoes)}<p>${HANDOFF.downloads}</p></div>
      </div>
    </section>
    <h2>If something fails</h2>
    ${BACKUP_LABELS.map(([k]) => html`<section class="pn-fail"><h3>${BACKUP_ALL[k].problem}</h3>${bullets(BACKUP_ALL[k].steps)}</section>`)}
    <h2>The three downloads</h2>
    <ul>${DOWNLOAD_NAMES.map((d) => html`<li><strong>${d.name}</strong>, ${d.detail}: <a href="${absUrl(d.pdf.replace("/access-practice-lab", ""))}">PDF</a> and <a href="${absUrl(d.docx.replace("/access-practice-lab", ""))}">Word</a></li>`)}</ul>
  </article>`;
  return `<div class="ig">${toHtml(body)}</div>`;
}

export function notesMarkdown() {
  const L = [];
  const out = (s = "") => L.push(s);
  const bl = (items) => items.forEach((i) => out(`- ${i}`));
  out(`# ${NOTES_TITLE}`);
  out();
  out(
    `<!-- Generated by scripts/generate-intro-guide.mjs from src/intro/presenter-notes.js and data.js. Do not edit by hand. -->`,
  );
  out();
  out(
    "Run this script top to bottom. Times follow the 30-minute schedule, then the 20-minute exploration.",
  );
  out(
    `One link for teachers: [${ENTRANCE.short}](${ENTRANCE.url}) (printed on the Quick Guide with a QR code).`,
  );
  out();
  out("## Before the room fills");
  out();
  bl(ROOM_SETUP);
  out();
  out("## The 30 minutes");
  PRESENTER_NOTES.forEach((r) => {
    out();
    out(`### ${r.range} min: ${r.title}`);
    out();
    out(`**Link:** [${r.openLabel}](${absUrl(r.route)}) (\`${shortUrl(r.route)}\`)`);
    out();
    out("**Say:**");
    out();
    r.say.forEach((s) => out(`> ${s}`));
    out();
    out("**You:**");
    out();
    bl(r.presenterDoes);
    out();
    out("**Teachers:**");
    out();
    bl(r.teachersDo);
    out();
    out(`**Watch for:** ${r.watchFor}`);
    out();
    out(`**Backup:** ${r.backup}`);
  });
  out();
  out(`### 30 min: ${HANDOFF.title}`);
  out();
  out(
    `**Link:** [${HANDOFF.openLabel}](${absUrl(HANDOFF.route)}) (\`${shortUrl(HANDOFF.route)}\`)`,
  );
  out();
  out(`**On screen:** ${HANDOFF.onScreen}`);
  out();
  out("**Say:**");
  out();
  HANDOFF.say.forEach((s) => out(`> ${s}`));
  out();
  out("**How teachers choose a focus:**");
  out();
  bl(HANDOFF.chooseFocus);
  out();
  out("**You:**");
  out();
  bl(HANDOFF.presenterDoes);
  out();
  out(HANDOFF.downloads);
  out();
  out("## If something fails");
  BACKUP_LABELS.forEach(([k]) => {
    out();
    out(`### ${BACKUP_ALL[k].problem}`);
    out();
    bl(BACKUP_ALL[k].steps);
  });
  out();
  out("## The three downloads");
  out();
  DOWNLOAD_NAMES.forEach((d) =>
    out(
      `- **${d.name}**, ${d.detail}: [PDF](${absUrl(d.pdf.replace("/access-practice-lab", ""))}), [Word](${absUrl(d.docx.replace("/access-practice-lab", ""))})`,
    ),
  );
  out();
  out(
    `The featured lesson (${FEATURED_LESSON.title}) runs ${FEATURED_LESSON.minutes} minutes: ${FEATURED_LESSON.steps.map((s) => `${s.name} ${s.minutes}`).join(", ")}.`,
  );
  out();
  return `${L.join("\n")}\n`;
}
