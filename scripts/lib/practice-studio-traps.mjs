// The generator-tag table (data/practice-studio/generator-traps.json) compiled into the browser asset
// assets/studio-gen/traps.js, which StudioGen.make() reads to swap a generator's own wrong-answer tag for the taxonomy id
// it means (data/practice-studio/misconceptions.json), and which My thinking reads for the names of those traps.
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import { REPO_ROOT } from "../../tools/lib/curriculum-source.mjs";

export const TRAPS_JS = "assets/studio-gen/traps.js";

/** Every taxonomy id the table can produce, sorted. */
export function trapTargets(/** @type {any} */ map) {
  const ids = new Set(Object.values(map.tags || {}));
  for (const o of Object.values(map.byGenerator || {}))
    for (const id of Object.values(o)) ids.add(id);
  return [...ids].sort();
}

/** Problems with the table itself: a target that is not a taxonomy id, a malformed tag, an override for no generator. */
export function generatorTrapProblems(
  /** @type {any} */ map,
  /** @type {Record<string, any>} */ traps,
  /** @type {string[] | undefined} registered generator ids, when the caller has loaded them */ generatorIds,
) {
  const p = [];
  const tagOk = (/** @type {string} */ t) => /^[a-z0-9]+(-[a-z0-9]+)*$/.test(t);
  const check = (
    /** @type {string} */ where,
    /** @type {string} */ tag,
    /** @type {unknown} */ id,
  ) => {
    if (!tagOk(tag)) p.push(`generator-traps.json ${where}: "${tag}" is not a kebab-case tag`);
    if (typeof id !== "string" || !traps[id])
      p.push(
        `generator-traps.json ${where}: "${tag}" maps to "${id}", which is not in misconceptions.json`,
      );
  };
  for (const [tag, id] of Object.entries(map.tags || {})) check("tags", tag, id);
  for (const [gen, o] of Object.entries(map.byGenerator || {})) {
    if (generatorIds && !generatorIds.includes(gen))
      p.push(`generator-traps.json byGenerator: "${gen}" is not a registered generator`);
    for (const [tag, id] of Object.entries(/** @type {Record<string, string>} */ (o)))
      check(`byGenerator.${gen}`, tag, id);
  }
  return p;
}

/** The browser asset: the table plus the name, Spanish name and quick fix of every trap it can produce. */
export function trapsJs(/** @type {any} */ map, /** @type {Record<string, any>} */ traps) {
  const names = Object.fromEntries(
    trapTargets(map).map((id) => {
      const t = traps[id];
      if (!t) throw new Error(`generator-traps.json maps to unknown trap "${id}"`);
      return [id, { n: t.name, nEs: t.nameEs, fix: t.fix, fixEs: t.fixEs }];
    }),
  );
  const data = { tags: map.tags, byGenerator: map.byGenerator, names };
  const source = `/* GENERATED by scripts/generate-practice-studios.mjs from data/practice-studio/generator-traps.json and
 * data/practice-studio/misconceptions.json -- do not hand-edit. StudioGen.trapOf() (core.js) reads tags/byGenerator to
 * name a generated wrong answer by its taxonomy id; assets/studio/insight.js reads names for My thinking. */
(() => {
  const W = /** @type {any} */ (window);
  const G = (W.StudioGen = W.StudioGen || {});
  G.traps = ${JSON.stringify(data)};
})();
`;
  // Formatted the way Biome would, so `npm run check` passes on the output (same as tools/sync-curriculum-shell.mjs).
  return execFileSync(
    "npx",
    ["biome", "format", `--stdin-file-path=${join(REPO_ROOT, TRAPS_JS)}`],
    {
      cwd: REPO_ROOT,
      input: source,
      encoding: "utf8",
    },
  );
}
