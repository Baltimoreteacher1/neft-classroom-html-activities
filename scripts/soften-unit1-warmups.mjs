#!/usr/bin/env node
// soften-unit1-warmups.mjs — make the Unit 1 warmups an on-ramp, not a gate.
//
//   node scripts/soften-unit1-warmups.mjs [--dry-run]
//
// WHY
//
// Unit 1 is the first week of sixth grade and the warmup is the first thing a
// student sees each day. The shipped questions were doing real work — 5/6 × 540,
// 4,000 ÷ 80, comparing 3 × 240 against 2 × 400 — which is lesson-grade thinking
// asked before the lesson, from students who have not been in a math class since
// June. A warmup that stalls the room costs more than it teaches.
//
// Each replacement below keeps the SAME idea as the question it replaces
// (groups, half of an amount, equal groups, filling a box, continuing a pattern)
// and takes it down to one step with friendly numbers. 1-6 also changes topic:
// it was reviewing ratio tables and unit rates, which are Unit 3 and Unit 4
// content that Unit 1 has not taught, under a heading that said "Lesson 1-5
// Review".
//
// Warmups are NOT regenerated by any build step (scripts/generate-warmups.mjs is
// a one-off that reads spiral-review/bank.json, and Unit 1's warmups did not come
// from it), so the lesson configs are the source of truth. Applied to the base
// lessons and their small-group / catch-up variants together.
//
// Idempotent: re-running writes nothing once the easier set is in place.
//
// SUPERSEDED 2026-08-26 — this script no longer writes. Read the guard below
// before removing it.
//
// The Unit 1 warmups this file authored have since gained Spanish (stemEs,
// choicesEs, explanationEs) and per-choice misconceptionTags, and a third
// question each. NONE of that exists in the WARMUPS literal below, and the
// write path replaces `questions` wholesale — so running this file today would
// silently strip the Spanish and the tags off all six Unit 1 lessons and their
// variants, and no gate would say so, because the result is still a valid,
// well-ordered, easy warmup. That is the same shape as this repo's other
// two-owners-drifting failures.
//
// scripts/soften-warmup-onramps.mjs is now the single owner of these warmups
// and carries the current content. This file is kept for its history — the
// reasoning above is the record of WHY Unit 1 opens the way it does — and is
// inert.

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DRY = process.argv.includes("--dry-run");
const LESSONS = "lessons";
const UNIT_1 = /^(1-\d)(?:-(?:group1|group2|catchup))?$/;

const WARMUPS = {
  "1-1": {
    title: "Warmup: Let's Get Started",
    questions: [
      {
        stem: "Which expression shows 4 groups of 5 students?",
        choices: ["4 × 5", "4 + 5", "5 − 4", "5 ÷ 4"],
        correctIndex: 0,
        explanation: "Equal groups mean multiplication: 4 groups of 5 is 4 × 5 = 20.",
      },
      {
        stem: "What is 40 ÷ 10?",
        choices: ["4", "10", "30", "400"],
        correctIndex: 0,
        explanation: "40 split into groups of 10 makes 4 groups.",
      },
    ],
  },
  "1-2": {
    title: "Warmup: Lesson 1-1 Review",
    questions: [
      {
        stem: "A Ferris wheel has 10 cars. Each car holds 4 people. How many people ride at once?",
        choices: ["40 people", "14 people", "20 people", "44 people"],
        correctIndex: 0,
        explanation: "10 cars with 4 people each is 10 × 4 = 40 people.",
      },
      {
        stem: "What is half of 20?",
        choices: ["10", "5", "15", "40"],
        correctIndex: 0,
        explanation: "Half means split into 2 equal parts: 20 ÷ 2 = 10.",
      },
    ],
  },
  "1-3": {
    title: "Warmup: Lesson 1-2 Review",
    questions: [
      {
        stem: "What is 1/2 of 60?",
        choices: ["30", "20", "40", "120"],
        correctIndex: 0,
        explanation: "One half of 60 is 60 ÷ 2 = 30.",
      },
      {
        stem: "You multiply a whole number by a fraction smaller than 1. The answer is:",
        choices: [
          "Smaller than the number you started with",
          "Bigger than the number you started with",
          "Exactly the same",
          "Always zero",
        ],
        correctIndex: 0,
        explanation: "Taking part of an amount leaves you with less than the whole amount.",
      },
    ],
  },
  "1-4": {
    title: "Warmup: Lesson 1-3 Review",
    questions: [
      {
        stem: "A tram carries 10 passengers each trip. How many trips move 40 passengers?",
        choices: ["4 trips", "10 trips", "30 trips", "400 trips"],
        correctIndex: 0,
        explanation: "40 passengers in groups of 10 is 40 ÷ 10 = 4 trips.",
      },
      {
        stem: "What is 2.5 × 10?",
        choices: ["25", "2.5", "250", "12.5"],
        correctIndex: 0,
        explanation: "Multiplying by 10 moves each digit one place left: 2.5 becomes 25.",
      },
    ],
  },
  "1-5": {
    title: "Warmup: Lesson 1-4 Review",
    questions: [
      {
        stem: "Which box holds more — one that holds 20 cubic inches, or one that holds 30 cubic inches?",
        choices: [
          "The 30 cubic inch box",
          "The 20 cubic inch box",
          "They hold the same",
          "You cannot tell",
        ],
        correctIndex: 0,
        explanation: "More cubic inches means more space inside, so 30 holds more than 20.",
      },
      {
        stem: "A box is 2 cm long, 3 cm wide, and 2 cm tall. What is its volume?",
        choices: ["12 cubic cm", "7 cubic cm", "10 cubic cm", "24 cubic cm"],
        correctIndex: 0,
        explanation: "Volume multiplies all three edges: 2 × 3 × 2 = 12 cubic cm.",
      },
    ],
  },
  "1-6": {
    title: "Warmup: Lesson 1-5 Review",
    questions: [
      {
        stem: "A pattern goes 2, 4, 6, 8. What is the next number?",
        choices: ["10", "9", "12", "16"],
        correctIndex: 0,
        explanation: "Each number is 2 more than the one before, so 8 + 2 = 10.",
      },
      {
        stem: "The pattern rule is “add 5.” If you start at 10, what comes next?",
        choices: ["15", "5", "50", "20"],
        correctIndex: 0,
        explanation: "Follow the rule once: 10 + 5 = 15.",
      },
    ],
  },
};

/* The guard. Not a comment — a comment does not stop `node scripts/…`. */
console.error(
  "soften-unit1-warmups.mjs is SUPERSEDED and will not write.\n" +
    "  Its WARMUPS literal predates the Spanish and the misconceptionTags now on\n" +
    "  these lessons, so writing it would strip both. The current owner is\n" +
    "  scripts/soften-warmup-onramps.mjs — run that instead.",
);
process.exit(0);

// eslint-disable-next-line no-unreachable
let files = 0;
for (const folder of readdirSync(LESSONS).sort()) {
  const match = folder.match(UNIT_1);
  if (!match) continue;
  const spec = WARMUPS[match[1]];
  if (!spec) continue;

  const file = join(LESSONS, folder, "config.json");
  let config;
  try {
    config = JSON.parse(readFileSync(file, "utf8"));
  } catch {
    continue;
  }
  if (!config.warmup) continue;

  const questions = spec.questions.map((question, index) => ({
    id: `warmup-${match[1]}-${index + 1}`,
    ...question,
  }));
  const next = { ...config.warmup, title: spec.title, questions };
  if (JSON.stringify(config.warmup) === JSON.stringify(next)) continue;

  config.warmup = next;
  files++;
  if (!DRY) writeFileSync(file, `${JSON.stringify(config, null, 2)}\n`);
}

console.log(`${DRY ? "[dry-run] " : ""}unit 1 warmups: ${files} config(s) softened`);
