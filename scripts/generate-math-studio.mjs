#!/usr/bin/env node
// Generates Math Studio for every in-scope lesson (Units 2-9):
//   math/studio/<id>/index.html     the five-stage lesson experience
//   math/studio/index.html          the finder
//   data/math-studio/registry.json  the machine-readable integration inventory
//   docs/math-studio/COVERAGE.md    the lesson-by-lesson coverage audit
//   the hand-built Unit 4 practice studios: no duplicate lesson-stage bar, a Word problems button after the last step
//   node scripts/generate-math-studio.mjs [--check]
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { REPO_ROOT } from "../tools/lib/curriculum-source.mjs";
import { studioUrls } from "./generate-lesson-paths.mjs";
import { coverageReport } from "./lib/math-studio-coverage.mjs";
import { finderPage, lessonPage } from "./lib/math-studio-page.mjs";
import { buildRegistry } from "./lib/math-studio-registry.mjs";
import {
  WP_STEP_PANELS,
  wordProblemsCta,
  wordProblemsInline,
  wordProblemsInlineHead,
} from "./lib/word-problems-page.mjs";

const read = (rel) => readFileSync(join(REPO_ROOT, rel), "utf8");
const ASSET_DIR = "assets/math-studio";
const BAR = /\n?<!-- math-studio-bar:begin -->[\s\S]*?<!-- math-studio-bar:end -->/;

/** Cache-busting stamp: a hash of the studio runtime and the lab modules it imports. */
function stamp() {
  const h = createHash("sha256");
  for (const f of readdirSync(join(REPO_ROOT, ASSET_DIR)).sort())
    h.update(read(`${ASSET_DIR}/${f}`));
  h.update(read("assets/lib/stacked-fractions.js"));
  for (const f of ["model.mjs", "math.mjs", "lab.css"])
    h.update(read(`curriculum/learning-labs/shared/${f}`));
  return h.digest("hex").slice(0, 10);
}

const CTA = /\n?[ \t]*<!-- word-problems-cta:begin -->[\s\S]*?<!-- word-problems-cta:end -->/;
const WP =
  /\n?[ \t]*<!-- word-problems-(?:head|step-\d):begin -->[\s\S]*?<!-- word-problems-(?:head|step-\d):end -->/g;

/** Insert `block` at the end of panel `n` (before its closing </section>), which must hold no nested section. */
function intoPanel(html, n, block, url) {
  const start = html.indexOf(`id="panel-${n}"`);
  // skip the closing tags of our own "Real-world check" cards, which sit inside the panel
  const own = /<section class="wp-inline"[\s\S]*?<\/section>/g;
  const tail = html.slice(start).replace(own, (m) => " ".repeat(m.length));
  const end = start < 0 ? -1 : start + tail.indexOf("</section>");
  if (start < 0 || end < start || tail.slice(0, end - start).includes("<section"))
    throw new Error(`Unit 4 studio ${url} has no simple panel-${n}`);
  return html.slice(0, end).replace(/\s*$/, "") + block + html.slice(end);
}

/** A hand-built Unit 4 studio: no duplicate lesson-stage bar, "Real-world check" cards in steps 2, 3 and 5, and the
 * Word problems button closing its last step. */
function unit4Studio(html, id, url) {
  let out = html.replace(BAR, "").replace(CTA, "").replace(WP, "");
  // before the u4-clarity block when there is one: inject-u4-lab-bench.mjs rewrites that block in place and
  // leaves anything above it alone, so the two generators agree on the order
  const headBlock = `<!-- word-problems-head:begin -->\n${wordProblemsInlineHead()}\n<!-- word-problems-head:end -->\n`;
  const anchor = out.includes("<!-- u4-clarity:begin") ? "  <!-- u4-clarity:begin" : "</head>";
  out = out.replace(anchor, `${headBlock}${anchor}`);
  WP_STEP_PANELS.forEach((panel, n) => {
    out = intoPanel(
      out,
      panel + 1,
      `\n      <!-- word-problems-step-${n}:begin -->\n      ${wordProblemsInline(id, n)}\n      <!-- word-problems-step-${n}:end -->\n    `,
      url,
    );
  });
  return intoPanel(
    out,
    5,
    `\n      <!-- word-problems-cta:begin -->\n      ${wordProblemsCta(id, url)}\n      <!-- word-problems-cta:end -->\n    `,
    url,
  );
}

export function outputs() {
  const { lessons, skipped, stats } = buildRegistry();
  const manifest = JSON.parse(read("data/curriculum-launch-manifest.json"));
  const s = stamp();
  const files = new Map();
  for (const L of lessons) files.set(`math/studio/${L.id}/index.html`, lessonPage(L, s));
  files.set("math/studio/index.html", finderPage(lessons, s));
  const coverage = coverageReport(lessons, manifest, skipped);
  files.set(
    "data/math-studio/registry.json",
    `${JSON.stringify(
      {
        note: "Generated by scripts/generate-math-studio.mjs: the Math Studio integration inventory. Do not edit.",
        schemaVersion: 1,
        stages: ["explore", "understand", "practice", "apply", "reflect"],
        handoffs: stats,
        lessons: lessons.map((L) => ({
          id: L.id,
          unit: L.unit,
          title: L.title,
          standard: L.standard,
          objective: L.objective,
          concept: L.concept,
          ownExplore: L.explore ? L.explore.kind : undefined,
          route: `/math/studio/${L.id}/`,
          lab: {
            id: L.lab.id,
            href: L.lab.href,
            sharedWith: L.lab.lessons.filter((x) => x !== L.id),
          },
          practice: {
            regular: L.practice.urls.regular,
            challenge: L.practice.urls.challenge,
            regularItems: L.practice.regular.length,
            challengeItems: L.practice.challenge.length,
            modelHandoffs: [...L.practice.regular, ...L.practice.challenge]
              .filter((i) => i.model)
              .map((i) => i.id),
          },
          apply: Object.keys(L.apply)
            .filter((k) => k !== "optional")
            .concat("create"),
          reflect: {
            checks: L.reflect.checks.map((c) => c.id),
            errorAnalysis: Boolean(L.reflect.errorAnalysis),
          },
          coverage: coverage.results.find((r) => r.id === L.id).pass ? "pass" : "fail",
        })),
        outOfScope: skipped,
      },
      null,
      2,
    )}\n`,
  );
  files.set("docs/math-studio/COVERAGE.md", coverage.markdown);
  for (const L of lessons.filter((x) => x.unit === 4)) {
    for (const url of studioUrls(L.id)) {
      const rel = `${url.replace(/^\//, "")}index.html`;
      if (!rel.startsWith("math/unit-4/")) continue;
      files.set(rel, unit4Studio(read(rel), L.id, url));
    }
  }
  return { files, coverage, lessons, stats };
}

function main() {
  const check = process.argv.includes("--check");
  const { files, coverage, lessons, stats } = outputs();
  let stale = 0;
  for (const [rel, content] of files) {
    const path = join(REPO_ROOT, rel);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    stale++;
    if (check) console.error(`Stale: ${rel}`);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, content);
    }
  }
  const summary = `${lessons.length} lessons; coverage ${coverage.passed}/${lessons.length}; model hand-offs verified ${stats.verified}, refused ${stats.refused}`;
  if (check && stale) {
    console.error("Run: node scripts/generate-math-studio.mjs");
    process.exitCode = 1;
  } else
    console.log(
      check
        ? `Math Studio is current: ${summary}.`
        : `Generated Math Studio (${stale} files written): ${summary}.`,
    );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
export const ROOT = dirname(fileURLToPath(import.meta.url));
