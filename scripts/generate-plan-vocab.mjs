#!/usr/bin/env node
/* =============================================================================
 * generate-plan-vocab.mjs — build functions/_lib/plan-vocab.js
 * -----------------------------------------------------------------------------
 * The Plan Notes annotation layer is only useful to the curriculum nervous
 * system if its tags are drawn from vocabularies that already exist. That means
 * the API has to validate a note's misconception ids, standards, activity refs
 * and lesson ids at write time — and a Pages Function cannot read data/*.json
 * off disk at runtime.
 *
 * So the four vocabularies get compiled into one ES module the Function imports.
 * Generated, never hand-edited: when a 23rd misconception is added to
 * engine/core/misconceptions.js and the labels are regenerated, this runs too
 * and the API accepts the new tag. Nothing drifts.
 *
 *   node scripts/generate-plan-vocab.mjs [--check]
 *
 * --check exits non-zero if the committed file is stale, for the validator.
 * ========================================================================== */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "functions/_lib/plan-vocab.js");
const CHECK = process.argv.includes("--check");

const readJson = (rel) => JSON.parse(readFileSync(join(ROOT, rel), "utf8"));

const labels = readJson("data/misconception-labels.json");
const standards = readJson("data/ccss-standards.json");
const catalog = readJson("data/catalog.json");
const manifest = readJson("data/curriculum-manifest.json");

/* Misconceptions: id -> the teacher-facing label and the watch-for coaching
 * line. The annotator shows both; the AI pass is handed the same list so it can
 * only ever choose from tags that already exist. */
const misconceptions = Object.fromEntries(
  Object.entries(labels.tags).map(([id, t]) => [
    id,
    { label: t.label, watchFor: t.watchFor || "" },
  ]),
);

/* Standards: the MSDE-coded set the lessons actually use. shortLabel is what a
 * note chip displays; fullText is what the AI pass reads to decide relevance. */
const standardEntries = Object.entries(standards.standards).map(([id, s]) => [
  id,
  { shortLabel: s.shortLabel || id, unit: s.unit ?? null, fullText: s.fullText || "" },
]);

/* Activity refs are catalog paths, not free strings — a note that says "run
 * Factor Frenzy here" has to resolve to a page that exists, or it is a dead
 * link the day Joel needs it. Lessons are excluded: a lesson is the thing being
 * annotated, not a resource to pin inside it. */
const activities = catalog.entries
  .filter((e) => e.category !== "Lesson" && typeof e.path === "string")
  .map((e) => ({
    path: e.path,
    title: e.title,
    category: e.category,
    unit: e.unit ?? null,
  }));

const lessons = manifest.lessons.map((l) => ({
  id: l.id,
  unit: l.unit,
  lesson: l.lesson,
  title: l.title,
  standard: l.standard || null,
}));

const raw = `/* GENERATED by scripts/generate-plan-vocab.mjs — do not hand-edit.
 * Sources: data/misconception-labels.json, data/ccss-standards.json,
 *          data/catalog.json, data/curriculum-manifest.json
 *
 * The controlled vocabulary behind /curriculum/plan-notes/. Every structured
 * field on a note validates against one of these maps before it is written, so
 * an annotation layer cannot accumulate forty spellings of the same idea. */

export const MISCONCEPTIONS = ${JSON.stringify(misconceptions, null, 2)};

export const STANDARDS = ${JSON.stringify(Object.fromEntries(standardEntries), null, 2)};

export const ACTIVITIES = ${JSON.stringify(activities, null, 2)};

export const LESSONS = ${JSON.stringify(lessons, null, 2)};

export const MISCONCEPTION_IDS = new Set(Object.keys(MISCONCEPTIONS));
export const STANDARD_IDS = new Set(Object.keys(STANDARDS));
export const ACTIVITY_PATHS = new Set(ACTIVITIES.map((a) => a.path));
export const LESSON_IDS = new Set(LESSONS.map((l) => l.id));
`;

/* JSON.stringify emits quoted keys and no trailing commas; Biome rewrites both.
 * Without this the file could never be simultaneously fresh and formatted —
 * `npm run check` demanded one shape, this generator's --check demanded the
 * other, and whichever ran last "failed". Format here so the two agree, and so
 * a regenerated vocabulary never lands as a 1,100-line reformat diff. */
const body = execFileSync("npx", ["biome", "format", `--stdin-file-path=${OUT}`], {
  input: raw,
  encoding: "utf8",
  cwd: ROOT,
});

const prev = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return null;
  }
})();

if (CHECK) {
  if (prev !== body) {
    console.error(
      "plan-vocab: functions/_lib/plan-vocab.js is stale. Run `npm run generate-plan-vocab`.",
    );
    process.exit(1);
  }
  console.log("plan-vocab: up to date.");
  process.exit(0);
}

if (prev === body) {
  console.log("plan-vocab: unchanged.");
} else {
  writeFileSync(OUT, body);
  console.log(
    `plan-vocab: wrote ${Object.keys(misconceptions).length} misconceptions, ` +
      `${standardEntries.length} standards, ${activities.length} activities, ${lessons.length} lessons.`,
  );
}
