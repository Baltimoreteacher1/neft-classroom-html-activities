#!/usr/bin/env node
// Writes docs/motion-spanish-review.md: every Spanish string the motion figures show, next to its English, for a Spanish-speaking
// mathematics teacher to review. Numbers are masked (#) so each sentence pattern appears once. No claim of review is made by this file.
import { writeFileSync } from "node:fs";
import { JSDOM } from "jsdom";
import { registered } from "../curriculum/learning-labs/shared/models/index.mjs";
import { FIGURES } from "../shared/motion/figures/index.mjs";
import { figureSvg } from "../shared/motion/figures/mount.mjs";
import { blueprints } from "../tools/learning-labs/blueprints.mjs";

const mask = (t) =>
  t
    .replace(/\d[\d,.]*/g, "#")
    .replace(/\s+/g, " ")
    .trim();
const texts = (svg) => {
  const d = new JSDOM(`<body>${svg}</body>`).window.document;
  return [...d.querySelectorAll("text")].map((n) => n.textContent || "").filter(Boolean);
};
const startOf = (key) => {
  const bp = blueprints.find((b) => `${b.model.kind}:${b.model.mode}` === key)?.model;
  if (bp) return bp.values;
  const [kind, mode] = key.split(":");
  return registered({ kind, mode })?.values;
};

let out =
  "# Spanish review sheet: motion figures\n\nGenerated by `node scripts/export-motion-spanish-review.mjs`. **Not reviewed by a person.** Each row is a Spanish string a student or family sees, with the English it pairs with. Mark corrections in the last column. Numbers are shown as `#`.\n\nTerms to check first: *total* (the whole), *copias*, *barra*, *trozos*, *MCD* / *mcm*, *RIC* / *DAM*, decimal point (not comma).\n";
for (const f of FIGURES) {
  const key = f.keys[0];
  const values = startOf(key);
  const en = figureSvg(f, key, values, { lang: "en", width: 400 });
  const es = figureSvg(f, key, values, { lang: "es", width: 400 });
  const enT = texts(en.svg);
  const esT = texts(es.svg);
  const rows = new Map();
  const pair = enT.length === esT.length;
  esT.forEach((t, i) => {
    const m = mask(t);
    if (!/[a-záéíóúñ]{3}/i.test(m) || rows.has(m)) return;
    rows.set(m, pair ? mask(enT[i]) : "");
  });
  out += `\n## ${f.id} (${f.keys.join(", ")})\n\nTitle: ${f.title.es} / ${f.title.en}\n\n`;
  out += `**Full text, English then Spanish, at the starting numbers** (the screen-reader description; the picture's labels are the same sentences in pieces):\n\n> EN: ${f.describe(en.model, "en")}\n\n> ES: ${f.describe(es.model, "es")}\n\n`;
  out += `Controls: ${f
    .controls(key)
    .map((c) => `${c.labelEs} (${c.label})`)
    .join("; ")}\n\n`;
  out += `Picture labels in Spanish (line breaks are layout, not sentences) | Reviewer\n--- | ---\n`;
  for (const [sp] of rows) out += `${sp.replace(/\|/g, "\\|")} | \n`;
}
writeFileSync("docs/motion-spanish-review.md", out);
console.log(
  `wrote docs/motion-spanish-review.md: ${FIGURES.length} figures, ${out.split("\n").length} lines`,
);
