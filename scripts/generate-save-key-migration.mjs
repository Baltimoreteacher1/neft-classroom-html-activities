#!/usr/bin/env node
// Emits engine/core/toc-save-migration.js from data/toc-migration.json.
// The map has to be inlined: this runs in the browser before any lesson state
// is read, and there is no synchronous way to fetch a JSON manifest first.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const map = JSON.parse(readFileSync(join(ROOT, "data/toc-migration.json"), "utf8"));

const pairs = map.moves.filter((m) => m.from !== m.to).map((m) => [m.from, m.to]);

const body = `// GENERATED by scripts/generate-save-key-migration.mjs — do not hand-edit.
// Source: data/toc-migration.json. Regenerate with \`npm run generate-save-keys\`.
//
// Renumbering the curriculum to the publisher's TOC reused the old URL space:
// 48 old lesson numbers now serve DIFFERENT lessons. Saved work is keyed by
// lesson id (rma_<lessonId>[_<studentId>]), so without this remap a student who
// opens the new /lessons/1-1/ ("Math is Mine") would have last term's Prime
// Factorization answers restored into it.
//
// Two-phase on purpose. The map contains swaps (5-2 <-> 5-3) and long chains,
// so renaming keys one at a time would overwrite a destination that is itself
// still waiting to be read. Everything is read into memory first, then written,
// then the old keys are dropped.

const PREFIX = "rma_";
const DONE_FLAG = "rma_toc_migrated_v1";

/** old lesson id -> new lesson id */
export const ID_MAP = new Map(${JSON.stringify(pairs)});

// rma_<id>, rma_<id>_<student>, rma_<id>-group1, rma_<id>-group1_<student>
const KEY_RE = /^rma_(\\d+-\\d+)((?:-(?:group\\d+|catchup))?)((?:_.*)?)$/;

/**
 * Remap every saved-work key from the old numbering to the new one. Idempotent:
 * a flag marks the device done, so a student who already migrated is untouched.
 * Returns the number of keys moved (0 if already migrated).
 */
export function migrateSavedWork(storage) {
  const store = storage || (typeof localStorage !== "undefined" ? localStorage : null);
  if (!store) return 0;
  try {
    if (store.getItem(DONE_FLAG)) return 0;
  } catch {
    return 0; // storage disabled (private mode) — nothing to migrate
  }

  const staged = [];
  for (let i = 0; i < store.length; i++) {
    const key = store.key(i);
    if (!key || !key.startsWith(PREFIX)) continue;
    const m = KEY_RE.exec(key);
    if (!m) continue;
    const next = ID_MAP.get(m[1]);
    if (!next) continue;
    staged.push([key, \`\${PREFIX}\${next}\${m[2]}\${m[3]}\`, store.getItem(key)]);
  }

  // Phase 1 read is complete; only now is it safe to write.
  for (const [, newKey, value] of staged) {
    if (value !== null) store.setItem(newKey, value);
  }
  // Drop old keys last, and never one that a later entry just claimed.
  const claimed = new Set(staged.map(([, newKey]) => newKey));
  for (const [oldKey] of staged) {
    if (!claimed.has(oldKey)) store.removeItem(oldKey);
  }

  store.setItem(DONE_FLAG, new Date().toISOString());
  return staged.length;
}
`;

writeFileSync(join(ROOT, "engine/core/toc-save-migration.js"), body);
console.log(`Wrote engine/core/toc-save-migration.js (${pairs.length} id mappings)`);
