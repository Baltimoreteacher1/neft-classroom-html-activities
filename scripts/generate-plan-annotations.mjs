#!/usr/bin/env node
/* =============================================================================
 * generate-plan-annotations.mjs — roll Plan Notes up into data/plan-annotations.json
 * -----------------------------------------------------------------------------
 * This is the half of Plan Notes that pays off later. The annotator is where
 * Joel writes what he knows about teaching a plan; this is where the structured
 * part of it becomes something the curriculum nervous system can read.
 *
 *   node scripts/generate-plan-annotations.mjs [--check]
 *
 * ONE-DIRECTIONAL. Nothing else writes data/plan-annotations.json, and this
 * never writes back to D1. A rollup that could edit its own source would make
 * the annotations unreliable as a record of what the teacher actually said.
 *
 * FREE TEXT NEVER LEAVES. `body` and `bodyAlt` are the teacher's own words about
 * his own classes and they stay in D1. Only the controlled-vocabulary fields —
 * misconception ids, activity paths, levels, minutes — are rolled up, because
 * those are the only ones anything downstream can consume anyway. The test
 * asserts this; it is not a convention.
 *
 * Reads D1 through wrangler, so it needs credentials and does not run in CI. It
 * is a nightly/manual job. With no database reachable it exits 0 and leaves the
 * committed file alone rather than writing an empty rollup over a good one —
 * an empty gap report reads as "no problems", which is the opposite of true.
 * ========================================================================== */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "data/plan-annotations.json");
const CHECK = process.argv.includes("--check");

const QUERY = `
  SELECT anchor_key, kind, misconception_tags, standards, activity_refs, level,
         timing_min, origin
  FROM plan_note
  WHERE deleted_at IS NULL
`;

function readD1() {
  try {
    const out = execFileSync(
      "npx",
      [
        "wrangler",
        "d1",
        "execute",
        "neft-student-progress",
        "--remote",
        "--json",
        "--command",
        QUERY.replace(/\s+/g, " ").trim(),
      ],
      { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    );
    const parsed = JSON.parse(out);
    const rows = Array.isArray(parsed) ? parsed[0]?.results : parsed?.result?.[0]?.results;
    return Array.isArray(rows) ? rows : null;
  } catch {
    return null;
  }
}

const parseArr = (v) => {
  try {
    const out = JSON.parse(v);
    return Array.isArray(out) ? out : [];
  } catch {
    return [];
  }
};

function rollup(rows) {
  const byAnchor = new Map();

  for (const r of rows) {
    const key = r.anchor_key;
    if (!byAnchor.has(key)) {
      byAnchor.set(key, {
        anchorKey: key,
        lessonId: key.startsWith("lesson:") ? key.slice(7) : null,
        noteCount: 0,
        aiDrafted: 0,
        misconceptions: new Set(),
        standards: new Set(),
        activities: new Set(),
        levelsAddressed: new Set(),
        notedMinutes: 0,
        kinds: {},
      });
    }
    const a = byAnchor.get(key);
    a.noteCount += 1;
    if (r.origin === "ai") a.aiDrafted += 1;
    a.kinds[r.kind] = (a.kinds[r.kind] || 0) + 1;
    for (const t of parseArr(r.misconception_tags)) a.misconceptions.add(t);
    for (const s of parseArr(r.standards)) a.standards.add(s);
    for (const p of parseArr(r.activity_refs)) a.activities.add(p);
    if (r.level != null) a.levelsAddressed.add(r.level);
    if (r.timing_min) a.notedMinutes += r.timing_min;
  }

  const plans = [...byAnchor.values()]
    .map((a) => ({
      anchorKey: a.anchorKey,
      lessonId: a.lessonId,
      noteCount: a.noteCount,
      aiDrafted: a.aiDrafted,
      kinds: a.kinds,
      misconceptions: [...a.misconceptions].sort(),
      standards: [...a.standards].sort(),
      activities: [...a.activities].sort(),
      levelsAddressed: [...a.levelsAddressed].sort(),
      notedMinutes: a.notedMinutes,
    }))
    .sort((x, y) => x.anchorKey.localeCompare(y.anchorKey));

  // The cross-plan view: which mistakes Joel flags most often, across every
  // plan he has marked up. That ranking is the thing no other data source here
  // can produce, because nothing else records what a teacher expects to happen.
  const tally = new Map();
  for (const p of plans) {
    for (const m of p.misconceptions) {
      if (!tally.has(m)) tally.set(m, { tag: m, plans: 0, lessons: [] });
      const t = tally.get(m);
      t.plans += 1;
      if (p.lessonId) t.lessons.push(p.lessonId);
    }
  }

  return {
    note: "GENERATED by scripts/generate-plan-annotations.mjs — do not hand-edit. Read-only for consumers.",
    schemaVersion: 1,
    planCount: plans.length,
    noteCount: plans.reduce((n, p) => n + p.noteCount, 0),
    plans,
    misconceptionsByFrequency: [...tally.values()].sort(
      (a, b) => b.plans - a.plans || a.tag.localeCompare(b.tag),
    ),
  };
}

/* Everything above is pure. Everything below TALKS TO D1 AND EXITS, so it runs
 * only when this file is the entry point — importing it (the tests do) must not
 * fire a remote query or kill the importing process. This repo has been bitten
 * by exactly that before. */
function main() {
  const rows = readD1();
  if (!rows) {
    console.log(
      "plan-annotations: no database reachable — leaving the committed rollup alone.\n" +
        "  (Needs wrangler credentials; this job is nightly/manual, not CI.)",
    );
    process.exit(0);
  }

  const next = `${JSON.stringify(rollup(rows), null, 2)}\n`;
  const prev = (() => {
    try {
      return readFileSync(OUT, "utf8");
    } catch {
      return null;
    }
  })();

  if (CHECK) {
    if (prev !== next) {
      console.error("plan-annotations: data/plan-annotations.json is stale.");
      process.exit(1);
    }
    console.log("plan-annotations: up to date.");
    process.exit(0);
  }

  if (prev === next) {
    console.log("plan-annotations: unchanged.");
  } else {
    writeFileSync(OUT, next);
    const parsed = JSON.parse(next);
    console.log(
      `plan-annotations: ${parsed.planCount} plans, ${parsed.noteCount} notes, ` +
        `${parsed.misconceptionsByFrequency.length} distinct misconceptions.`,
    );
  }
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) main();

export { rollup };
