/**
 * Returns the theme object for a given unit number (defaults to Unit 1).
 */
export function getUnitTheme(unitNumber) {
  const num = parseInt(unitNumber, 10) || 1;
  return UNIT_THEMES[num] || UNIT_THEMES[1];
}

