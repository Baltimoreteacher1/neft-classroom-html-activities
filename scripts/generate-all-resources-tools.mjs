#!/usr/bin/env node
/**
 * Builds curriculum/all-resources/tools.json: every `/curriculum/<slug>/` tool
 * page with a human title, a one-line description, a category and whether the
 * page sits behind the teacher gate.
 *
 *   node scripts/generate-all-resources-tools.mjs          write
 *   node scripts/generate-all-resources-tools.mjs --check  fail if the file is stale
 *
 * WHY A GENERATOR: the curated Resources guide lists 32 tools; the curriculum
 * folder ships 59 tool pages, and 29 had no listing anywhere a teacher could
 * browse. Title and description are read from each page's own <title> and
 * <meta name="description">, so the directory cannot drift from the page it
 * names. Teacher gating comes from the REAL predicate the middleware uses
 * (functions/_lib/teacher-surface.js), never a second copy of the rule.
 * Category and audience come from data/curriculum-resource-guide.json where the
 * guide already classifies the page; the rest fall back to "explore".
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { isTeacherSurface } from "../functions/_lib/teacher-surface.js";

const ROOT = resolve(fileURLToPath(new URL("..", import.meta.url)));
const OUT = join(ROOT, "curriculum", "all-resources", "tools.json");
const FALLBACK_CATEGORY = "explore";
/** The directory does not list itself. */
const SELF = "all-resources";
/** Where the guide does not classify a page, the first matching slug rule decides. */
const SLUG_CATEGORY = [
  [
    /(adventure-review|test-review|test-practice|review-mission|review-expeditions|division-foundry)/,
    "review",
  ],
  [/(family|extra-help|student-launch|student-digital|data-privacy)/, "support"],
  [
    /(^|-)(matrix|map|about|runtime|publisher-demo|lesson-materials|units|forge|class-brain|my-progress)($|-)/,
    "plan",
  ],
  [/(practice|fluency|monster|ratio-quest|unit-rate-market|math-workbench)/, "practice"],
];
const categoryFor = (slug, known) =>
  known ?? SLUG_CATEGORY.find(([re]) => re.test(slug))?.[1] ?? FALLBACK_CATEGORY;

const decode = (s) =>
  s
    .replace(/&amp;/g, "&")
    .replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"')
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/\s+/g, " ")
    .trim();

/** "Curriculum Map — Neft Teacher" -> "Curriculum Map"; keeps a title that is only a brand. */
export function cleanTitle(raw) {
  const parts = decode(raw).split(/\s+(?:[—–|·-])\s+/);
  const brand = /^(neft teacher|eduwonderlab|neft curriculum)/i;
  const kept = parts.filter((p, i) => i === 0 || !brand.test(p));
  return kept.slice(0, 2).join(" — ");
}

export function readPage(html) {
  const title = html.match(/<title>([\s\S]*?)<\/title>/i)?.[1] ?? "";
  const desc =
    html.match(/<meta[^>]+name=["']description["'][^>]+content=["']([^"']*)["']/i)?.[1] ?? "";
  return { title: cleanTitle(title), description: decode(desc) };
}

function guideIndex() {
  const guide = JSON.parse(readFileSync(join(ROOT, "data/curriculum-resource-guide.json"), "utf8"));
  const byPath = new Map();
  for (const r of guide.resources) {
    const path = r.href.split("#")[0].split("?")[0];
    if (!byPath.has(path)) byPath.set(path, { category: r.category, audience: r.audience });
  }
  return { byPath, categories: guide.categories };
}

export function build() {
  const base = join(ROOT, "curriculum");
  const { byPath, categories } = guideIndex();
  const tools = readdirSync(base)
    .filter(
      (d) =>
        d !== SELF &&
        statSync(join(base, d)).isDirectory() &&
        existsSync(join(base, d, "index.html")),
    )
    .sort()
    .map((slug) => {
      const url = `/curriculum/${slug}/`;
      const { title, description } = readPage(readFileSync(join(base, slug, "index.html"), "utf8"));
      const known = byPath.get(url);
      return {
        url,
        title: title || slug,
        description,
        category: categoryFor(slug, known?.category),
        teacherOnly: isTeacherSurface(url),
      };
    });
  return {
    $comment: "GENERATED by scripts/generate-all-resources-tools.mjs — do not hand-edit.",
    categories,
    tools,
  };
}

const serialize = (doc) => `${JSON.stringify(doc, null, 1)}\n`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = serialize(build());
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== next) {
      console.error(
        "FAIL all-resources tools.json is stale — run: node scripts/generate-all-resources-tools.mjs",
      );
      process.exit(1);
    }
    console.log("PASS all-resources tools.json is current");
  } else {
    writeFileSync(OUT, next);
    console.log(`wrote ${OUT.replace(`${ROOT}/`, "")}`);
  }
}
