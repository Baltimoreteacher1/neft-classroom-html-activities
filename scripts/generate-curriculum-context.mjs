#!/usr/bin/env node
/** Keep the unit browser's examples and activity recommendations on the same
 * lesson numbers as the taught curriculum. Legacy asset URLs are deliberately
 * preserved: folder numbers are not curriculum ownership. */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { listLessonDirs, loadLessonConfig, REPO_ROOT } from "../tools/lib/curriculum-source.mjs";

export function buildCurriculumContext(lessons) {
  const realWorld = {};
  const projects = {};
  for (const [id, config] of lessons) {
    const scenario = config.connect?.scenario;
    if (typeof scenario === "string" && scenario.trim()) realWorld[id] = scenario.trim();
    const seen = new Set();
    projects[id] = (config.projects || []).flatMap((project) => {
      // Only curriculum-owned links belong in this local resource catalogue.
      if (!/^\/(?!\/)/.test(project.href || "") || !project.title || seen.has(project.href)) {
        return [];
      }
      seen.add(project.href);
      // Titles inherited from the old numbering still name their original unit.
      // Keep the actual project topic and route without claiming a current unit.
      const title = project.title.replace(/^Unit\s+\d+\s+Project\s*[—–:-]?\s*/i, "Project — ");
      return [{ text: `${project.emoji ? `${project.emoji} ` : ""}${title}`, href: project.href }];
    });
  }
  return { realWorld, projects };
}

export function contextFiles() {
  const ids = listLessonDirs({ filter: /^\d+-\d+(?:-flagship)?$/ }).sort((a, b) =>
    a.localeCompare(b, "en", { numeric: true }),
  );
  const context = buildCurriculumContext(ids.map((id) => [id, loadLessonConfig(id)]));
  return new Map([
    ["assets/curriculum-real-world.json", `${JSON.stringify(context.realWorld, null, 2)}\n`],
    [
      "curriculum/lesson-context.js",
      "// Generated by scripts/generate-curriculum-context.mjs; edit the lesson configs.\n" +
        `window.LESSON_PROJECTS = ${JSON.stringify(context.projects, null, 2)};\n`,
    ],
  ]);
}

function main() {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [file, expected] of contextFiles()) {
    if (check) {
      let actual;
      try {
        actual = readFileSync(join(REPO_ROOT, file), "utf8");
      } catch {
        actual = null;
      }
      if (actual !== expected) {
        console.error(
          `Stale curriculum context: ${file}. Run npm run generate-curriculum-context.`,
        );
        stale++;
      }
    } else {
      writeFileSync(join(REPO_ROOT, file), expected);
      console.log(`Generated ${file}`);
    }
  }
  if (stale) process.exitCode = 1;
  else if (check)
    console.log("Curriculum examples and project recommendations match the lesson sources.");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
