#!/usr/bin/env node
// Derives data/ewl/integration-map.json — which Living Math Canvas scenes, Math Reality Lab investigations, Forge bots,
// Invariant hunts and Sketch stories belong to each lesson, and which learning labs inherit them. It is DERIVED from
// those surfaces' own data (their `lessons[]`), never edited by hand, so the cockpit, the learning-lab "Go deeper"
// card and the Lesson Paths cannot drift from the activities they point at.
//   node scripts/generate-ewl-integration-map.mjs [--check]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => JSON.parse(readFileSync(join(ROOT, p), "utf8"));
const OUT = "data/ewl/integration-map.json";

export function sketchStories() {
  const ctx = { window: {} };
  ctx.window = ctx;
  vm.createContext(ctx);
  vm.runInContext(readFileSync(join(ROOT, "assets/ewl/sketch-stories.js"), "utf8"), ctx);
  return ctx.EWL?.SketchStories || [];
}

export function build() {
  /** @type {Record<string, Record<string, string[]>>} */
  const lessons = {};
  const add = (kind, id, lessonIds) => {
    for (const l of lessonIds || []) {
      const e = (lessons[l] ||= {});
      e[kind] ||= [];
      if (!e[kind].includes(id)) e[kind].push(id);
    }
  };
  for (const s of read("data/ewl/canvas-scenes.json").scenes) add("canvas", s.id, s.lessons);
  for (const i of read("data/ewl/investigations.json").investigations) add("lab", i.id, i.lessons);
  for (const b of read("data/ewl/forge-bots.json").bots) add("forge", b.id, b.lessons);
  for (const h of read("data/ewl/invariants.json").hunts) add("invariant", h.id, h.lessons);
  for (const s of sketchStories()) add("sketch", s.id, s.lessons);
  const sorted = Object.fromEntries(
    Object.keys(lessons)
      .sort((a, b) => a.localeCompare(b, "en", { numeric: true }))
      .map((k) => [k, lessons[k]]),
  );
  // a learning lab inherits the activities of the lessons it is connected to
  /** @type {Record<string, Record<string, string[]>>} */
  const learningLabs = {};
  const labDir = join(ROOT, "curriculum/learning-labs");
  for (const slug of readdirSafe(labDir)) {
    const f = join(labDir, slug, "content.json");
    if (!existsSync(f)) continue;
    const lab = JSON.parse(readFileSync(f, "utf8"));
    const entry = {};
    for (const l of lab.lessons || [])
      for (const [kind, ids] of Object.entries(sorted[l.id] || {})) {
        entry[kind] ||= [];
        for (const id of ids) if (!entry[kind].includes(id)) entry[kind].push(id);
      }
    if (Object.keys(entry).length) learningLabs[slug] = entry;
  }
  return {
    schemaVersion: 1,
    note: "GENERATED by scripts/generate-ewl-integration-map.mjs from the lessons[] of each Curriculum 2.0 surface. Do not edit by hand.",
    lessons: sorted,
    learningLabs,
  };
}
function readdirSafe(dir) {
  try {
    return readdirSync(dir).filter((n) => !n.startsWith(".") && n !== "shared");
  } catch {
    return [];
  }
}

import { readdirSync } from "node:fs";

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = `${JSON.stringify(build(), null, 2)}\n`;
  const path = join(ROOT, OUT);
  const cur = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (cur !== text) {
      console.error(`${OUT} is stale; run: node scripts/generate-ewl-integration-map.mjs`);
      process.exit(1);
    }
    console.log("integration map is current.");
  } else {
    writeFileSync(path, text);
    const m = JSON.parse(text);
    console.log(
      `Wrote ${OUT}: ${Object.keys(m.lessons).length} lessons, ${Object.keys(m.learningLabs).length} learning labs.`,
    );
  }
}
