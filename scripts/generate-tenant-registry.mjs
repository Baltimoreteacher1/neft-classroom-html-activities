/* Compiles data/tenants.json into functions/_lib/tenant-registry.js.
 *
 * Pages Functions cannot read data/*.json at runtime, so the registry ships as
 * a generated module — the exact pattern generate-plan-vocab.mjs established.
 * `--check` fails when the committed module is stale (wired into validate as
 * validate:tenants).
 *
 * Validation enforced here, at the SoT boundary:
 *   - tenant ids are URL-safe slugs, unique;
 *   - dbBinding matches TENANT_DB_<UPPERID> so a registry entry can never
 *     name an unrelated binding (least privilege by construction);
 *   - joinCodeHash is a 64-char sha256 hex — never a plain code;
 *   - status is one of staging | active | offboarded.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "data", "tenants.json");
const OUT = join(ROOT, "functions", "_lib", "tenant-registry.js");

const reg = JSON.parse(readFileSync(SRC, "utf8"));
const STATUSES = new Set(["staging", "active", "offboarded"]);
const seen = new Set();
for (const t of reg.tenants) {
  if (!/^[a-z0-9][a-z0-9-]{1,30}$/.test(t.id)) fail(`tenant id not a url-safe slug: ${t.id}`);
  if (seen.has(t.id)) fail(`duplicate tenant id: ${t.id}`);
  seen.add(t.id);
  const expected = `TENANT_DB_${t.id.toUpperCase().replace(/-/g, "_")}`;
  if (t.dbBinding !== expected) {
    fail(`tenant ${t.id}: dbBinding must be ${expected}, got ${t.dbBinding}`);
  }
  if (!/^[0-9a-f]{64}$/.test(t.joinCodeHash || "")) {
    fail(`tenant ${t.id}: joinCodeHash must be sha256 hex (never a plain code)`);
  }
  if (!STATUSES.has(t.status)) fail(`tenant ${t.id}: unknown status ${t.status}`);
}

function fail(msg) {
  console.error(`FAIL generate-tenant-registry — ${msg}`);
  process.exit(1);
}

// Emit Biome-formatted source: identifier keys unquoted, others quoted.
function lit(value, indent) {
  if (typeof value === "string") return JSON.stringify(value);
  const pad = "  ".repeat(indent);
  const inner = "  ".repeat(indent + 1);
  const entries = Object.entries(value).map(([k, v]) => {
    const key = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
    return `${inner}${key}: ${lit(v, indent + 1)},`;
  });
  return `{\n${entries.join("\n")}\n${pad}}`;
}

const body = `// GENERATED by scripts/generate-tenant-registry.mjs from data/tenants.json.
// Do not edit by hand — edit the JSON and regenerate (validate:tenants checks freshness).
export const TENANTS = ${lit(Object.fromEntries(reg.tenants.map((t) => [t.id, t])), 0)};

export function resolveTenant(id) {
  return Object.prototype.hasOwnProperty.call(TENANTS, id) ? TENANTS[id] : null;
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {}
  if (current !== body) {
    console.error(
      "FAIL validate:tenants — functions/_lib/tenant-registry.js is stale; run: node scripts/generate-tenant-registry.mjs",
    );
    process.exit(1);
  }
  console.log(`PASS validate:tenants — registry fresh (${reg.tenants.length} tenant(s)).`);
} else {
  writeFileSync(OUT, body);
  console.log(`tenant-registry: wrote ${reg.tenants.length} tenant(s) -> ${OUT}`);
}
