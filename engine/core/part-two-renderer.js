function esc(value) {
  return String(value ?? "").replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c],
  );
}

function el(tag, className, html) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (html != null) node.innerHTML = html;
  return node;
}

/** A labelled, auto-persisting textarea on this page's phase. */
function field(state, phase, key, label, placeholder, rows = 3) {
  const wrap = el("div", "syw-field");
  wrap.append(el("label", "syw-label", `<span>${esc(label)}</span>`));
  const input = document.createElement("textarea");
  input.rows = rows;
  input.id = `p2-${phase}-${key}`;
  input.className = "text-input syw-input";
  input.placeholder = placeholder || "";
  input.value = (state.getResponse && state.getResponse(phase, key)) || "";
  input.addEventListener(
    "input",
    () => state.saveResponse && state.saveResponse(phase, key, input.value),
  );
  wrap.querySelector("label").setAttribute("for", input.id);
  wrap.append(input);
  return wrap;
}

function phaseHeading(host, num, icon, title, lede) {
  host.append(
    el(
      "header",
      "phase-header",
      `<div class="section-title" style="font-size:1.9rem;">${icon} ${esc(title)}</div>
       <div class="section-desc" style="font-size:1.05rem;">${esc(lede)}</div>`,
    ),
  );
  host.firstElementChild.setAttribute("data-phase-num", String(num));
}

/* ── Phase 0 · Review ─────────────────────────────────────────────────────── */

function renderReview(host, state, ctx, config) {
  phaseHeading(
    host,
    1,
    "🔁",
    "Review",
    "This is day 2. Remind yourself what we did, then answer one question to warm up.",
  );

  // resolveContentObjective / resolveLanguageObjective return text that is
  // ALREADY HTML-escaped (same contract app.js openObjectives relies on), so
  // running esc() over them again would print "&amp;" at students.
  const card = el("section", "card card-teal");
  card.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 10px; font-size:1.3rem; color:#0f172a;">📌 What we are still working on</h3>
       <p style="margin:0 0 6px; font-size:1.1rem; font-weight:700; color:#0f172a; line-height:1.5;">🎯 ${resolveContentObjective(config)}</p>
       <p style="margin:0; font-size:1.05rem; font-weight:600; color:#334155; line-height:1.5;">🗣️ ${resolveLanguageObjective(config)}</p>
       <p style="margin:12px 0 0; font-size:.95rem; color:#475569;">Need the full page? Open <strong>📓 Math Notes</strong> or <strong>🎯 Objectives</strong> above.</p>`,
    ),
  );
  host.append(card);

  const vocab = Array.isArray(config.vocabulary)
    ? config.vocabulary.filter((v) => v && v.term)
    : [];
  if (vocab.length) {
    const vcard = el("section", "card card-coral");
    vcard.append(
      el(
        "div",
        null,
        `<h3 style="margin:0 0 10px; font-size:1.3rem; color:#0f172a;">🔑 Words we need today</h3>
         <ul style="margin:0; padding-left:20px; display:flex; flex-direction:column; gap:7px;">
           ${vocab
             .map(
               (v) =>
                 `<li style="font-size:1.02rem; line-height:1.5; color:#0f172a;"><strong>${esc(v.term)}</strong>${
                   v.definition ? ` — ${esc(v.definition)}` : ""
                 }</li>`,
             )
             .join("")}
         </ul>`,
      ),
    );
    host.append(vcard);
  }

  // One autograded question, reusing the core lesson's own on-level practice so
  // Part 2 invents no mathematics of its own.
  const check = config.reviewCheck;
  if (check && (check.stem || check.prompt)) {
    const ccard = el("section", "card");
    ccard.append(
      el(
        "div",
        null,
        `<h3 style="margin:0 0 4px; font-size:1.3rem; color:#0f172a;">⚡ Quick check</h3>
         <p style="margin:0 0 12px; font-size:1rem; color:#475569;">One question from yesterday. Get it right and you are ready for today's problem.</p>`,
      ),
    );
    const slot = el("div");
    ccard.append(slot);
    renderComponent(slot, check, () => {}, { number: 1, total: 1, tier: "onLevel" });
    host.append(ccard);
  }

  host.append(advanceButton("See today's problem 📋 →", state, ctx, 0));
}

/* ── Phase 1 · Today's Problem ────────────────────────────────────────────── */

/**
 * The Apply text ends with its task sentence ("Question: …" in the Reveal
 * decks). Splitting it out is the same treatment the slide deck gives it — the
 * scenario is the reading, the question is the job.
 */
function splitProblem(text) {
  const raw = String(text || "").trim();
  const at = raw.search(/(^|\n)\s*Question:\s*/i);
  if (at < 0) return { scenario: raw, question: "" };
  return {
    scenario: raw.slice(0, at).trim(),
    question: raw
      .slice(at)
      .replace(/(^|\n)\s*Question:\s*/i, "")
      .trim(),
  };
}

function renderProblem(host, state, ctx, config) {
  phaseHeading(
    host,
    2,
    "📋",
    "Today's Problem",
    "Read it twice. Then write what you know and what the problem is asking — before any arithmetic.",
  );

  const wp = config.revealWordProblem || {};
  const { scenario, question } = splitProblem(wp.text);

  const card = el("section", "card wp-card");
  card.append(
    el(
      "div",
      "wp-head",
      `<span class="wp-badge" aria-hidden="true">📋 Today</span>
       <h3 class="wp-title">${esc(wp.title || "Apply")}</h3>`,
    ),
  );

  if (scenario) {
    const p = el("p", "wp-text");
    p.setAttribute("data-annotate", "word-problem");
    p.textContent = scenario;
    card.append(p);
  }

  if (wp.image) {
    const fig = el("figure", "wp-figure");
    const img = document.createElement("img");
    img.className = "wp-img";
    img.setAttribute("loading", "lazy");
    img.setAttribute("decoding", "async");
    img.src = String(wp.image);
    img.alt = String(wp.imageAlt || wp.title || "Figure for today's problem");
    fig.append(img);
    attachImageZoom(img);
    card.append(fig);
  }

  if (question) {
    card.append(
      el(
        "div",
        null,
        `<p style="margin:14px 0 0; padding:12px 16px; background:#ecfeff; border-left:4px solid #0e7490; border-radius:10px; font-size:1.12rem; font-weight:700; color:#0f172a; line-height:1.5;">❓ ${esc(question)}</p>`,
      ),
    );
  }
  host.append(card);

  const think = el("section", "card");
  think.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 10px; font-size:1.25rem; color:#0f172a;">🧭 Before you solve</h3>`,
    ),
  );
  think.append(
    field(state, 1, "know", "1 · What we KNOW", "The numbers and facts the problem gives us…"),
  );
  think.append(
    field(state, 1, "need", "2 · What we NEED to find", "What is the problem actually asking for?"),
  );
  host.append(think);

  host.append(advanceButton("Break into groups 👥 →", state, ctx, 1));
}

/* ── Phase 2 · Group Work ─────────────────────────────────────────────────── */

function renderGroups(host, state, _ctx, config) {
  phaseHeading(
    host,
    3,
    "👥",
    "Group Work",
    "Everyone in the group solves the same problem. Each person has one job.",
  );

  const picked = (state.getResponse && state.getResponse(2, "role")) || "";
  const roleCard = el("section", "card");
  roleCard.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 4px; font-size:1.3rem; color:#0f172a;">🧩 Pick your job</h3>
       <p style="margin:0 0 14px; font-size:1rem; color:#475569;">Tap your job. Every job is needed — the group cannot finish without all four.</p>`,
    ),
  );
  const grid = el("div", "grid-2");
  grid.style.cssText =
    "display:grid; grid-template-columns:repeat(auto-fit,minmax(240px,1fr)); gap:12px;";
  ROLES.forEach((role) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "card";
    btn.setAttribute("aria-pressed", String(picked === role.key));
    btn.dataset.role = role.key;
    btn.style.cssText =
      "text-align:left; cursor:pointer; border:2px solid transparent; padding:14px 16px; margin:0;";
    btn.innerHTML = `
      <div style="font-size:1.12rem; font-weight:800; color:#0f172a;">${role.icon} ${esc(role.name)}</div>
      <div style="margin-top:6px; font-size:.98rem; color:#334155; line-height:1.5;">${esc(role.job)}</div>
      <div style="margin-top:8px; font-size:.93rem; color:#0e7490; font-style:italic;">“${esc(role.starter)}”</div>`;
    const paint = () => {
      const on = btn.getAttribute("aria-pressed") === "true";
      btn.style.borderColor = on ? "#0f766e" : "transparent";
      btn.style.background = on ? "#f0fdfa" : "";
    };
    paint();
    btn.addEventListener("click", () => {
      grid.querySelectorAll("[data-role]").forEach((b) => {
        b.setAttribute("aria-pressed", "false");
        b.style.borderColor = "transparent";
        b.style.background = "";
      });
      btn.setAttribute("aria-pressed", "true");
      paint();
      if (state.saveResponse) state.saveResponse(2, "role", role.key);
    });
    grid.append(btn);
  });
  roleCard.append(grid);
  host.append(roleCard);

  const solve = el("section", "card");
  solve.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 10px; font-size:1.3rem; color:#0f172a;">📝 Our group's work</h3>
       <p style="margin:0 0 12px; font-size:1rem; color:#475569;">Fill this in together. One answer for the group.</p>`,
    ),
  );
  // The same "I'm stuck" bar Part 1 offers, pointed at the problem on THIS page:
  // hint, first step, worked example, vocabulary, sentence starter, simpler
  // words, and the Socratic tutor. Passing no `problem` is deliberate — the bar
  // falls back to config.revealWordProblem, which IS what is being solved here.
  mountStuckSupport(solve, { config, state });
  solve.append(
    field(state, 2, "estimate", "🎯 Our estimate (before solving)", "We think it is about…", 2),
  );
  solve.append(field(state, 2, "work", "✏️ Our steps", "Step 1… Step 2… Step 3…", 5));
  solve.append(field(state, 2, "answer", "✅ Our answer", "Include the units.", 2));
  solve.append(
    field(
      state,
      2,
      "why",
      "🔍 How we know it is reasonable",
      "Compare it to the estimate, and to the problem.",
      3,
    ),
  );
  host.append(solve);

  const share = el("section", "card card-coral");
  share.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 10px; font-size:1.3rem; color:#0f172a;">🗣️ Share out</h3>
       <p style="margin:0 0 10px; font-size:1rem; color:#334155; line-height:1.55;">Presenter, read this to the class:</p>
       <p style="margin:0 0 12px; padding:12px 16px; background:#fff7ed; border-left:4px solid #ea580c; border-radius:10px; font-size:1.05rem; font-style:italic; color:#0f172a;">“Our group decided ___ . We know it is reasonable because ___ .”</p>`,
    ),
  );
  share.append(
    field(state, 2, "share", "Our share-out sentence", "Write it out so it is ready to read.", 3),
  );
  host.append(share);

  const sample = config.revealWordProblem && config.revealWordProblem.sampleAnswer;
  if (sample && isTeacherMode()) {
    const det = document.createElement("details");
    det.className = "card";
    det.innerHTML = `
      <summary style="cursor:pointer; font-weight:800; color:#0f766e;">👩‍🏫 Sample answer (teacher)</summary>
      <p style="margin:10px 0 0; font-size:1rem; line-height:1.6; color:#0f172a; white-space:pre-wrap;">${esc(sample)}</p>`;
    host.append(det);
  }

  const done = document.createElement("button");
  done.type = "button";
  done.className = "btn btn-primary";
  done.style.cssText =
    "margin:24px auto 8px; display:block; padding:14px 36px; font-weight:800; font-size:16px; border-radius:12px; background:#0f766e; color:#ffffff; cursor:pointer;";
  done.textContent = "We're done ✅";
  done.addEventListener("click", () => {
    state.markCompleted(2);
    done.textContent = "Saved ✅";
    done.disabled = true;
  });
  host.append(done);
}

/* ── Shared ───────────────────────────────────────────────────────────────── */

function advanceButton(label, state, ctx, phaseIdx) {
  const btn = document.createElement("button");
  btn.type = "button";
  btn.className = "btn btn-primary";
  btn.style.cssText =
    "margin:24px auto 8px; display:block; padding:14px 36px; font-weight:800; font-size:16px; border-radius:12px; background:#0f766e; color:#ffffff; box-shadow:0 4px 14px rgba(15,118,110,.25); cursor:pointer;";
  btn.textContent = label;
  btn.addEventListener("click", () => {
    state.markCompleted(phaseIdx);
    if (ctx && typeof ctx.nextPhase === "function") ctx.nextPhase();
  });
  return btn;
}

export function bootPartTwo(config) {
  ensureCanvasBridge(config);
  createApp({
    ...config,
    phaseMeta: [
      { name: "Review", icon: "🔁" },
      { name: "Today's Problem", icon: "📋" },
      { name: "Group Work", icon: "👥" },
    ],
    // Math Notes and Objectives belong to the review; the other two phases have
    // no takeover to offer, and a chip that opens nothing is worse than no chip.
    phaseSubtabs: {
      0: [
        { extra: "mathnotes", icon: "📓", label: "Math Notes" },
        { extra: "objectives", icon: "🎯", label: "Objectives" },
      ],
    },
    phases: [
      (host, state, ctx) => renderReview(host, state, ctx, config),
      (host, state, ctx) => renderProblem(host, state, ctx, config),
      (host, state, ctx) => renderGroups(host, state, ctx, config),
    ],
  });
  observeContentImageZoom(document.body);
}
