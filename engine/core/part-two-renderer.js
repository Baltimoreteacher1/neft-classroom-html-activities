/**
 * The Apply text ends with its task sentence ("Question: …" in the Reveal
 * decks). Splitting it out is the same treatment the slide deck gives it — the
 * scenario is the reading, the question is the job.
 */
function splitProblem(text) {
  const raw = String(text || "").trim();
  const at = raw.search(/(^|\n)\s*Question:\s*/i);
  if (at < 0) return { scenario: raw, question: "" };
  return {
    scenario: raw.slice(0, at).trim(),
    question: raw
      .slice(at)
      .replace(/(^|\n)\s*Question:\s*/i, "")
      .trim(),
  };
}

function renderProblem(host, state, ctx, config) {
  phaseHeading(
    host,
    2,
    "📋",
    "Today's Problem",
    "Read it twice. Then write what you know and what the problem is asking — before any arithmetic.",
  );

  const wp = config.revealWordProblem || {};
  const { scenario, question } = splitProblem(wp.text);

  const card = el("section", "card wp-card");
  card.append(
    el(
      "div",
      "wp-head",
      `<span class="wp-badge" aria-hidden="true">📋 Today</span>
       <h3 class="wp-title">${esc(wp.title || "Apply")}</h3>`,
    ),
  );

  if (scenario) {
    const p = el("p", "wp-text");
    p.setAttribute("data-annotate", "word-problem");
    p.textContent = scenario;
    card.append(p);
  }

  if (wp.image) {
    const fig = el("figure", "wp-figure");
    const img = document.createElement("img");
    img.className = "wp-img";
    img.setAttribute("loading", "lazy");
    img.setAttribute("decoding", "async");
    img.src = String(wp.image);
    img.alt = String(wp.imageAlt || wp.title || "Figure for today's problem");
    fig.append(img);
    attachImageZoom(img);
    card.append(fig);
  }

  if (question) {
    card.append(
      el(
        "div",
        null,
        `<p style="margin:14px 0 0; padding:12px 16px; background:#ecfeff; border-left:4px solid #0e7490; border-radius:10px; font-size:1.12rem; font-weight:700; color:#0f172a; line-height:1.5;">❓ ${esc(question)}</p>`,
      ),
    );
  }
  host.append(card);

  // AND IT HAS TO BE SOLVABLE WITH SOMETHING. Every interaction on this page
  // used to be answer entry, which is why the interaction-quality audit graded
  // all 66 of these pages D: "no manipulable representation". `config.tool` is
  // the core lesson's own model, carried here by generate-part-two.mjs, so the
  // student reaches for the thing they already know how to use. It sits above
  // the written work on purpose — you try it, then you write down what it told
  // you. Absent tool, absent section: pages without a model are unchanged.
  if (config.tool) {
    const toolCard = el("section", "card");
    toolCard.append(
      el(
        "div",
        null,
        `<h3 style="margin:0 0 4px; font-size:1.25rem; color:#0f172a;">🖌️ A reminder of how it works</h3>
         <p style="margin:0 0 12px; font-size:1rem; color:#475569;">The same tool from Part 1, so you can see how the math behaves before you solve today's problem on paper.</p>`,
      ),
    );
    const mount = document.createElement("div");
    mount.innerHTML = interactiveVisualHost(config.tool, {
      ariaLabel: `Interactive model for ${config.title || "today's problem"}`,
      fallback: "Turn on JavaScript to use this model. The steps below work on paper too.",
    });
    toolCard.append(mount);
    host.append(toolCard);
    // Hydrate only after the card is in the document — a component measured
    // while detached lays out at zero width.
    queueMicrotask(() => mountInteractiveVisuals(mount));
  }

  // THE PROBLEM HAS TO BE SOLVABLE HERE (Joel, 2026-08-26: "either guided steps
  // or space to solve it and work on it"). Reading it and then being sent to a
  // group left the one problem the day is built around with nowhere to do it.
  // These are the same guided moves Part 1's Show Your Work uses — know, need,
  // plan, work, answer, how-I-know — persisted on this phase.
  const think = el("section", "card");
  think.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 4px; font-size:1.25rem; color:#0f172a;">🧭 Solve it</h3>
       <p style="margin:0 0 12px; font-size:1rem; color:#475569;">Work through it on your own first. You will compare with your group next.</p>`,
    ),
  );
  // The same "I'm stuck" bar the rest of the engine offers, on the problem that
  // is on this screen — `config.revealWordProblem` IS what is being solved here.
  mountStuckSupport(think, { config, state });
  // Laid out ACROSS, not down (Joel, 2026-09-01: "the steps should line up next
  // to each other horizontally"). Stacked, the six moves read as six separate
  // assignments and the student meets them one screen-height apart; side by
  // side they read as one method, and KNOW sits next to NEED — which is exactly
  // what the phase heading tells them to do first. `auto-fit` + a 16rem floor
  // means the row count follows the screen instead of a guess, collapsing to a
  // single column on a phone with no separate mobile rule.
  const steps = el("div", "p2-solve-steps");
  steps.append(
    field(state, 1, "know", "1 · What I KNOW", "The numbers and facts the problem gives me…"),
  );
  steps.append(
    field(state, 1, "need", "2 · What I NEED to find", "What is the problem actually asking for?"),
  );
  steps.append(field(state, 1, "plan", "3 · My plan", "First I will… then I will…"));
  // My work is where the arithmetic actually goes, so it spans the full row
  // rather than being squeezed into a column — a six-row textarea at a third of
  // the width is not somewhere a student can show every step.
  const work = field(state, 1, "work", "4 · My work", "Show every step.", 6);
  work.classList.add("p2-solve-wide");
  steps.append(work);
  steps.append(field(state, 1, "answer", "5 · My answer", "Include the units.", 2));
  steps.append(
    field(state, 1, "why", "6 · How I know it is reasonable", "Compare it to an estimate.", 3),
  );
  think.append(steps);
  host.append(think);

  host.append(advanceButton("Break into groups 👥 →", state, ctx, 1));
}

/* ── Phase 2 · Group Work ─────────────────────────────────────────────────── */

function renderGroups(host, state, _ctx, config) {
  phaseHeading(
    host,
    3,
    "👥",
    "Group Work",
    "Work your table's problem set together, then bring today's problem back and agree on one answer.",
  );

  const solve = el("section", "card");
  solve.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 10px; font-size:1.3rem; color:#0f172a;">📝 Our group's work on today's problem</h3>
       <p style="margin:0 0 12px; font-size:1rem; color:#475569;">After your set: bring the Apply problem back together and agree on one answer.</p>`,
    ),
  );
  // The same "I'm stuck" bar Part 1 offers, pointed at the problem on THIS page:
  // hint, first step, worked example, vocabulary, sentence starter, simpler
  // words, and the Socratic tutor. Passing no `problem` is deliberate — the bar
  // falls back to config.revealWordProblem, which IS what is being solved here.
  mountStuckSupport(solve, { config, state });
  solve.append(
    field(state, 2, "estimate", "🎯 Our estimate (before solving)", "We think it is about…", 2),
  );
  solve.append(field(state, 2, "work", "✏️ Our steps", "Step 1… Step 2… Step 3…", 5));
  solve.append(field(state, 2, "answer", "✅ Our answer", "Include the units.", 2));
  solve.append(
    field(
      state,
      2,
      "why",
      "🔍 How we know it is reasonable",
      "Compare it to the estimate, and to the problem.",
      3,
    ),
  );
  host.append(solve);

  const share = el("section", "card card-coral");
  share.append(
    el(
      "div",
      null,
      `<h3 style="margin:0 0 10px; font-size:1.3rem; color:#0f172a;">🗣️ Share out</h3>
       <p style="margin:0 0 10px; font-size:1rem; color:#334155; line-height:1.55;">One person from your table reads this to the class:</p>
       <p style="margin:0 0 12px; padding:12px 16px; background:#fff7ed; border-left:4px solid #ea580c; border-radius:10px; font-size:1.05rem; font-style:italic; color:#0f172a;">“Our group decided ___ . We know it is reasonable because ___ .”</p>`,
    ),
  );
  share.append(
    field(state, 2, "share", "Our share-out sentence", "Write it out so it is ready to read.", 3),
  );
  host.append(share);

  // ── Leveled practice — AFTER the group solve, not before it ───────────────
  // Group Work is named for the collaborative problem, so the collaborative
  // problem leads; the leveled table sets (Joel: "Group work should be leveled
  // (with subcards) having different levels and different modifications /
  // problems included") are what a table does when its solve and share-out are
  // ready. They used to render first, which made this phase read as a second
  // worksheet with the actual group artifact seven screens down. Every problem
  // is AUTHORED — assembled by scripts/generate-part-two.mjs from the core
  // lesson and its own small-group variants. The MODIFICATION line under each
  // chip is what that table does differently, not a different subject.
  renderLevels(host, state, config);

  const sample = config.revealWordProblem && config.revealWordProblem.sampleAnswer;
  if (sample && isTeacherMode()) {
    const det = document.createElement("details");
    det.className = "card";
    det.innerHTML = `
      <summary style="cursor:pointer; font-weight:800; color:#0f766e;">👩‍🏫 Sample answer (teacher)</summary>
      <p style="margin:10px 0 0; font-size:1rem; line-height:1.6; color:#0f172a; white-space:pre-wrap;">${esc(sample)}</p>`;
    host.append(det);
  }

  const done = document.createElement("button");
  done.type = "button";
  done.className = "btn btn-primary";
  done.style.cssText =
    "margin:24px auto 8px; display:block; padding:14px 36px; font-weight:800; font-size:16px; border-radius:12px; background:#0f766e; color:#ffffff; cursor:pointer;";
  done.textContent = "We're done ✅";
  done.addEventListener("click", () => {
    state.markCompleted(2);
    done.textContent = "Saved ✅";
    done.disabled = true;
  });
  host.append(done);
}

