// Part 2 — the second day of an interactive lesson.
//
// WHAT THIS IS. Every Reveal lesson ends with an "Apply" word problem: the
// culminating, messiest, most real-world version of the day's mathematics,
// carrying the one figure the deck gives it. It used to be the last card of a
// 45-minute Part 1, which meant it landed with about four minutes left — the
// richest problem in the lesson, reliably rushed.
//
// Part 2 gives it its own day. The Apply problem is no longer rendered in Part 1
// (see renderShowYourWork in lesson-renderer.js); it is the whole point of this
// page. The shape Joel asked for is deliberately thin: a brief review of the
// notes and the objectives, the scenario, and then students break into groups.
//
//   Phase 0  🔁 Review          objectives + vocabulary + one quick check
//   Phase 1  📋 Today's Problem  the Apply scenario, its figure, know/need
//   Phase 2  👥 Group Work       four roles, a shared solve, a share-out
//
// It rides the SAME engine as Part 1 (createApp), so save/resume, teacher mode,
// learning supports, telemetry, language preference and the phase strip all work
// with no new machinery. The only engine additions it needed were
// `config.phaseMeta` and `config.phaseSubtabs` (engine/core/app.js), because a
// page whose phases are Review / Problem / Group Work must not label itself
// "Act 2: Lesson".
//
// Its config is generated by scripts/generate-part-two.mjs from the core
// lesson's config.json and carries `partTwo: true` plus the fields below. This
// file OWNS no lesson content — every string it renders comes from the core
// lesson.

