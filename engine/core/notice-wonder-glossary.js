export function normalizeAcademicWord(value) {
  return String(value ?? "")
    .toLowerCase()
    .replace(/[–—]/g, "-")
    .replace(/\s+/g, " ")
    .replace(/s$/, "")
    .trim();
}

const SHARED_ACADEMIC_WORDS = new Map(
  Object.entries(WORDS).map(([label, [definition, termEs, definitionEs]]) => [
    normalizeAcademicWord(label),
    Object.freeze({ definition, termEs, definitionEs }),
  ]),
);

export function resolveNoticeWonderAcademicWord(label, lessonVocabulary = []) {
  const key = normalizeAcademicWord(label);
  const authored = lessonVocabulary.find(
    (entry) =>
      normalizeAcademicWord(entry?.term) === key &&
      (entry?.definition || entry?.definitionEs || entry?.visual || entry?.example),
  );
  if (authored) return { ...authored, term: String(label) };
  const shared = SHARED_ACADEMIC_WORDS.get(key);
  return shared ? { term: String(label), ...shared } : null;
}
